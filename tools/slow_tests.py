"""Regenerate ``tests/slow_tests.txt``: the node ids that ``tests/conftest.py`` marks ``slow`` (D-409).

    uv run python tools/slow_tests.py <durations.log> [<durations.log> ...] [--threshold 2.0] [--write] [--prune]

Each log is the terminal output of a full run with ``--durations=0`` (``pytest ... --durations=0 > run.log``). A test
is listed when its **call** time is at least ``--threshold`` seconds in any of the given runs. Setup time is left out on
purpose: a session or module fixture is charged to whichever test happens to use it first, which depends on the run
order and the xdist distribution, so setup-based lists would change from run to run.

The list only grows unless ``--prune`` is given (an entry stays listed until a run shows it under the threshold and
the user asks to drop it), so repeated regenerations are stable. Without ``--write`` the tool prints what would change
and exits 1 when a test would be added.

``--shard-seconds`` (D-1020) instead rewrites ``tests/shard_seconds.txt``: each test file's measured seconds (call, setup
and teardown), by which ``tests/conftest.py`` balances the CI shards. Give it the logs of every shard of every leg of
one CI run (``--durations=0``; GitHub's timestamp prefix is accepted): a test's seconds are the mean over the logs that
time it, so each OS counts once. A log whose header names its profile (``agentprov shard i/n, profile P``, printed by
``tests/conftest.py``; D-1110) also feeds that profile's own ``[P]`` section, the mean over that OS's logs only, which a
shard run of that profile weighs by instead. A file the list lacks is weighed by its test count, so a stale list only
unbalances the shards; it never changes what runs.

The developer lane is ``pytest -n 10 -m "not slow"``. The merge gate never deselects anything, so this list changes how
long a quick check takes, never what the gate runs. Tests marked ``slow`` in their own file stay slow regardless.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LIST = REPO / "tests" / "slow_tests.txt"
HEADER = ("# Node ids marked `slow` by tests/conftest.py (generated by tools/slow_tests.py from --durations=0 call times;\n"
          "# do not edit by hand). `pytest -m \"not slow\"` skips them for a quick check; the full suite (the merge gate)\n"
          "# runs everything.\n")
DURATION = re.compile(r"^\s*(\d+(?:\.\d+)?)s call\s+(\S.*?)\s*$")


def call_times(paths: list[Path]) -> dict[str, float]:
    """Node id -> the longest call time over the logs (xdist's ``@group`` suffix removed)."""
    out: dict[str, float] = {}
    for path in paths:
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            m = DURATION.match(line)
            if m:
                nid = re.sub(r"@[\w-]+$", "", m.group(2))
                out[nid] = max(out.get(nid, 0.0), float(m.group(1)))
    return out


SHARD_SECONDS = REPO / "tests" / "shard_seconds.txt"
SHARD_HEADER = ("# Seconds per test file (call + setup + teardown, the mean over the OS legs of one CI run), by which\n"
                "# tests/conftest.py balances the CI shards (D-1020). Generated by tools/slow_tests.py --shard-seconds; do not\n"
                "# edit by hand. A [profile] section holds one OS's own mean, used by that OS's shards (D-1110).\n")
PHASE = re.compile(r"^(?:\S+Z )?\s*(\d+(?:\.\d+)?)s (?:call|setup|teardown)\s+(\S.*?)\s*$")
PROFILE = re.compile(r"^(?:\S+Z )?agentprov shard \d+/\d+, profile ([A-Za-z0-9][A-Za-z0-9_.-]*) ")


def file_seconds(paths: list[Path]) -> dict[str, float]:
    """Test file -> seconds: each test's phases summed per log, averaged over the logs that time it."""
    per_log: list[dict[str, float]] = []
    for path in paths:
        times: dict[str, float] = {}
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            m = PHASE.match(line)
            if m:
                nid = re.sub(r"@[\w-]+$", "", m.group(2))
                times[nid] = times.get(nid, 0.0) + float(m.group(1))
        per_log.append(times)
    out: dict[str, float] = {}
    for nid in set().union(*per_log):
        seen = [times[nid] for times in per_log if nid in times]
        path = nid.partition("::")[0]
        out[path] = out.get(path, 0.0) + sum(seen) / len(seen)
    return out


def log_profile(path: Path) -> str | None:
    """The profile a shard log's header names (``-`` is none), or None."""
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = PROFILE.match(line)
        if m:
            return None if m.group(1) == "-" else m.group(1)
    return None


def shard_sections(paths: list[Path]) -> dict[str, dict[str, float]]:
    """``""`` -> the mean over every log (:func:`file_seconds`); each profile the logs name -> the mean over its logs."""
    by_profile: dict[str, list[Path]] = {}
    for path in paths:
        profile = log_profile(path)
        if profile is not None:
            by_profile.setdefault(profile, []).append(path)
    return {"": file_seconds(paths)} | {profile: file_seconds(logs) for profile, logs in sorted(by_profile.items())}


def render_shard_seconds(sections: dict[str, dict[str, float]]) -> str:
    out = [SHARD_HEADER, *(f"{s:.1f} {f}\n" for f, s in sorted(sections[""].items()))]
    for profile in sorted(p for p in sections if p):
        out += [f"[{profile}]\n", *(f"{s:.1f} {f}\n" for f, s in sorted(sections[profile].items()))]
    return "".join(out)


def read_list(path: Path = LIST) -> set[str]:
    if not path.is_file():
        return set()
    return {line.strip() for line in path.read_text(encoding="utf-8").splitlines()
            if line.strip() and not line.startswith("#")}


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="slow_tests.py", description=__doc__.split("\n\n")[0])
    p.add_argument("logs", nargs="+", type=Path, help="terminal output of full runs with --durations=0")
    p.add_argument("--threshold", type=float, default=2.0, metavar="S", help="call seconds (default 2.0)")
    p.add_argument("--write", action="store_true", help="rewrite tests/slow_tests.txt")
    p.add_argument("--prune", action="store_true", help="also drop listed tests now measured under the threshold")
    p.add_argument("--shard-seconds", action="store_true",
                   help="rewrite tests/shard_seconds.txt from every shard log of one CI run instead (D-1020)")
    opts = p.parse_args(argv)
    if opts.shard_seconds:
        sections = shard_sections(opts.logs)
        seconds = sections[""]
        if not seconds:
            p.error("no '<seconds>s call|setup|teardown <node id>' lines found: run pytest with --durations=0")
        SHARD_SECONDS.write_text(render_shard_seconds(sections), encoding="utf-8")
        profiles = ", ".join(f"{p} {sum(v.values()):.0f} s" for p, v in sections.items() if p) or "none"
        print(f"{len(seconds)} test files, {sum(seconds.values()):.0f} s, written to {SHARD_SECONDS.relative_to(REPO)} "
              f"(profiles: {profiles})")
        return 0
    times = call_times(opts.logs)
    if not times:
        p.error("no '<seconds>s call <node id>' lines found: run pytest with --durations=0")
    measured = {nid for nid, t in times.items() if t >= opts.threshold}
    old = read_list()
    dropped = {nid for nid in old if nid in times and times[nid] < opts.threshold} if opts.prune else set()
    new = (old | measured) - dropped
    added = sorted(new - old)
    if opts.write:
        LIST.write_text(HEADER + "".join(f"{nid}\n" for nid in sorted(new)), encoding="utf-8")
        print(f"{len(new)} slow tests (threshold {opts.threshold:g} s call time; {len(added)} added, {len(dropped)} "
              f"dropped) written to {LIST.relative_to(REPO)}")
        return 0
    for nid in added:
        print(f"+ {nid}")
    for nid in sorted(dropped):
        print(f"- {nid}")
    print(f"{len(new)} slow tests at {opts.threshold:g} s call time; {len(added)} to add, {len(dropped)} to drop")
    return 1 if added or dropped else 0


if __name__ == "__main__":
    sys.exit(main())
