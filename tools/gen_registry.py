"""The source registry as one module per source and per family, with generated static lists (D-426).

Usage::

    uv run python tools/gen_registry.py --check     # test + merge train: exit 1 if a generated module is stale
    uv run python tools/gen_registry.py --write     # regenerate _sources.py and _factories.py
    uv run python tools/gen_registry.py --split     # one-time migration of registry/__init__.py (drained slot only)

**Why.** Every new source appended to the one ``REGISTRY`` tuple in ``adapters/registry/__init__.py``, and every new
family added lines to the shared ``READERS``/``MAPPERS`` dicts, so parallel branches conflicted there on almost every
merge. After the split, a new source is a new file and a new family is a new file; the two generated modules conflict
and are resolved by running ``--write``.

**Layout after the split** (``src/agentprov/adapters/registry/``)::

    __init__.py         public names, unchanged: REGISTRY, READERS, MAPPERS, BACKENDS, EXTERNAL_OWNERS, REGISTRY_DATE,
                        the dataclasses, get_source
    _model.py           the dataclasses and literals, the _phase10d helper, caveats shared by several sources
    sources/<id>.py     one SourceRegistration (``REGISTRATION``) with its own caveat constant
    families/<fam>.py   that family's READERS and MAPPERS entries (plain dict literals, read as data)
    _legacy_order.py    the order at the split, frozen; newer sources and factory keys sort after it
    _factories.py       GENERATED: READERS and MAPPERS, static literals
    _sources.py         GENERATED: explicit imports of every source module and the REGISTRY tuple

Nothing is discovered at runtime and nothing is loaded by name (no plugin loading; CLAUDE.md): ``_sources.py`` is a
static, committed list of imports, and a test checks that it is current. The family modules are never imported; the
generator reads their literals with ``ast.literal_eval``.

README.md's source tables (``tools/gen_readme_sources.py``) are generated from the same public values, so a split
leaves them unchanged; the migration runs its ``--check`` to show it. After the split, a new source or family
changes those tables too: run ``tools/gen_registry.py --write`` and then ``tools/gen_readme_sources.py --write``
(the merge train runs both, in that order).

``--split`` refuses unless the public names of the package have the same ``repr`` before and after (compared in
subprocesses), so ``agentprov info`` and every importer see identical values in identical order. The one visible
difference is the dataclasses' ``__module__`` (``agentprov.adapters.registry._model``); they are compared by name,
docstring and fields. Before the split,
``--check`` reports ``not migrated`` and passes.

Standard library only; no network.
"""

from __future__ import annotations

import argparse
import ast
import json
import keyword
import re
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _workflow import git_ok  # noqa: E402

PKG = Path("src/agentprov/adapters/registry")
INIT_NAMES = {"__all__", "REGISTRY_DATE", "BACKENDS", "EXTERNAL_OWNERS"}
FACTORY_NAMES = ("READERS", "MAPPERS")
MODEL_NAMES = {"Status", "Role", "Evidence"}
GENERATED_NOTE = "Generated by tools/gen_registry.py; do not edit. Resolve a conflict here by running ``--write``."
_FAMILY = re.compile(r"^agentprov\.adapters\.([a-z0-9_]+)\.")


def module_name(source_id: str) -> str:
    name = re.sub(r"\W", "_", source_id)
    if name[:1].isdigit() or keyword.iskeyword(name):
        name = "s_" + name
    return name


def family_of(factory: str) -> str:
    m = _FAMILY.match(factory)
    if not m:
        raise ValueError(f"factory {factory!r} is not agentprov.adapters.<family>.…")
    return m.group(1)


# --------------------------------------------------------------------------------------------------- generating


def _literal(path: Path, name: str) -> object:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.value is not None:
            target, value = node.target, node.value
        elif isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            target, value = node.targets[0], node.value
        else:
            continue
        if target.id == name:
            return ast.literal_eval(value)
    raise ValueError(f"{path.name}: no literal {name}")


def _names(path: Path, name: str) -> tuple[str, ...]:
    value = _literal(path, name)
    if not isinstance(value, tuple) or not all(isinstance(v, str) for v in value):
        raise ValueError(f"{path.name}: {name} is not a tuple of strings")
    return value


def _ordered(legacy: tuple[str, ...], present: set[str]) -> list[str]:
    missing = [n for n in legacy if n not in present]
    if missing:
        raise ValueError(f"legacy entries missing: {', '.join(missing[:5])} (a source is never deleted; its "
                         "status changes)")
    return [*legacy, *sorted(present - set(legacy))]


def generated(pkg: Path) -> dict[str, str]:
    """The text of ``_sources.py`` and ``_factories.py`` from the source, family and legacy-order modules."""
    legacy = pkg / "_legacy_order.py"
    order_sources = _names(legacy, "SOURCES")
    sources = {p.stem for p in (pkg / "sources").glob("*.py") if p.stem != "__init__"}
    names = _ordered(order_sources, sources)
    imports = "".join(f"from .sources import {n}\n" for n in names)
    entries = "".join(f"    {n}.REGISTRATION,\n" for n in names)
    src = (f'"""The registered sources, in order. {GENERATED_NOTE}"""\n\n'
           "from __future__ import annotations\n\nfrom typing import Final\n\n"
           f"from ._model import SourceRegistration\n{imports}\n"
           f"REGISTRY: Final[tuple[SourceRegistration, ...]] = (\n{entries})\n")
    factories: dict[str, dict[str, str]] = {k: {} for k in FACTORY_NAMES}
    for fam in sorted((pkg / "families").glob("*.py")):
        if fam.stem == "__init__":
            continue
        for kind in FACTORY_NAMES:
            part = _literal(fam, kind)
            if not isinstance(part, dict):
                raise ValueError(f"families/{fam.name}: {kind} is not a dict literal")
            for key, value in part.items():
                if key in factories[kind]:
                    raise ValueError(f"{kind}[{key!r}] is defined by two families")
                if family_of(value) != fam.stem:
                    raise ValueError(f"families/{fam.name}: {kind}[{key!r}] names another family's module")
                factories[kind][key] = value
    body = []
    for kind in FACTORY_NAMES:
        keys = _ordered(_names(legacy, kind), set(factories[kind]))
        items = "".join(f"        {json.dumps(k)}: {json.dumps(factories[kind][k])},\n" for k in keys)
        body.append(f"{kind}: Final[Mapping[str, str]] = MappingProxyType(\n    {{\n{items}    }}\n)\n")
    fac = (f'"""Reader and mapper factories by dialect, from ``families/*.py``. {GENERATED_NOTE}"""\n\n'
           "from __future__ import annotations\n\nfrom collections.abc import Mapping\nfrom types import "
           "MappingProxyType\nfrom typing import Final\n\n" + "".join(body))
    return {"_sources.py": src, "_factories.py": fac}


def migrated(pkg: Path) -> bool:
    return (pkg / "_legacy_order.py").is_file()


# --------------------------------------------------------------------------------------------------- the split


def _stmt_name(node: ast.stmt) -> str | None:
    if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
        return node.name
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        return node.target.id
    if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
        return node.targets[0].id
    return None


def _names_used(text: str) -> set[str]:
    return {n.id for n in ast.walk(ast.parse(text)) if isinstance(n, ast.Name)}


def _imports(text: str, available: dict[str, str]) -> str:
    """Import lines for the names ``text`` uses, grouped by module, from ``available`` (name -> module)."""
    used = _names_used(text) | set(re.findall(r"\b(Final|Literal|Mapping)\b", text))
    by_module: dict[str, list[str]] = {}
    for name in sorted(used & set(available)):
        by_module.setdefault(available[name], []).append(name)
    std = [m for m in by_module if not m.startswith(".")]
    local = [m for m in by_module if m.startswith(".")]
    lines = [f"from {m} import {', '.join(sorted(by_module[m]))}\n" for m in sorted(std)]
    if local:
        lines.append("\n")
        lines += [f"from {m} import {', '.join(sorted(by_module[m]))}\n" for m in sorted(local)]
    return "".join(lines)


def plan_split(text: str) -> dict[str, str]:
    """Every file of the split package (relative to the registry directory) from today's ``__init__.py`` text."""
    tree = ast.parse(text)
    lines = text.splitlines(keepends=True)
    std_imports: dict[str, str] = {}
    chunks: list[tuple[str | None, ast.stmt, str]] = []
    prev = 0
    for node in tree.body:
        chunk = "".join(lines[prev:node.end_lineno])
        prev = node.end_lineno or prev
        if isinstance(node, ast.ImportFrom) and node.module != "__future__":
            for alias in node.names:
                std_imports[alias.asname or alias.name] = node.module or ""
            continue
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            continue
        chunks.append((_stmt_name(node), node, chunk))
    if prev != len(lines) and "".join(lines[prev:]).strip():
        raise ValueError("text after the last statement")

    docstring = chunks[0][2] if isinstance(chunks[0][1], ast.Expr) else ""
    registry = next(node for name, node, _c in chunks if name == "REGISTRY")
    assert isinstance(registry, ast.AnnAssign | ast.Assign) and isinstance(registry.value, ast.Tuple)
    elements = registry.value.elts

    def source_id(elt: ast.expr) -> str:
        if not isinstance(elt, ast.Call):
            raise ValueError("a REGISTRY element that is not a call")
        for kw in elt.keywords:
            if kw.arg == "source_id" and isinstance(kw.value, ast.Constant):
                return str(kw.value.value)
        if elt.args and isinstance(elt.args[0], ast.Constant):
            return str(elt.args[0].value)
        raise ValueError("a REGISTRY element without a literal source id")

    uses: dict[str, list[int]] = {}
    for i, elt in enumerate(elements):
        for n in ast.walk(elt):
            if isinstance(n, ast.Name):
                uses.setdefault(n.id, []).append(i)

    init_parts: list[str] = []
    model_parts: list[str] = []
    per_source_caveats: dict[int, list[str]] = {i: [] for i in range(len(elements))}
    factory_literals: dict[str, dict[str, str]] = {}
    for name, node, chunk in chunks[1:] if docstring else chunks:
        if name == "REGISTRY":
            continue
        if name in INIT_NAMES or name == "get_source":
            init_parts.append(chunk)
        elif name in FACTORY_NAMES:
            assert isinstance(node, ast.AnnAssign | ast.Assign)
            call = node.value
            assert isinstance(call, ast.Call)
            factory_literals[name] = ast.literal_eval(call.args[0])
        elif name and name.endswith("_CAVEAT") and len(set(uses.get(name, []))) == 1:
            per_source_caveats[uses[name][0]].append(chunk)
        elif name in MODEL_NAMES or isinstance(node, (ast.ClassDef, ast.FunctionDef)) or (
                name and name.startswith("_")):
            model_parts.append(chunk)
        else:
            raise ValueError(f"top-level statement {name or type(node).__name__} has no place in the split")

    files: dict[str, str] = {}
    mod_names = [module_name(source_id(e)) for e in elements]
    if len(set(mod_names)) != len(mod_names):
        raise ValueError("two sources map to one module name")

    model_text = "".join(model_parts).lstrip("\n")
    model_defined = {n for n in (_stmt_name(s) for s in ast.parse(model_text).body) if n}
    local = {**{n: "._model" for n in model_defined}, **dict.fromkeys(FACTORY_NAMES, "._factories")}
    model_imports = _imports(model_text, {**std_imports, **{k: v for k, v in local.items() if v == "._factories"}})
    files["_model.py"] = ('"""Types, the phase-10d helper and shared caveats of the source registry (split from '
                          '``__init__.py`` by tools/gen_registry.py)."""\n\nfrom __future__ import annotations\n\n'
                          f"{model_imports}\n\n{model_text}")

    for i, elt in enumerate(elements):
        seg = ast.get_source_segment(text, elt)
        assert seg is not None
        start = elements[i - 1].end_lineno if i else registry.lineno
        between = lines[start:elt.lineno - 1]  # comments inside the tuple, before this element
        comments = "".join(textwrap.dedent("".join(ln for ln in between if ln.strip().startswith("#"))))
        caveats = "".join(per_source_caveats[i]).strip("\n")
        body = (f"{caveats}\n\n" if caveats else "") + comments + "REGISTRATION: Final = " + textwrap.dedent(
            "    " + seg)[0:] + "\n"
        rel = {k: ("." + v) for k, v in local.items()}  # sources/ is one level down
        files[f"sources/{mod_names[i]}.py"] = (
            f'"""Registry entry for ``{source_id(elt)}`` (one file per source; tools/gen_registry.py)."""\n\n'
            "from __future__ import annotations\n\n" + _imports(body, {**std_imports, **rel}) + "\n" + body)
    files["sources/__init__.py"] = '"""One module per registered source; listed by ``_sources.py`` (generated)."""\n'

    by_family: dict[str, dict[str, dict[str, str]]] = {}
    for kind, mapping in factory_literals.items():
        for key, value in mapping.items():
            by_family.setdefault(family_of(value), {k: {} for k in FACTORY_NAMES})[kind][key] = value
    for fam, parts in sorted(by_family.items()):
        body = "".join(f"{kind} = {{\n" + "".join(f"    {json.dumps(k)}: {json.dumps(v)},\n" for k, v in parts[kind]
                                                    .items()) + "}\n" for kind in FACTORY_NAMES)
        files[f"families/{fam}.py"] = (f'"""Reader and mapper factories of the ``{fam}`` family. Read as data by '
                                       'tools/gen_registry.py (never imported); merged into ``_factories.py``."""\n\n'
                                       + body)
    files["families/__init__.py"] = '"""Per-family factory literals; data for tools/gen_registry.py, never imported."""\n'
    files["_legacy_order.py"] = (
        '"""The registry order at the split, frozen (tools/gen_registry.py). Never edited: newer sources and factory '
        'keys sort after these."""\n\n'
        + "".join(f"{k}: tuple[str, ...] = (\n" + "".join(f"    {json.dumps(n)},\n" for n in v) + ")\n"
                  for k, v in (("SOURCES", mod_names), *((kind, list(factory_literals[kind])) for kind in FACTORY_NAMES))))

    init_text = "".join(init_parts).lstrip("\n")
    exported = ["BackendDescriptor", "Capability", "LicencePolicy", "SealedCorpus", "SourceRegistration"]
    init_imports = _imports(init_text, std_imports)
    files["__init__.py"] = (
        docstring + "\nfrom __future__ import annotations\n\n" + init_imports + "\n"
        f"from ._factories import MAPPERS, READERS\nfrom ._model import {', '.join(exported)}\n"
        "from ._sources import REGISTRY\n\n" + init_text)
    return files


SNAPSHOT = """
import dataclasses, importlib, json, sys
sys.path.insert(0, sys.argv[1])
m = importlib.import_module("agentprov.adapters.registry")
def describe(v):
    if isinstance(v, type):  # its __module__ becomes registry._model; compare what the class is instead
        return {"qualname": v.__qualname__, "doc": v.__doc__,
                "fields": [(f.name, str(f.type), "MISSING" if f.default is dataclasses.MISSING else repr(f.default),
                           f.default_factory is not dataclasses.MISSING) for f in dataclasses.fields(v)]}
    return repr(v)
print(json.dumps({"__all__": list(m.__all__), **{n: describe(getattr(m, n)) for n in m.__all__ if n != "get_source"},
                  "get_source": [repr(m.get_source(r.source_id)) == repr(r) for r in m.REGISTRY]}))
"""


def snapshot(src_root: Path) -> dict[str, object]:
    """The public names of ``agentprov.adapters.registry`` under ``src_root``, as reprs, from a fresh interpreter."""
    out = subprocess.run([sys.executable, "-c", SNAPSHOT, str(src_root)], capture_output=True, text=True, check=False)
    if out.returncode != 0:
        raise ValueError(f"importing the registry failed: {out.stderr.strip()[-1500:]}")
    return json.loads(out.stdout)


def isolated_copy(init_text: str, where: Path) -> Path:
    """A stub ``agentprov.adapters.registry`` holding ``init_text`` (the registry imports only the standard library)."""
    pkg = where / "agentprov" / "adapters" / "registry"
    pkg.mkdir(parents=True)
    (where / "agentprov" / "__init__.py").write_text("", encoding="utf-8")
    (where / "agentprov" / "adapters" / "__init__.py").write_text("", encoding="utf-8")
    (pkg / "__init__.py").write_text(init_text, encoding="utf-8")
    return where


def split(root: Path) -> list[str]:
    pkg = root / PKG
    if migrated(pkg) or (pkg / "sources").exists():
        raise ValueError("the registry is already split")
    original = (pkg / "__init__.py").read_text(encoding="utf-8")
    files = plan_split(original)
    with tempfile.TemporaryDirectory() as tmp:
        before = snapshot(isolated_copy(original, Path(tmp) / "before"))
        staged = Path(tmp) / "after"
        isolated_copy(original, staged)
        spkg = staged / "agentprov" / "adapters" / "registry"
        for rel, text in files.items():
            (spkg / rel).parent.mkdir(parents=True, exist_ok=True)
            (spkg / rel).write_text(text, encoding="utf-8")
        for rel, text in generated(spkg).items():
            (spkg / rel).write_text(text, encoding="utf-8")
        after = snapshot(staged)
    if before != after:
        diff = [k for k in before if before.get(k) != after.get(k)]
        raise ValueError(f"the split changes public names: {', '.join(diff)}; nothing written")
    written = []
    for rel, text in {**files, **generated_from(files)}.items():
        (pkg / rel).parent.mkdir(parents=True, exist_ok=True)
        (pkg / rel).write_text(text, encoding="utf-8")
        written.append(str(PKG / rel))
    return written


def generated_from(files: dict[str, str]) -> dict[str, str]:
    with tempfile.TemporaryDirectory() as tmp:
        pkg = Path(tmp)
        for rel, text in files.items():
            (pkg / rel).parent.mkdir(parents=True, exist_ok=True)
            (pkg / rel).write_text(text, encoding="utf-8")
        return generated(pkg)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(allow_abbrev=False, description=__doc__.split("\n\n")[0])
    p.add_argument("-C", dest="cwd", type=Path, default=Path.cwd())
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--split", action="store_true")
    a = p.parse_args(argv)
    top = git_ok(["rev-parse", "--show-toplevel"], a.cwd)
    root = Path(top) if top else a.cwd.resolve()
    pkg = root / PKG
    try:
        if a.split:
            for path in split(root):
                print(f"gen-registry: wrote {path}")
            return 0
        if not migrated(pkg):
            print("gen-registry: not migrated")
            return 0
        stale = []
        for rel, text in generated(pkg).items():
            target = pkg / rel
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                stale.append(rel)
                if a.write:
                    target.write_text(text, encoding="utf-8")
        for rel in stale:
            print(f"gen-registry: {'wrote' if a.write else 'stale'} {PKG / rel}")
        if not stale:
            print("gen-registry: current")
        return 1 if stale and a.check else 0
    except (ValueError, OSError, SyntaxError) as exc:
        print(f"gen-registry: {exc}")
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
