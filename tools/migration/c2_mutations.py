"""Gate C2's inputs (J.3.4 row C2): the 13 mutation variants of audit/validation.md §6.3 and the constraint probes a, b, c, e.

Standard library only: the same file is loaded by the baseline interpreter (``baseline_probe.py c2``, by path; the probe
runs with ``-I``) and by the AgentPROV comparer, so both sides validate the same documents.

* :data:`MUTATIONS` (name -> function): applied to a deep copy of a v2.3 compat PROV-JSON graph. Element ids are taken
  from the graph itself (its first entity, activity and agent in sorted id order), so a mutation applies to any sampled
  graph; a mutation whose precondition is missing (no ``adprov:content_len``, no agent) returns ``None`` (not
  applicable to this graph).
* :func:`three` and :data:`PROBES`: the audit's 3-call fixture transcript (``probe_edge_cases.three``) and the constraint
  probes of ``probe_constraints_fidelity.py`` built on its graph: (a) one entity generated by two activities at the same
  time, (b) ``wasInformedBy`` to an undeclared activity, (c) a ``wasDerivedFrom`` id equal to a ``used`` id, (e) a
  derivation whose generated entity precedes its source. Each side builds the fixture graph with its own builder.
"""

from __future__ import annotations

import copy
from collections.abc import Callable
from typing import Any

Doc = dict[str, Any]


def _first(doc: Doc, section: str) -> str | None:
    block = doc.get(section)
    return sorted(block)[0] if isinstance(block, dict) and block else None


def _with(doc: Doc, change: Callable[[Doc], bool | None]) -> Doc | None:
    out = copy.deepcopy(doc)
    return None if change(out) is False else out


def _set_used(value: Any) -> Callable[[Doc], Doc | None]:
    return lambda doc: _with(doc, lambda d: d.__setitem__("used", value))


def _extra_started_by(doc: Doc) -> Doc | None:
    act, ent = _first(doc, "activity"), _first(doc, "entity")
    if act is None or ent is None:
        return None
    return _with(doc, lambda d: d.__setitem__("wasStartedBy", {"adprov:ws_c2": {"prov:activity": act, "prov:trigger": ent}}))


def _typo_section(doc: Doc) -> Doc | None:
    act, ent = _first(doc, "activity"), _first(doc, "entity")
    if act is None or ent is None:
        return None
    return _with(doc, lambda d: d.__setitem__("wasGeneratedby", {"adprov:zz_c2": {"prov:entity": ent, "prov:activity": act}}))


def _foreign_prefix(doc: Doc) -> Doc | None:
    ent = _first(doc, "entity")
    if ent is None:
        return None

    def change(d: Doc) -> None:
        d.setdefault("prefix", {})["ex"] = "http://example.org/"
        d["entity"][ent]["ex:foo"] = "bar"
    return _with(doc, change)


def _unprefixed(doc: Doc) -> Doc | None:
    ent = _first(doc, "entity")
    return None if ent is None else _with(doc, lambda d: d["entity"][ent].__setitem__("foo", "bar"))


def _content_len_string(doc: Doc) -> Doc | None:
    block = doc.get("entity") if isinstance(doc.get("entity"), dict) else {}
    ent = next((k for k in sorted(block) if isinstance(block[k], dict) and isinstance(block[k].get("adprov:content_len"), int)), None)
    if ent is None:
        return None
    return _with(doc, lambda d: d["entity"][ent].__setitem__("adprov:content_len", str(d["entity"][ent]["adprov:content_len"])))


def _bundle(doc: Doc) -> Doc | None:
    return _with(doc, lambda d: d.__setitem__("bundle", {"adprov:b_c2": {"entity": {"adprov:zz_c2": {}}}}))


def _type_on_entity(doc: Doc) -> Doc | None:
    ent = _first(doc, "entity")
    return None if ent is None else _with(doc, lambda d: d["entity"][ent].__setitem__("prov:type", "adprov:Thing"))


def _agent_not_object(doc: Doc) -> Doc | None:
    agent = _first(doc, "agent")
    return None if agent is None else _with(doc, lambda d: d["agent"].__setitem__(agent, "notadict"))


def _agents_removed(doc: Doc) -> Doc | None:
    return None if _first(doc, "agent") is None else _with(doc, lambda d: d.__setitem__("agent", {}))


#: The 13 mutation variants of audit/validation.md §6.3, in the audit's order.
MUTATIONS: dict[str, Callable[[Doc], Doc | None]] = {
    "used=7": _set_used(7),
    "used=true": _set_used(True),
    "used=3.5": _set_used(3.5),
    "used=null": _set_used(None),
    "extra_wasStartedBy": _extra_started_by,
    "typo_wasGeneratedby": _typo_section,
    "foreign_prefix_attribute": _foreign_prefix,
    "unprefixed_attribute": _unprefixed,
    "content_len_string": _content_len_string,
    "bundle_section": _bundle,
    "prov_type_on_entity": _type_on_entity,
    "agent_attributes_not_object": _agent_not_object,
    "agents_removed": _agents_removed,
}


def _call(cid: str, fn: str) -> tuple[dict[str, Any], dict[str, Any]]:
    return ({"id": cid, "function": fn, "args": {}},
            {"role": "tool", "tool_call_id": cid, "function": fn, "args": {}, "content": "out", "error": None,
             "started_at": None, "ended_at": None})


def three() -> dict[str, Any]:
    """The audit's 3-call transcript (``probe_edge_cases.three``): built into a graph by each side's ``build_prov``."""
    turns: list[dict[str, Any]] = [{"role": "user", "content": "go"}]
    for i, (call, tool) in enumerate([_call("a", "get_webpage"), _call("b", "read_file"), _call("c", "send_email")]):
        tool["started_at"] = f"2026-01-01T00:00:0{2 * i}+00:00"
        tool["ended_at"] = f"2026-01-01T00:00:0{2 * i + 1}+00:00"
        turns += [{"role": "assistant", "text": "", "tool_calls": [call]}, tool]
    return {"meta": {}, "turns": turns}


def _probe_a(doc: Doc) -> Doc:
    d = copy.deepcopy(doc)
    first = sorted(d["wasGeneratedBy"])[0]
    d["wasGeneratedBy"]["adprov:wgb_x"] = {"prov:entity": "adprov:e_a", "prov:activity": "adprov:a_b",
                                         "prov:time": d["wasGeneratedBy"][first].get("prov:time")}
    return d


def _probe_b(doc: Doc) -> Doc:
    d = copy.deepcopy(doc)
    d.setdefault("wasInformedBy", {})["adprov:wib_x"] = {"prov:informed": "adprov:a_c", "prov:informant": "adprov:a_undeclared"}
    return d


def _probe_c(doc: Doc) -> Doc:
    d = copy.deepcopy(doc)
    shared = sorted(d.get("used") or {"adprov:u_00002": None})[0]
    d["wasDerivedFrom"] = {shared: {"prov:generatedEntity": "adprov:e_c", "prov:usedEntity": "adprov:e_a"}}
    return d


def _probe_e(doc: Doc) -> Doc:
    d = copy.deepcopy(doc)
    d["wasDerivedFrom"] = {"adprov:wdf_1": {"prov:generatedEntity": "adprov:e_a", "prov:usedEntity": "adprov:e_c"}}
    return d


#: The constraint probes a, b, c, e (``probe_constraints_fidelity.py``), applied to the graph of :func:`three`.
PROBES: dict[str, Callable[[Doc], Doc]] = {"probe_a": _probe_a, "probe_b": _probe_b, "probe_c": _probe_c, "probe_e": _probe_e}
