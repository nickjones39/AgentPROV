"""Generate the semantic-diff tables from ``src/agentprov/prov/compat/semdiff-map.toml`` (R-33; MN M.1.2 ``docs/compat/``).

    uv run python tools/gen_semdiff_tables.py            # write docs/compat/semantic-diff.md
    uv run python tools/gen_semdiff_tables.py --check    # exit 1 when the committed file is stale

The output holds the EF E.8.4 relations, nodes and attributes tables and the J.3.6 table, rendered from the map alone
(counts are the map's frozen counts and their sources; the measured counts are in the gate-E reports). The spec sections
keep their prose tables as written; ``tests/migration/test_semdiff_map.py`` checks that they agree with the map and lists
every known disagreement with the ruling the map follows.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
MAP = REPO / "src" / "agentprov" / "prov" / "compat" / "semdiff-map.toml"
OUT = REPO / "docs" / "compat" / "semantic-diff.md"

sys.path.insert(0, str(REPO / "src"))

from agentprov.migration.semdiff import MapRow, SemDiffMap, parse_map  # noqa: E402


def _n(value: int | None) -> str:
    return "—" if value is None else f"{value:,}"


def _count(row: MapRow) -> str:
    released, converted = row.frozen.get("released"), row.frozen.get("converted")
    if released is None and converted is None:
        text = row.frozen_note or "generated by the report"
    elif converted is None:
        text = f"{_n(released)} / — (converted: generated by the report)"
    else:
        text = f"{_n(released)} / {_n(converted)}"
    return text + (" (recompute: phase 13)" if row.recompute else "")


def _ids(ids: tuple[str, ...]) -> str:
    return ", ".join(f"`{i}`" for i in ids)


def _counterpart(row: MapRow) -> str:
    parts = [row.counterpart]
    if row.targets:
        parts.append(f"rules: {_ids(row.targets)}")
    if row.assumptions:
        parts.append(f"assumptions: {_ids(row.assumptions)}")
    if row.content_status:
        parts.append(f"content status `{row.content_status}`")
    return "; ".join(parts)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _section(semdiff_map: SemDiffMap, section: str, title: str) -> list[str]:
    lines = [
        f"### {title}",
        "",
        "| v2.3 element | Count (released / converted) | `agentprov-prov/0.1` counterpart | Disposition | Bundle | Class |",
        "|---|---|---|---|---|---|",
    ]
    for row in semdiff_map.rows:
        if row.section != section:
            continue
        lines.append(
            f"| {_cell(row.v23_element)} | {_cell(_count(row))} | {_cell(_counterpart(row))} | {row.disposition} | "
            f"{', '.join(row.bundle)} | {', '.join(row.evidence_class) or '—'} |"
        )
    return [*lines, ""]


def _j_table(semdiff_map: SemDiffMap) -> list[str]:
    groups: dict[str, list[MapRow]] = {}
    for row in semdiff_map.rows:
        if row.j is not None:
            groups.setdefault(row.j, []).append(row)
    lines = [
        "### J.3.6 table",
        "",
        "| v2.3 element | Release / converted count | Disposition | `agentprov-prov/0.1` counterpart |",
        "|---|---|---|---|",
    ]
    for label, rows in groups.items():
        counted = [r for r in rows if r.frozen]
        count = _count(counted[0]) if counted and len(rows) == 1 else "; ".join(f"{r.id}: {_count(r)}" for r in counted) or "—"
        dispositions = ", ".join(dict.fromkeys(r.disposition for r in rows))
        targets = tuple(dict.fromkeys(t for r in rows for t in r.targets))
        lines.append(f"| {_cell(label)} | {_cell(count)} | {dispositions} | {_ids(targets) or 'none'} |")
    return [*lines, ""]


def render(semdiff_map: SemDiffMap) -> str:
    lines = [
        "# Semantic diff: AgentDojo-PROV v2.3 (`adprov-v2.3-compat`) → `agentprov-prov/0.1`",
        "",
        "<!-- generated by tools/gen_semdiff_tables.py from src/agentprov/prov/compat/semdiff-map.toml; do not edit -->",
        "",
        f"Generated from `src/agentprov/prov/compat/semdiff-map.toml` (format `{semdiff_map.format}`, version "
        f"{semdiff_map.version}, sha256 `{semdiff_map.sha256}`), the one machine-readable semantic diff (R-33). The "
        "counts are the map's frozen counts (released / converted, with their sources in the map); the counts measured "
        "on the baseline trees, the R4 and R6 overlaps and the `new` counts are in the gate-E reports "
        "`migration/semdiff/semdiff-<tree>.json` (`agentprov migrate gate-e`). Dispositions use J's closed vocabulary: "
        "kept, reclassified, moved, replaced, moved-to-assessment, dropped, new. Bundle and class are those of the "
        "counterpart statements on the two v2.3 trees (v1 imports).",
        "",
        "## EF E.8.4",
        "",
        *_section(semdiff_map, "relation", "Relations"),
        *_section(semdiff_map, "node", "Nodes"),
        *_section(semdiff_map, "attribute", "Attributes"),
        "## J.3.6",
        "",
        *_j_table(semdiff_map),
        "## Notes",
        "",
    ]
    for row in semdiff_map.rows:
        if row.note:
            lines.append(f"- **{_cell(row.v23_element)}.** {row.note}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if docs/compat/semantic-diff.md is not current")
    args = parser.parse_args(argv)
    text = render(parse_map(MAP.read_bytes()))
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else None
        if current != text:
            print(f"{OUT.relative_to(REPO)} is stale: run uv run python tools/gen_semdiff_tables.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
