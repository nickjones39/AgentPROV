"""Generate the tool tables of the semantics profile ``agentdojo.suites`` (docs/architecture C.14; D.1 "Semantics profile").

    uv run python tools/agentdojo/gen_suite_tools.py \
        --git-dir-2024-06 ~/.agentprov/cache/git/github.com/ethz-spylab/agentdojo.git \
        --git-dir-head /path/to/AgentPROV-upstream/agentdojo/.git [--write]

Reads the AgentDojo source **as text and AST only** (never imported, never executed; D.13.1) through
``git --git-dir <dir> show <commit>:<path>``, so neither clone's checkout is touched, and writes
``src/agentprov/adapters/agentdojo/semantics/agentdojo.suites-1/suite_tools.toml``:

* ``2024-06``: the unversioned suites of the June-2024 code at ``c274885`` (``function_calling_pi``; the pin of the
  ``2024-06`` part of the ``agentdojo-upstream`` source profile). The suite registry is ``task_suites/__init__.py``
  ``SUITES``; each suite's ``TaskSuite(name, env, TOOLS)`` lists ``<function>.__name__`` values.
* ``head``: every suite version of the ``head`` pin ``089ed468`` (``agentdojo.task_suite.load_suites._SUITES``:
  ``v1`` … ``v1.2.2``). A versioned suite is either a v1 suite object or ``<v1 suite>.get_new_version(...)``, a deep
  copy that changes only ``benchmark_version`` (``task_suite.py``), so its tools are the v1 suite's ``TOOLS`` passed
  through ``make_function`` (which registers each function under its ``__name__``).

Every tool name is resolved through the module's imports (aliases included) to a top-level ``def`` of the defining
module, which the generator checks. The table header records the commits and every path read. Without ``--write`` the
script compares the generated bytes with the committed file and exits 1 on a difference (a check mode for review).
Prints names and paths only.
"""

from __future__ import annotations

import argparse
import ast
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "src" / "agentprov" / "adapters" / "agentdojo" / "semantics" / "agentdojo.suites-1" / "suite_tools.toml"
UPSTREAM = "https://github.com/ethz-spylab/agentdojo"
COMMIT_2024_06 = "c274885610efaaafec38b6d3eb07152ba7ff3f94"
COMMIT_HEAD = "089ed468cf3ed0322acc66b0211f26d9d90dbf60"


@dataclass
class Source:
    """One git object store read at one commit; ``paths`` records every file read, in reading order."""

    git_dir: Path
    commit: str
    paths: list[str] = field(default_factory=list)
    _cache: dict[str, ast.Module] = field(default_factory=dict)

    def exists(self, path: str) -> bool:
        proc = subprocess.run(["git", "--git-dir", str(self.git_dir), "cat-file", "-e", f"{self.commit}:{path}"],
                              capture_output=True, check=False)
        return proc.returncode == 0

    def module(self, path: str) -> ast.Module:
        if path not in self._cache:
            proc = subprocess.run(["git", "--git-dir", str(self.git_dir), "show", f"{self.commit}:{path}"],
                                  capture_output=True, check=True)
            self._cache[path] = ast.parse(proc.stdout.decode("utf-8"), filename=path)
            self.paths.append(path)
        return self._cache[path]


def module_path(src: Source, dotted: str) -> str:
    base = "src/" + dotted.replace(".", "/")
    for candidate in (f"{base}.py", f"{base}/__init__.py"):
        if src.exists(candidate):
            return candidate
    raise SystemExit(f"module {dotted} not found at {src.commit}")


def absolute(module_dotted: str, is_package: bool, imp: ast.ImportFrom) -> str:
    if imp.level == 0:
        return str(imp.module)
    parts = module_dotted.split(".")
    package = parts if is_package else parts[:-1]
    base = package[: len(package) - (imp.level - 1)]
    return ".".join(base + ([imp.module] if imp.module else []))


def dotted_of(path: str) -> tuple[str, bool]:
    stem = path.removeprefix("src/").removesuffix(".py")
    if stem.endswith("/__init__"):
        return stem.removesuffix("/__init__").replace("/", "."), True
    return stem.replace("/", "."), False


def _assigns(node: ast.stmt, name: str) -> bool:
    """``name = …`` or ``name: T = …`` at module level."""
    if isinstance(node, ast.Assign):
        return any(isinstance(t, ast.Name) and t.id == name for t in node.targets)
    return (isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.target.id == name
            and node.value is not None)


def resolve(src: Source, path: str, name: str) -> tuple[str, ast.AST]:
    """The module path and top-level node (``def``, ``Assign`` value) that ``name`` denotes in module ``path``."""
    tree = src.module(path)
    dotted, is_pkg = dotted_of(path)
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == name:
            return path, node
        if _assigns(node, name):
            assert isinstance(node, ast.Assign | ast.AnnAssign) and node.value is not None
            return path, node.value
        if isinstance(node, ast.ImportFrom):
            for alias in node.names:
                if (alias.asname or alias.name) == name:
                    return resolve(src, module_path(src, absolute(dotted, is_pkg, node)), alias.name)
    raise SystemExit(f"{name} is not defined in {path} at {src.commit}")


def tool_function(src: Source, path: str, node: ast.expr) -> str:
    """The registered tool name of one ``TOOLS`` element (``f`` or ``f.__name__``), checked against its ``def``."""
    if isinstance(node, ast.Attribute) and node.attr == "__name__":
        node = node.value
    if not isinstance(node, ast.Name):
        raise SystemExit(f"unexpected TOOLS element in {path}: {ast.dump(node)}")
    where, target = resolve(src, path, node.id)
    if not isinstance(target, ast.FunctionDef):
        raise SystemExit(f"{node.id} in {path} does not resolve to a function (at {where})")
    return target.name


def suite_tools(src: Source, path: str, var: str) -> tuple[str, list[str]]:
    """``(suite name, tool names)`` of the ``TaskSuite(...)`` object bound to ``var`` in module ``path``."""
    where, value = resolve(src, path, var)
    if not isinstance(value, ast.Call):
        raise SystemExit(f"{var} in {where} is not a TaskSuite(...) call")
    func = value.func.value if isinstance(value.func, ast.Subscript) else value.func
    if not (isinstance(func, ast.Name) and func.id == "TaskSuite"):
        raise SystemExit(f"{var} in {where} is not a TaskSuite(...) call")
    name_node, tools_node = value.args[0], value.args[2]
    if not (isinstance(name_node, ast.Constant) and isinstance(name_node.value, str)):
        raise SystemExit(f"suite name of {var} in {where} is not a literal")
    if isinstance(tools_node, ast.ListComp):  # [make_function(tool) for tool in TOOLS]
        tools_node = tools_node.generators[0].iter
    if not isinstance(tools_node, ast.Name):
        raise SystemExit(f"tools of {var} in {where} are not a module-level list")
    tools_where, tools_value = resolve(src, where, tools_node.id)
    if not isinstance(tools_value, ast.List):
        raise SystemExit(f"{tools_node.id} in {tools_where} is not a list literal")
    names = [tool_function(src, tools_where, element) for element in tools_value.elts]
    if len(set(names)) != len(names):
        raise SystemExit(f"duplicate tool names in {tools_where}")
    return name_node.value, sorted(names)


def dict_literal(node: ast.AST, where: str) -> list[tuple[str, ast.expr]]:
    if isinstance(node, ast.Call) and node.args:  # defaultdict(dict, {...})
        node = node.args[-1]
    if not isinstance(node, ast.Dict):
        raise SystemExit(f"expected a dict literal in {where}")
    out = []
    for key, value in zip(node.keys, node.values, strict=True):
        if not (isinstance(key, ast.Constant) and isinstance(key.value, str)):
            raise SystemExit(f"non-literal key in {where}")
        out.append((key.value, value))
    return out


def base_suite(src: Source, path: str, node: ast.expr) -> tuple[str, list[str]]:
    """A ``_SUITES`` value: a suite variable, or ``<suite>.get_new_version(...)`` (a deep copy with the same tools)."""
    if (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "get_new_version"):
        node = node.func.value
    if not isinstance(node, ast.Name):
        raise SystemExit(f"unexpected suite expression in {path}: {ast.dump(node)}")
    where, local = resolve_binding(src, path, node.id)
    return suite_tools(src, where, local)


def resolve_binding(src: Source, path: str, name: str) -> tuple[str, str]:
    """Follow imports of ``name`` from ``path`` to the module that assigns it; returns ``(module path, local name)``."""
    tree = src.module(path)
    dotted, is_pkg = dotted_of(path)
    for node in tree.body:
        if _assigns(node, name):
            return path, name
        if isinstance(node, ast.ImportFrom):
            for alias in node.names:
                if (alias.asname or alias.name) == name:
                    return resolve_binding(src, module_path(src, absolute(dotted, is_pkg, node)), alias.name)
    raise SystemExit(f"{name} is not bound in {path}")


def tables_2024_06(src: Source) -> dict[str, list[str]]:
    path = "src/function_calling_pi/task_suites/__init__.py"
    _, value = resolve(src, path, "SUITES")
    out: dict[str, list[str]] = {}
    for key, node in dict_literal(value, path):
        suite, tools = base_suite(src, path, node)
        if suite != key:
            raise SystemExit(f"SUITES[{key!r}] is the suite {suite!r}")
        out[key] = tools
    return dict(sorted(out.items()))


def tables_head(src: Source) -> dict[str, dict[str, list[str]]]:
    path = "src/agentdojo/task_suite/load_suites.py"
    _, registry = resolve(src, path, "_SUITES")
    out: dict[str, dict[str, list[str]]] = {}
    for label, table in dict_literal(registry, path):
        if not isinstance(table, ast.Name):
            raise SystemExit(f"_SUITES[{label!r}] is not a module-level dict")
        _, value = resolve(src, path, table.id)
        suites: dict[str, list[str]] = {}
        for key, node in dict_literal(value, path):
            suite, tools = base_suite(src, path, node)
            if suite != key:
                raise SystemExit(f"{table.id}[{key!r}] is the suite {suite!r}")
            suites[key] = tools
        out[label] = dict(sorted(suites.items()))
    return out


def _list(names: list[str]) -> str:
    return "[" + ", ".join(f'"{n}"' for n in names) + "]"


def render(june: Source, june_tables: dict[str, list[str]], head: Source,
           head_tables: dict[str, dict[str, list[str]]]) -> bytes:
    lines = [
        "# GENERATED by tools/agentdojo/gen_suite_tools.py from the AgentDojo source read as AST (git show <commit>:<path>);",
        "# do not edit by hand. Tool names per suite (sorted), per code state and per suite version. Data of the semantics",
        "# profile agentdojo.suites@1 (docs/architecture C.14); the selection rules are agentdojo.suite_tools_* in the",
        "# agentdojo catalogue. Upstream licence: MIT (c) 2024 Debenedetti et al.; only tool names are reproduced.",
        "",
        "[generator]",
        'script = "tools/agentdojo/gen_suite_tools.py"',
        "format = 1",
        "",
    ]
    for key, src, note in (
        ("2024-06", june, "unversioned suites of the June-2024 code (function_calling_pi); pin of agentdojo-upstream part 2024-06"),
        ("head", head, "suite versions v1 ... v1.2.2 of the head pin (agentdojo.task_suite.load_suites._SUITES)"),
    ):
        lines += [f'[sources."{key}"]', f'repo = "{UPSTREAM}"', f'commit = "{src.commit}"', f'note = "{note}"',
                  "paths = ["] + [f'  "{p}",' for p in src.paths] + ["]", ""]
    lines += ['[code_states."2024-06"]', 'source = "2024-06"', "", '[code_states."2024-06".suites]']
    lines += [f"{suite} = {_list(tools)}" for suite, tools in june_tables.items()]
    lines.append("")
    for label, suites in head_tables.items():
        lines += [f'[versions."{label}"]', 'source = "head"', "", f'[versions."{label}".suites]']
        lines += [f"{suite} = {_list(tools)}" for suite, tools in suites.items()]
        lines.append("")
    return ("\n".join(lines).rstrip("\n") + "\n").encode("utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--git-dir-2024-06", type=Path, required=True, help=f"a git object store holding {COMMIT_2024_06}")
    parser.add_argument("--git-dir-head", type=Path, required=True, help=f"a git object store holding {COMMIT_HEAD}")
    parser.add_argument("--write", action="store_true", help="write the table instead of checking it")
    args = parser.parse_args(argv)
    june = Source(args.git_dir_2024_06.expanduser(), COMMIT_2024_06)
    head = Source(args.git_dir_head.expanduser(), COMMIT_HEAD)
    data = render(june, tables_2024_06(june), head, tables_head(head))
    if args.write:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_bytes(data)
        print(f"wrote {OUT.relative_to(REPO)} ({len(data)} bytes)")
        return 0
    current = OUT.read_bytes() if OUT.is_file() else b""
    if current != data:
        print(f"{OUT.relative_to(REPO)} differs from the generated table; rerun with --write")
        return 1
    print(f"{OUT.relative_to(REPO)} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
