"""Build the AutoDojo cache variant-0 table of ``autodojo.payload_cache_link@1`` from the two pinned trees (D.6.13).

    uv run python tools/agentdojo/autodojo_cache_table.py [--cache DIR] [--check]

Reads, from the bare, extraction-free fetch cache (``git ls-tree`` / ``git cat-file --batch``, every blob checked
against its SHA-1; no checkout, no network):

* the 150 optimiser caches ``agentdojo/variant_generation/variants/<suite>/<provider>/<model>/<defence>/injections.json``
  of the AutoDojo pin (``cache_repo`` @ ``cache_commit`` of the ``autodojo-via-rope`` profile), and
* the 3 ``routed`` caches ``autodojo/variant_generation/variants/<suite>/openai/gpt-4o-mini/routed/injections.json`` of the
  ROPE pin (the ``rope`` profile's primary pin),

parses each with :func:`agentprov.ingest.loaders.strict_json_loads` (untrusted data), and writes
``src/agentprov/adapters/agentdojo/tables/autodojo_cache_variant0.json``: per ``(suite, injection task, vector)`` the
SHA-256 of ``yaml_escape(variants[0])`` (the exact bytes ``AutoDojoAttack`` writes into a log's ``injections``) with the
indices of the cells holding it. No payload text is written. ``--check`` compares with the shipped table instead and
prints its SHA-256 (the value the profile pins).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TABLE = REPO / "src" / "agentprov" / "adapters" / "agentdojo" / "tables" / "autodojo_cache_variant0.json"
AUTODOJO_PREFIX = "agentdojo/variant_generation/variants/"
ROPE_PREFIX = "autodojo/variant_generation/variants/"


def build(cache: str | None = None) -> bytes:
    from agentprov.adapters.agentdojo.hooks.autodojo import TABLE_FORMAT, yaml_escape
    from agentprov.adapters.profiles import load_profile
    from agentprov.ingest.limits import IngestLimits
    from agentprov.ingest.loaders import strict_json_loads
    from agentprov.raw.fetch import Fetcher, Recipe, resolve_cache_dir

    prov = load_profile("autodojo-via-rope").family_table()["attack_provenance"]
    rope = load_profile("rope").data["source"]
    pin = next(p for p in rope["pins"] if p.get("primary") is True)
    sources = {
        "autodojo": (str(prov["cache_repo"]), str(prov["cache_commit"]), AUTODOJO_PREFIX),
        "rope": (str(rope["canonical_repo"]), str(pin["commit"]), ROPE_PREFIX),
    }
    fetcher = Fetcher(resolve_cache_dir(cache))
    limits = IngestLimits()
    cells: list[dict[str, object]] = []
    entries: dict[str, list[tuple[str, str, str, str]]] = {}
    for key, (repo, commit, prefix) in sorted(sources.items()):
        recipe = Recipe(kind="git", role=key, primary=False, repo=repo, commit=commit, paths=(prefix,))
        tree, _skipped = fetcher.git_tree(recipe)
        chosen = [e for e in tree if e.is_blob and e.path.endswith("/injections.json")]
        for blob in fetcher.iter_git_blobs(recipe, chosen):
            cell = f"{key}:{blob.entry.path[len(prefix):-len('/injections.json')]}"
            doc = strict_json_loads(blob.data, limits)
            suite = doc.get("suite")
            if not isinstance(suite, str) or not isinstance(doc.get("injection_tasks"), dict):
                raise SystemExit(f"{cell}: not an AutoDojo cache (no suite or injection_tasks)")
            cells.append({"id": cell, "path": blob.entry.path, "blob": blob.entry.oid, "bytes": len(blob.data),
                          "suite": suite})
            rows: list[tuple[str, str, str, str]] = []
            for task, vectors in doc["injection_tasks"].items():
                for vector, entry in vectors.items():
                    variants = entry.get("variants") if isinstance(entry, dict) else None
                    if isinstance(variants, list) and variants and isinstance(variants[0], str):
                        digest = hashlib.sha256(yaml_escape(variants[0]).encode("utf-8")).hexdigest()
                        rows.append((suite, str(task), str(vector), digest))
            entries[cell] = rows
    cells.sort(key=lambda c: str(c["id"]))
    index = {str(c["id"]): i for i, c in enumerate(cells)}
    slots: dict[str, dict[str, list[int]]] = {}
    for cell, rows in entries.items():
        for suite, task, vector, digest in rows:
            slots.setdefault(f"{suite}|{task}|{vector}", {}).setdefault(digest, []).append(index[cell])
    for rows_ in slots.values():
        for idx in rows_.values():
            idx.sort()
    doc = {
        "format": TABLE_FORMAT,
        "description": "sha256(yaml_escape(variants[0])) per (suite|injection task|vector) of every AutoDojo optimiser "
                       "cache at the two pins, with the indices of the cells holding it (autodojo.payload_cache_link@1; "
                       "D.6.13). Generated by tools/agentdojo/autodojo_cache_table.py; no payload text.",
        "sources": {k: {"repo": r, "commit": c, "prefix": p} for k, (r, c, p) in sorted(sources.items())},
        "cells": cells,
        "slots": {k: dict(sorted(v.items())) for k, v in sorted(slots.items())},
    }
    return _dump(doc).encode("ascii")


def _dump(doc: dict[str, object]) -> str:
    """Sorted, ASCII JSON with one cell and one slot per line (stable diffs; ``json.loads``-equal to the document)."""
    def one(value: object) -> str:
        return json.dumps(value, sort_keys=True, ensure_ascii=True, separators=(",", ":"))

    lines = ["{"]
    keys = sorted(doc)
    for n, key in enumerate(keys):
        value = doc[key]
        end = "," if n < len(keys) - 1 else ""
        if isinstance(value, list):
            lines.append(f"{one(key)}:[")
            lines.extend(one(item) + ("," if i < len(value) - 1 else "") for i, item in enumerate(value))
            lines.append("]" + end)
        elif isinstance(value, dict) and key == "slots":
            lines.append(f"{one(key)}:{{")
            items = sorted(value.items())
            lines.extend(f"{one(k)}:{one(v)}" + ("," if i < len(items) - 1 else "") for i, (k, v) in enumerate(items))
            lines.append("}" + end)
        else:
            lines.append(f"{one(key)}:{one(value)}{end}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cache", default=None)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    data = build(args.cache)
    digest = hashlib.sha256(data).hexdigest()
    if args.check:
        same = TABLE.is_file() and TABLE.read_bytes() == data
        print(f"{'identical' if same else 'DIFFERS'} sha256 {digest}")
        return 0 if same else 1
    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_bytes(data)
    doc = json.loads(data)
    print(f"wrote {TABLE.relative_to(REPO)}: {len(doc['cells'])} cells, {len(doc['slots'])} slots, "
          f"{sum(len(v) for v in doc['slots'].values())} digest rows, sha256 {digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
