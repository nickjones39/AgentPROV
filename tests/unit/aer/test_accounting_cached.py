"""Regen item 67 (CA-8, C.12.2, C.20(1)): provider-reported counts do not count a cached call's assistant message.

A cache read answers the agent without inference, so it pairs with its assistant message in
``aer.acc.agent_calls_vs_assistant@1``, but it never reaches the provider. ``aer.acc.reported_counts@1`` compares the
reported call count with the assistant messages generated by held calls (plus emitted lost calls) only.
"""

from __future__ import annotations

from typing import Any

from aer_support import edit, example_records

from agentprov.aer.accounting import compute

SRC = [{"a": "a0", "p": "/messages/0"}]


def _reported(records: list[dict[str, Any]]) -> dict[str, Any]:
    return next(c for c in compute(records[1:]).checks if c["id"] == "aer.acc.reported_counts@1" and c["scope"] == "run")


def _kept_and_cached(calls: int) -> list[dict[str, Any]]:
    recs = edit(example_records(), "mc0", ev="O", by="capture", src=SRC, rule=None)
    recs = edit(recs, "mc1", ev="O", by="capture", src=SRC, rule=None, status="cached")
    return edit(recs, "run", usage={"calls": calls})


def test_a_cached_call_is_not_counted_against_the_reported_call_count() -> None:
    recs = _kept_and_cached(1)  # the provider saw only the kept call mc0
    entry = _reported(recs)
    assert entry["verdict"] == "consistent", entry
    assert entry["observed"] == {"assistant_messages": 1, "lost_calls": 0, "reported_calls": 1}
    assert compute(recs[1:]).status == "consistent"


def test_a_reported_count_that_includes_the_cached_call_is_inconsistent() -> None:
    entry = _reported(_kept_and_cached(2))
    assert entry["verdict"] == "inconsistent" and entry["reason"] == "reported_calls_differ", entry
    assert entry["observed"]["assistant_messages"] == 1


def test_kept_calls_only_are_unchanged() -> None:
    entry = _reported(edit(example_records(), "run", usage={"calls": 2}))
    assert entry["verdict"] == "consistent" and entry["observed"]["assistant_messages"] == 2
