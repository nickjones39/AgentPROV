"""The CI shards of ``tests/conftest.py`` (D-1020): ``AGENTPROV_SHARDS=n`` and ``AGENTPROV_SHARD=i`` keep the i-th of n
disjoint parts of the collected tests, so the parts of one ``ci.yml`` core leg run the whole suite between them."""

from __future__ import annotations

import importlib.util
import json
import os
import re
import subprocess
import sys
from pathlib import Path

import pytest
import yaml

REPO = Path(__file__).resolve().parents[3]
_spec = importlib.util.spec_from_file_location("agentprov_tests_conftest_shards", REPO / "tests" / "conftest.py")
assert _spec is not None and _spec.loader is not None
cf = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(cf)


def test_the_selection_reads_both_variables_and_refuses_a_bad_pair() -> None:
    assert cf.shard_selection({}) is None
    assert cf.shard_selection({"AGENTPROV_SHARD": "1", "AGENTPROV_SHARDS": "1"}) is None  # one shard is the whole suite
    assert cf.shard_selection({"AGENTPROV_SHARD": "2", "AGENTPROV_SHARDS": "3"}) == (2, 3)
    for index, count in (("0", "3"), ("4", "3"), ("", "3"), ("1", ""), ("one", "2"), ("-1", "2"), ("1", "0")):
        with pytest.raises(pytest.UsageError):
            cf.shard_selection({"AGENTPROV_SHARD": index, "AGENTPROV_SHARDS": count})


def test_a_test_never_sees_the_shard_variables() -> None:
    """The run takes them out of the environment, so a pytest that a test starts (pytester, a subprocess) collects its
    own tests whole (the first sharded trial failed eleven such tests)."""
    assert "AGENTPROV_SHARD" not in os.environ and "AGENTPROV_SHARDS" not in os.environ


def test_an_xdist_group_is_one_unit_and_any_other_file_is_its_own() -> None:
    for prefix, group in cf.XDIST_GROUPS:
        assert cf.shard_unit(prefix) == f"group:{group}"
    assert cf.shard_unit("tests/unit/test_cli.py") == "tests/unit/test_cli.py"
    pool_file = next(iter(cf.POOL_FILES))  # the host-sized pools groups are not shard units
    assert cf.shard_unit(pool_file) == pool_file


def test_the_assignment_is_deterministic_complete_and_balanced() -> None:
    weights = {f"tests/t{i}.py": float((i * 37) % 23 + 1) for i in range(60)} | {"group:serial": 40.0}
    for count in (1, 2, 3, 4, 7):
        shards = cf.assign_shards(weights, count)
        assert shards == cf.assign_shards(dict(reversed(list(weights.items()))), count)
        assert set(shards) == set(weights) and set(shards.values()) <= set(range(1, count + 1))
        loads = [sum(w for unit, w in weights.items() if shards[unit] == i) for i in range(1, count + 1)]
        # heaviest-first greedy: no shard exceeds the ideal share by more than the heaviest unit
        assert max(loads) <= sum(weights.values()) / count + max(weights.values())


def test_the_measured_seconds_parse_and_name_test_files() -> None:
    measured = cf._shard_seconds()
    assert len(measured) > 100  # tests/shard_seconds.txt, generated by tools/slow_tests.py --shard-seconds
    assert all(path.startswith("tests/") and path.endswith(".py") and seconds >= 0 for path, seconds in measured.items())


def test_the_generator_averages_each_test_over_the_legs_that_time_it(tmp_path: Path) -> None:
    sys.path.insert(0, str(REPO / "tools"))
    try:
        import slow_tests
    finally:
        sys.path.remove(str(REPO / "tools"))
    linux, windows = tmp_path / "linux.log", tmp_path / "windows.log"
    linux.write_text("2.00s call     tests/a.py::t1\n1.00s setup    tests/a.py::t1\n0.50s call     tests/b.py::t@serial\n",
                     encoding="utf-8")
    windows.write_text("2026-11-01T08:00:00.0Z 6.00s call     tests/a.py::t1\n2026-11-01T08:00:00.0Z 4.00s call     "
                       "tests/a.py::t2\n", encoding="utf-8")
    # t1: (3 + 6) / 2; t2 only on Windows; b's group suffix is dropped
    assert slow_tests.file_seconds([linux, windows]) == {"tests/a.py": 8.5, "tests/b.py": 0.5}


def _collect(env: dict[str, str]) -> subprocess.Popen[str]:
    return subprocess.Popen([sys.executable, "-m", "pytest", "--collect-only", "-q", "-p", "no:cacheprovider"],
                            cwd=REPO, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                            encoding="utf-8")


def _node_ids(run: subprocess.Popen[str]) -> list[str]:
    out, _ = run.communicate(timeout=900)
    assert run.returncode == 0, out[-4000:]
    return [line for line in out.splitlines() if "::" in line and not line[:1].isspace()]


@pytest.mark.slow  # collects the whole suite once per shard and once whole (about 15 s each, in parallel)
def test_the_shards_of_the_widest_ci_leg_are_disjoint_and_cover_every_collected_test() -> None:
    matrix = yaml.safe_load((REPO / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8"))
    include = matrix["jobs"]["core"]["strategy"]["matrix"]["include"]
    count = max(leg["shards"] for legs in re.findall(r"'(\[.*?\])'", include) for leg in json.loads(legs))
    assert count > 1
    base = {k: v for k, v in os.environ.items() if k not in ("AGENTPROV_SHARD", "AGENTPROV_SHARDS")}
    base["PYTHONDONTWRITEBYTECODE"] = "1"  # nothing written into the checkout
    whole = _collect(base)
    parts = [_collect(base | {"AGENTPROV_SHARD": str(i), "AGENTPROV_SHARDS": str(count)}) for i in range(1, count + 1)]
    everything = _node_ids(whole)
    shards = [_node_ids(run) for run in parts]
    assert len(everything) == len(set(everything)) > 1000
    assert all(shards), "every shard runs something"
    assert sum(len(ids) for ids in shards) == len(everything)  # disjoint ...
    assert set().union(*map(set, shards)) == set(everything)  # ... and complete
    for group in {group for _, group in cf.XDIST_GROUPS}:  # a group stays in one shard
        prefixes = tuple(prefix + "::" for prefix, g in cf.XDIST_GROUPS if g == group)
        holding = [i for i, ids in enumerate(shards) if any(nid.startswith(prefixes) for nid in ids)]
        assert len(holding) == 1, (group, holding)
    files = [{nid.partition("::")[0] for nid in ids} for ids in shards]
    assert sum(map(len, files)) == len(set().union(*files))  # a file stays in one shard
