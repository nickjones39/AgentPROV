def pool_group_count(environ: dict[str, str] | os._Environ[str] = os.environ, cpus: int | None = None) -> int:
    if environ.get("AGENTPROV_TEST_POOL_GROUPS"):
        return max(1, int(environ["AGENTPROV_TEST_POOL_GROUPS"]))
    return max(2, (cpus or os.cpu_count() or 1) // 6)


def assign_pool_groups(files: dict[str, float], k: int) -> dict[str, str]:
    """Longest first, each file to the least-loaded group (ties: the lower index): deterministic and balanced."""
    loads = [0.0] * k
    out: dict[str, str] = {}
    for path, seconds in sorted(files.items(), key=lambda kv: (-kv[1], kv[0])):
        i = min(range(k), key=lambda j: (loads[j], j))
        loads[i] += seconds
        out[path] = f"pools-{i + 1}"
    return out


POOL_GROUPS: dict[str, str] = assign_pool_groups(POOL_FILES, pool_group_count())


def _relpath(item: pytest.Item) -> str:
    path = Path(str(item.path)).resolve()
    return path.relative_to(REPO).as_posix() if path.is_relative_to(REPO) else path.as_posix()


def _group_for(relpath: str) -> str | None:
    for prefix, group in XDIST_GROUPS:
        if relpath == prefix or relpath.startswith(prefix.rstrip("/") + "/"):
            return group
    return POOL_GROUPS.get(relpath)


def _repo_nodeid(item: pytest.Item) -> str:
    """The node id relative to the repository, whatever the rootdir (``tests/x.py::Class::test[param]``)."""
    _, sep, rest = item.nodeid.partition("::")
    return _relpath(item) + sep + rest


def _slow_ids() -> frozenset[str]:
    """``tests/slow_tests.txt`` (generated by ``tools/slow_tests.py`` from measured timings; D-409)."""
    path = REPO / "tests" / "slow_tests.txt"
    if not path.is_file():
        return frozenset()
    return frozenset(line.strip() for line in path.read_text(encoding="utf-8").splitlines()
                     if line.strip() and not line.startswith("#"))


@pytest.hookimpl(tryfirst=True)  # before ``-m`` deselection and before xdist's worker hook (``@group`` node ids)
def pytest_collection_modifyitems(config: pytest.Config, items: list[pytest.Item]) -> None:
    slow = _slow_ids()
    for item in items:  # the developer lane: ``-m "not slow"``; the full suite deselects nothing
        if _repo_nodeid(item) in slow:
            item.add_marker(pytest.mark.slow)
    if not (hasattr(config, "workerinput") or config.getoption("dist", "no") != "no"):
        return  # not a distributed run
    for item in items:
        group = _group_for(_relpath(item))
        if group is not None:
            item.add_marker(pytest.mark.xdist_group(group))
