"""Shared pytest configuration for the core tests (docs/architecture K.3.4).

Only the pieces that exist so far: the escaped assertion output (K.3.4(8); R-42), the ``golden_index`` fixture, the
test-only registration of a retired source (``environmentoptim_registered``, D-901), and the parallel-run support of the
suite-perf proposals (D-400..D-409):

* **Hypothesis profiles** (D-405). ``HYPOTHESIS_PROFILE=gate`` (the default) is exactly the profile Hypothesis would
  load anyway (``default`` locally, its own ``ci`` profile under ``CI``), so the merge gate never gets weaker.
  ``HYPOTHESIS_PROFILE=dev`` lowers the *default* example count for targeted re-runs; tests that set their own
  ``max_examples`` keep it.
* **An isolated ``$AGENTPROV_HOME``** per test (and one per worker process for session fixtures), so no test writes the
  user's ``~/.agentprov`` and parallel workers never share one (D-402). The upstream fetch cache keeps its location
  (``$AGENTPROV_UPSTREAM_CACHE``, else the real home's ``cache``), read-only, so the pinned-tree tests still run.
* **A private ``$TMPDIR``** per test process (D-402): a fresh directory under the user's temporary directory, so a
  fixed file name in ``tempfile.gettempdir()`` never collides between xdist workers or with other sessions.
* **The write guard** (D-402). An audit hook fails a test that writes, renames, removes or changes the mode of an
  absolute path outside pytest's basetemp, the private ``$TMPDIR`` and the bytecode caches (``__pycache__``,
  ``sys.pycache_prefix``), so the repository checkout, ``~`` and the shared temporary directory are protected. The
  write is refused before it happens. ``AGENTPROV_TEST_WRITE_ALLOW=<path>[:<path>]`` (relative to the repository or
  absolute) adds files or directories a deliberate run may write, such as a regenerator's declared outputs.
  ``AGENTPROV_TEST_WRITE_GUARD=report`` records without refusing; ``off`` disables
  it. Relative paths are not checked: production code walks directories with ``dir_fd`` and the audit event does not
  carry the descriptor.
* **The ``slow`` lane** (D-409): the node ids in ``tests/slow_tests.txt`` (measured, regenerated by
  ``tools/slow_tests.py``) are marked ``slow``, so ``pytest -n 10 -m "not slow"`` is a quick check. The full suite, the
  merge gate, deselects nothing.
* **xdist groups** (D-401). Under ``pytest -n N``, the groups in :data:`XDIST_GROUPS` keep each listed set of tests on
  one worker: the load-sensitive and own-pool tests in one ``serial`` group, and the tests that start the host-default
  worker pools in k ``pools`` groups (:data:`POOL_FILES`; k = max(2, CPUs // 6), balanced by measured time), so at most
  k such pools run at once. ``--dist load`` (xdist's default for
  ``-n``) is turned into ``loadgroup``, in the controller and in every worker, because the groups are part of the
  gate's safety. A ``serial`` test never inherits a *failed* per-process calibration from an earlier test. Without
  xdist nothing changes except that last rule.
"""

