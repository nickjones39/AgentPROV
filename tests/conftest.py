# ------------------------------------------------------------------------------------------------ write guard
_GUARD_MODE = os.environ.get("AGENTPROV_TEST_WRITE_GUARD", "enforce")
_NO_DIR_FD = {None, -1, -100, getattr(os, "AT_FDCWD", -100)}
_WRITE_FLAGS = os.O_WRONLY | os.O_RDWR | os.O_CREAT | os.O_TRUNC | os.O_APPEND
# event -> ((index of a path argument, index of its dir_fd or None), ...)
_WATCHED: dict[str, tuple[tuple[int, int | None], ...]] = {
    "os.mkdir": ((0, 2),), "os.rename": ((0, 2), (1, 3)), "os.remove": ((0, 1),), "os.rmdir": ((0, 1),),
    "os.symlink": ((1, 2),), "os.link": ((1, 3),), "os.chmod": ((0, 2),), "os.chown": ((0, 3),),
    "os.utime": ((0, 3),), "os.truncate": ((0, None),), "shutil.rmtree": ((0, 1),), "shutil.copyfile": ((1, None),),
    "shutil.copytree": ((1, None),),
}
_EVENTS = frozenset(_WATCHED) | {"open"}
# events that act on the directory entry itself (a symlink there is removed, renamed or created, not followed): only
# their parent directory is resolved; every other write follows symlinks, so its full path is resolved (BF-3)
_ENTRY_EVENTS = frozenset({"os.mkdir", "os.rename", "os.remove", "os.rmdir", "os.symlink", "os.link", "shutil.rmtree",
                           "shutil.copytree"})


class _WriteGuard:
    def __init__(self) -> None:
        self.active: str | None = None  # the node id of the running test
        self.violations: list[str] = []
        self.allowed: tuple[str, ...] = ()
        self.allowed_files: tuple[str, ...] = ()  # "<file>." for the exact files of AGENTPROV_TEST_WRITE_ALLOW
        self.allowed_file_dirs: tuple[str, ...] = ()  # their ancestors, which a run may create (BF-4)

    def configure(self, basetemp: Path, private_tmp: Path | None) -> None:
        roots = {basetemp, Path("/dev"), REPO / ".hypothesis", REPO / ".pytest_cache"}
        if private_tmp is not None:
            roots.add(private_tmp)
        if sys.pycache_prefix:  # D-406: the interpreter's own bytecode cache, outside every source tree
            roots.add(Path(sys.pycache_prefix))
        forms = {os.path.join(os.path.abspath(r), "") for r in roots} | {os.path.join(os.path.realpath(r), "")
                                                                       for r in roots}
        # AGENTPROV_TEST_WRITE_ALLOW=<path>[:<path>]: files or directories a deliberate run may also write (a
        # regenerator's declared outputs), so the guard stays on for everything else. A file also admits its
        # "<file>.*" siblings, the temporaries of an atomic write (write "<file>.tmp", then replace "<file>").
        files: set[str] = set()
        for extra in filter(None, os.environ.get("AGENTPROV_TEST_WRITE_ALLOW", "").split(os.pathsep)):
            path = Path(extra) if os.path.isabs(extra) else REPO / extra
            forms |= {os.path.join(os.path.abspath(path), ""), os.path.join(os.path.realpath(path), "")}
            files |= {os.path.abspath(path), os.path.realpath(path)}
        self.allowed = tuple(sorted(forms))
        self.allowed_files = tuple(sorted(f + "." for f in files))
        self.allowed_file_dirs = tuple(sorted({os.path.join(a, "") for f in files for a in Path(f).parents}))

    def check(self, event: str, path: object, dir_fd: object) -> None:
        if isinstance(path, int) or path is None or dir_fd not in _NO_DIR_FD:
            return
        text = os.fsdecode(os.fspath(path))  # type: ignore[arg-type]
        if not os.path.isabs(text):
            return
        full = os.path.normpath(text)
        # the path the operation really touches (BF-3: a symlink inside a temporary directory must not let a write out)
        if event in _ENTRY_EVENTS:
            real = os.path.join(os.path.realpath(os.path.dirname(full)), os.path.basename(full))
        else:
            real = os.path.realpath(full)
        if (real + os.sep).startswith(self.allowed) or f"{os.sep}__pycache__{os.sep}" in real:
            return
        if self.allowed_files and real.startswith(self.allowed_files):  # "<allowed file>.<anything>"
            return
        if event == "os.mkdir" and (os.path.isdir(real) or (real + os.sep) in self.allowed_file_dirs):
            return  # BF-4: an existing directory changes nothing; an allowed file's missing parents may be created
        shown = full if real == full else f"{full} (really {real})"
        self.violations.append(f"{self.active}: {event} {shown}")
        if _GUARD_MODE == "enforce":
            raise PermissionError(f"write outside the test's temporary directories refused (D-402): {shown}")

    def hook(self, event: str, args: tuple[object, ...]) -> None:
        # one set lookup for the many unwatched events (imports, reads' ``open`` aside, sys._getframe, compile, ...)
        if event not in _EVENTS or self.active is None:
            return
        if event == "open":
            path, mode, flags = args
            writing = any(c in mode for c in "wax+") if isinstance(mode, str) else bool((flags or 0) & _WRITE_FLAGS)
            if writing:
                self.check(event, path, None)
            return
        spec = _WATCHED.get(event)
        if spec is not None:
            for pi, fi in spec:
                self.check(event, args[pi], None if fi is None else args[fi])


_GUARD = _WriteGuard()


_PRIVATE_TMP: Path | None = None


def _runs_tests(config: pytest.Config) -> bool:
    """False only in an xdist controller, which distributes the tests and runs none itself."""
    return hasattr(config, "workerinput") or getattr(config.option, "dist", "no") == "no"


@pytest.hookimpl(trylast=True)  # after the tmp_path plugin has made its factory and xdist has chosen ``dist``
def pytest_configure(config: pytest.Config) -> None:
    global _PRIVATE_TMP
    workerinput = getattr(config, "workerinput", None)
    if workerinput is None and getattr(config.option, "dist", "no") == "load":
        config.option.dist = "loadgroup"  # D-401: the groups are part of the gate's safety; read at session start
    if workerinput is not None and workerinput.get("agentprov_loadgroup"):
        config.option.loadgroup = True  # a worker re-parses the command line, where ``--dist`` may be absent
    if _runs_tests(config) and not config.getoption("collectonly"):
        # short (AF_UNIX paths are limited to 104 bytes on macOS), unique, and inherited by child processes
        _PRIVATE_TMP = Path(tempfile.mkdtemp(prefix="apt-"))
        os.environ["TMPDIR"] = str(_PRIVATE_TMP)
        tempfile.tempdir = str(_PRIVATE_TMP)
    if _GUARD_MODE != "off":
        _GUARD.configure(config._tmp_path_factory.getbasetemp(), _PRIVATE_TMP)  # type: ignore[attr-defined]
        sys.addaudithook(_GUARD.hook)  # inert outside a test (``active`` is None); a hook cannot be removed


@pytest.hookimpl(optionalhook=True)  # an xdist hook: tell each worker the controller's distribution mode
def pytest_configure_node(node: Any) -> None:  # xdist.workermanage.WorkerController
    node.workerinput["agentprov_loadgroup"] = node.config.getvalue("dist") == "loadgroup"


def pytest_unconfigure(config: pytest.Config) -> None:
    if _PRIVATE_TMP is not None:
        shutil.rmtree(_PRIVATE_TMP, ignore_errors=True)


@pytest.hookimpl(wrapper=True)
def pytest_runtest_protocol(item: pytest.Item, nextitem: pytest.Item | None) -> Iterator[None]:
    _GUARD.active = item.nodeid
    try:
        return (yield)
    finally:
        _GUARD.active = None


