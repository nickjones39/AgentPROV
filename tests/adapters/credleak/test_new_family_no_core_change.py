def test_the_branch_touches_only_the_family():
    changed = changed_or_skip(support.REPO)  # the merge base with origin/main or main, the newer
    if not any(p.startswith("src/agentprov/adapters/credleak/") for p in changed):
        pytest.skip("this branch does not change the credleak family")
    assert not [p for p in changed if p.startswith(PROTECTED) and p not in R_10K_1]
    assert [p for p in sorted(changed) if not any(fnmatch(p, g) for g in (*ALLOWED, *R_10K_1))] == []


def test_named_statements_and_gaps_of_one_run(mapped):
    """A fixture run with tool calls: each result is generated by its execution and the execution used the call (the
    co-located pair, class D); no model call, so agent messages have no generator (the named gap)."""
    import json

    entry = support.by_criterion("variant_tool_name")
    m = next(r for r in mapped[entry["path"]] if r.of("tool_execution"))
    prov = json.loads(m.prov.prov_json)
    text = json.dumps(prov)
    assert m.of("model_call") == [] and "wasGeneratedBy" in text and "used" in text
