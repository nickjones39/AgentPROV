"""Fixtures and helpers for the FooBench adapter tests (docs/architecture D.12, K.6.4).

The fixture is generated by ``tools/gen_foobench_fixture.py`` into ``tests/fixtures/foobench/`` (a primary file, the
hand-off's second file and the screenshot blob). It is synthetic and self-authored; tests read it programmatically.

The core finds the ``foobench`` profile and rule catalogue by convention (package data), and the hand-off's second file
reaches the mapper through ``map_unit(auxiliary=...)``; nothing in the core names FooBench (DoD Q.3).
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Callable
from dataclasses import dataclass
from importlib import resources
from pathlib import Path
from typing import Any

import pytest

from agentprov.adapters.foobench.dialect import FooJsonlReader
from agentprov.adapters.foobench.mapper import FooMapper
from agentprov.adapters.profiles import SourceProfile, load_profile
from agentprov.adapters.runner import MapOutcome, aer_bytes, map_unit
from agentprov.adapters.types import ArtefactRef, ExecutionUnit, Origin
from agentprov.aer.rules import RuleRegistry
from agentprov.aer.validate import AerValidator, ValidationReport
from agentprov.aer.writer import SealInfo
from agentprov.ingest.limits import IngestLimits

REPO = Path(__file__).resolve().parents[3]
FIXTURES = REPO / "tests" / "fixtures" / "foobench"
PRIMARY = "trace-001.jsonl"
SUB = "sub-trace-001.jsonl"
PNG = "screenshot-0.png"
PACKAGE = "agentprov.adapters.foobench"
#: Stand-in origin of the generated fixture (a pinned git origin is the cheapest one the release-mode writer accepts).
BASE_COMMIT = "ce45a3d560629e2ec6fa9633315eb1afa187891c"
LIMITS = IngestLimits()


def blob_sha1(data: bytes) -> str:
    return hashlib.sha1(b"blob %d\0" % len(data) + data, usedforsecurity=False).hexdigest()


def origin_of(name: str, data: bytes) -> Origin:
    return Origin.git("https://github.com/nickjones39/AgentPROV", BASE_COMMIT, f"tests/fixtures/foobench/{name}", blob_sha1(data))


def artefact(art_id: str, name: str, data: bytes, role: str = "primary") -> ArtefactRef:
    return ArtefactRef(art_id, hashlib.sha256(data).hexdigest(), len(data), "application/x-ndjson", origin_of(name, data),
                       role, "native")  # type: ignore[arg-type]


def profile_bytes() -> bytes:
    return (resources.files(PACKAGE) / "profiles" / "foobench.profile.toml").read_bytes()


def profile() -> SourceProfile:
    return load_profile("foobench")


def registry() -> RuleRegistry:
    """Every catalogue the package ships, autoloaded (``aer`` and ``foobench``)."""
    return RuleRegistry.default()


class _Store:
    """In-memory ``RawStore``: raw artefacts and the screenshot blob, by digest."""

    def __init__(self, *objects: bytes) -> None:
        self.objects = {hashlib.sha256(o).hexdigest(): o for o in objects}

    def has(self, sha256: str) -> bool:
        return sha256 in self.objects

    def size(self, sha256: str) -> int:
        return len(self.objects[sha256])

    def read_bytes(self, sha256: str) -> bytes:
        return self.objects[sha256]


@dataclass
class Mapped:
    primary: bytes
    sub: bytes | None
    outcome: MapOutcome
    data: bytes
    info: SealInfo
    png: bytes

    @property
    def records(self) -> list[dict[str, Any]]:
        return [json.loads(line) for line in self.data.splitlines()]

    def by_id(self) -> dict[str, dict[str, Any]]:
        return {r["id"]: r for r in self.records}

    def of_kind(self, kind: str) -> list[dict[str, Any]]:
        return [r for r in self.records if r["k"] == kind]

    @property
    def issues(self) -> list[dict[str, Any]]:
        return list(self.records[-1]["issues"])

    def issue_codes(self) -> list[str]:
        return [i["code"] for i in self.issues]

    def store(self) -> _Store:
        return _Store(self.primary, *([self.sub] if self.sub else []), self.png)

    def validate(self, mode: str = "release") -> ValidationReport:
        prof = profile()
        validator = AerValidator(store=self.store(), catalogues=registry(), mode=mode,  # type: ignore[arg-type]
                                 profile_digests={(prof.id, prof.version): prof.sha256})
        for line in self.data.splitlines(keepends=True):
            validator.feed(line)
        return validator.finish()


def unit_of(primary: bytes, sub: bytes | None, *, label: str = SUB) -> ExecutionUnit:
    ref = artefact("a0", PRIMARY, primary)
    (item,) = list(FooJsonlReader().parse(primary, ref, limits=LIMITS))
    aux = {label: artefact("a1", label, sub, "supporting")} if sub is not None else {}
    return ExecutionUnit(primary=item, auxiliary=aux)


def map_foo(primary: bytes | None = None, sub: bytes | None | str = "fixture", *, label: str = SUB) -> Mapped:
    """Parse and map the fixture (or the given bytes) in process and seal it. ``sub="fixture"`` reads the fixture's file."""
    primary = primary if primary is not None else (FIXTURES / PRIMARY).read_bytes()
    sub_bytes = (FIXTURES / SUB).read_bytes() if sub == "fixture" else sub
    assert sub_bytes is None or isinstance(sub_bytes, bytes)
    unit = unit_of(primary, sub_bytes, label=label)
    png = (FIXTURES / PNG).read_bytes()
    # The screenshot blob is supplied as ``blob:<hex>`` bytes, as the raw store would (the capture family's contract),
    # so the mapper checks the declared size against it; it is also in the store the validator reads (AER-V21).
    aux = {f"blob:{hashlib.sha256(png).hexdigest()}": png, **({label: sub_bytes} if sub_bytes is not None else {})}
    outcome = map_unit(unit, FooMapper(), profile(), registry=registry(), auxiliary=aux)
    data, info = aer_bytes(outcome, registry=registry(), unit=unit, mapper=FooMapper(), profile=profile())
    return Mapped(primary, sub_bytes, outcome, data, info, png)


def events_of(raw: bytes) -> list[dict[str, Any]]:
    return [json.loads(line) for line in raw.splitlines()]


def lines_of(events: list[dict[str, Any]]) -> bytes:
    return b"".join(json.dumps(e, separators=(",", ":")).encode() + b"\n" for e in events)


class FooTools:
    """The helpers above, handed to tests as one fixture (``--import-mode=importlib`` forbids importing conftest)."""

    FIXTURES = FIXTURES
    PRIMARY = PRIMARY
    SUB = SUB
    PNG = PNG
    LIMITS = LIMITS
    profile = staticmethod(profile)
    profile_bytes = staticmethod(profile_bytes)
    registry = staticmethod(registry)
    map: Callable[..., Mapped] = staticmethod(map_foo)
    unit = staticmethod(unit_of)
    artefact = staticmethod(artefact)
    events = staticmethod(events_of)
    lines = staticmethod(lines_of)
    Store = _Store

    @staticmethod
    def raw(name: str) -> bytes:
        return (FIXTURES / name).read_bytes()


@pytest.fixture(scope="session")
def foo() -> type[FooTools]:
    return FooTools


@pytest.fixture(scope="module")
def mapped() -> Mapped:
    """The fixture, mapped once per test module."""
    return map_foo()
