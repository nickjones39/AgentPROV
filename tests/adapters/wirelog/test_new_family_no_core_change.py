"""The new-family test for the wire-log family (docs/architecture D.20.12; the D.12.3 analogue; K.6.4; invariant 5).

The adding branch changes only the family's files, its tests and fixtures, the registry entry and documentation: nothing
under aer/, prov/, validate/ or corpus/.
"""

from __future__ import annotations

import sys
from fnmatch import fnmatch
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from new_family_guard import changed_or_skip  # noqa: E402
import wirelog_support as support

ALLOWED = (
    "src/agentprov/adapters/wirelog/*", "tests/adapters/wirelog/*", "tests/fixtures/wirelog/*",
    "tests/fixtures/LICENSES/WhatSurrounds-*", "src/agentprov/adapters/registry/__init__.py", "docs/*", "AGENTS.md",
    "tests/adapters/runner/test_per_unit_inputs.py",  # the list of families with per-unit inputs
    "tests/adapters/runner/test_job_failure_degenerate.py",  # the job-failure contract per family (D-219 pin)
    "README.md",  # the family and source table, generated by tools/gen_readme_sources.py
    # the same branch adds the mcphunt family (phase 10m part B)
    "src/agentprov/adapters/mcphunt/*", "tests/adapters/mcphunt/*", "tests/fixtures/mcphunt/*",
)
PROTECTED = ("src/agentprov/aer/", "src/agentprov/prov/", "src/agentprov/validate/", "src/agentprov/corpus/")




def test_the_branch_touches_only_the_family():
    changed = changed_or_skip(support.REPO)  # the merge base with origin/main or main, the newer
    if not any(p.startswith("src/agentprov/adapters/wirelog/") for p in changed):
        pytest.skip("this branch does not change the wirelog family")
    assert [p for p in changed if p.startswith(PROTECTED)] == []
    assert [p for p in sorted(changed) if not any(fnmatch(p, g) for g in ALLOWED)] == []
