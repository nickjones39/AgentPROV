"""Regen item 74 (CA-16): the v1 importer keeps every meta member it can, or rejects the file (C.15.3 Import direction).

Before the fix the ``adprov.transcript_v1`` mapper stored ``meta.source``/``timing_stubbed``/``run_error``/
``pipeline_name`` only for the converted variant, turned an explicit-null or non-list ``finish_reasons`` into a list
(or rejected it), ignored a non-object ``usage`` and declared a converted ``model_config.temperature`` unknown. Each case
changed the regenerated bytes with no seal issue. Now each shape round-trips byte-identically (gate A2) and validates,
except a non-object ``usage``, which is malformed (a degenerate outcome). Documents are built in code (conftest).
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Any

import pytest


def _set(member: str, value: Any) -> Callable[[dict[str, Any]], None]:
    return lambda meta: meta.__setitem__(member, value)


def _set_mc(member: str, value: Any) -> Callable[[dict[str, Any]], None]:
    return lambda meta: meta["model_config"].__setitem__(member, value)


RELEASED_CASES = {
    "run_error": _set("run_error", "x"),
    "source": _set("source", "x"),
    "timing_stubbed": _set("timing_stubbed", False),
    "pipeline_name": _set("pipeline_name", "p"),
    "pipeline_name_null": _set("pipeline_name", None),
    "finish_reasons_null": _set_mc("finish_reasons", None),
    "finish_reasons_string": _set_mc("finish_reasons", "stop"),
    "finish_reasons_object": _set_mc("finish_reasons", {"0": "stop"}),
    "finish_reasons_number": _set_mc("finish_reasons", 2),
}


def _gate(v1, doc: dict[str, Any]) -> None:
    raw = v1.dump(doc)
    m = v1.map(raw)
    assert not m.outcome.degenerate, m.outcome.error_code
    assert m.view_bytes() == raw, "A2: the regenerated v1 bytes differ from the source"
    report = m.validate()
    assert report.ok, sorted({f.code + " " + f.pointer for f in report.errors})


@pytest.mark.parametrize("name", sorted(RELEASED_CASES))
def test_released_member_round_trips(v1, name: str) -> None:
    doc = v1.released()
    RELEASED_CASES[name](doc["meta"])
    _gate(v1, doc)


def test_converted_temperature_round_trips(v1) -> None:
    doc = v1.converted()
    items = list(doc["meta"].items())
    slot = [k for k, _ in items].index("benchmark_version") + 1  # the J.3.2 layout slot of model_config
    doc["meta"] = dict(items[:slot] + [("model_config", {"temperature": 0.0})] + items[slot:])
    _gate(v1, doc)
    agent = v1.map(v1.dump(doc)).by_id()["agent"]
    assert agent["params"] == {"temperature": 0.0} and "/params" not in agent["unk"]


@pytest.mark.parametrize("usage", [[1], "x", 3])
def test_non_object_usage_is_malformed(v1, usage: Any) -> None:
    doc = v1.released()
    doc["meta"]["model_config"]["usage"] = usage
    m = v1.map(v1.dump(doc))
    assert m.outcome.degenerate, "a non-object usage was mapped as if absent"


def test_null_usage_still_round_trips(v1) -> None:
    doc = v1.released()
    doc["meta"]["model_config"]["usage"] = None
    _gate(v1, doc)
