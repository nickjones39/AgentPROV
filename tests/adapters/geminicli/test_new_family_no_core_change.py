"""The new-family test for the gemini-cli streams (docs/architecture D.23.11; the D.12.3 analogue; K.6.4).

The adding branch changes only the family's files, its tests and fixtures, its tools, the registry entry (append only),
the two runner tests that list the families (per-unit inputs; the D-219 job-failure contract), and documentation. Nothing under aer/, prov/,
validate/, corpus/, runner/, raw/ or ingest/ (invariant 5).
"""

from __future__ import annotations

import sys
from fnmatch import fnmatch
from pathlib import Path

import geminicli_support as support
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from new_family_guard import changed_or_skip  # noqa: E402

ALLOWED = (
    "src/agentprov/adapters/geminicli/*", "tests/adapters/geminicli/*", "tests/fixtures/geminicli/*", "tools/geminicli/*",
    "src/agentprov/adapters/registry/__init__.py", "tests/adapters/runner/test_per_unit_inputs.py",
    "tests/adapters/runner/test_job_failure_degenerate.py", "docs/*", "AGENTS.md",
    # the info-table width check now names the longest label, not the survey's (orchestrator-approved, 2026-10-14)
    "tests/adapters/agentdojo/test_survey.py",
    "README.md",  # the family and source tables, regenerated by tools/gen_readme_sources.py
    "tests/unit/test_d31_bumps.py",  # D-609: the profile's version 1 pinned as recorded (D-31)
    "corpora/datasheet-statements.toml",  # D-609: the known-issue disclosure of the withheld harness patches
    "tests/unit/corpus/test_datasheet.py",  # D-609: the disclosure's row test
    "tools/readme_corpora.toml",  # D-609: the README corpus row's withholding note
)
PROTECTED = ("src/agentprov/aer/", "src/agentprov/prov/", "src/agentprov/validate/", "src/agentprov/corpus/",
             "src/agentprov/adapters/runner/", "src/agentprov/raw/", "src/agentprov/ingest/")




def test_the_branch_touches_only_the_family():
    changed = changed_or_skip(support.REPO)  # the merge base with origin/main or main, the newer
    if not any(p.startswith("src/agentprov/adapters/geminicli/") for p in changed):
        pytest.skip("this branch does not change the geminicli family")
    assert [p for p in changed if p.startswith(PROTECTED)] == []
    assert [p for p in sorted(changed) if not any(fnmatch(p, g) for g in ALLOWED)] == []
