def _execute(sc: Scenario, session_dir: Path, backend: AutoDojoBackend) -> CaptureSession:
    session_dir.mkdir(parents=True)
    if sc.cell.get("attack") == "autodojo":
        (session_dir / AUTODOJO_CACHE_LABEL).parent.mkdir(parents=True)
        (session_dir / AUTODOJO_CACHE_LABEL).write_bytes(autodojo_cache_bytes())
    agent = AgentConfig.from_json(sc.agent)
    session = CaptureSession(session_dir, redactor=build_redactor({}, agent))
    transport = ScriptedTransport([step_from_dict(s) for s in sc.steps], model=sc.agent["model_requested"])
    result = backend.execute(CellSpec.from_json(sc.cell), agent, session, backend_config=sc.backend_config,
                             inner_transport=transport, environ={}, plan_sha256=None, attack_env=dict(sc.attack_env))
    if result.status != sc.expect_status:
        raise SystemExit(f"{sc.name}: status {result.status}, expected {sc.expect_status}")
    if transport.remaining:
        raise SystemExit(f"{sc.name}: {transport.remaining} scripted steps unused")
    return session


def _kill(session_dir: Path) -> None:
    """The forced-kill session: a real worker, SIGKILL once the stalled request is recorded, parent terminal event."""
    from agentprov_capture.log import append_terminal

    session_dir.mkdir(parents=True)
    (session_dir / "script.json").write_text(json.dumps(list(AUTODOJO_KILL_SCRIPT)))
    sc = AUTODOJO_SCENARIOS["autodojo_banking_important_instructions"]
    from agentprov_backend.session import uuid7

    session = uuid7()
    msgs = [{"v": PROTOCOL, "op": "hello", "nonce": "fixture"},
            {"v": PROTOCOL, "op": "run_cell", "req": 1, "cell": dict(sc.cell), "agent": dict(sc.agent),
             "session": {"ex": "ex_" + session, "attempt": 0, "dir": str(session_dir)}, "plan_sha256": None,
             "attack_env": {}}]
    home = session_dir.parent / "t2home"
    home.mkdir()
    env = {"PATH": "/usr/bin:/bin", "HOME": str(home), "LANG": "C.UTF-8", "TZ": "UTC", "AGENTPROV_BLOCK_NETWORK": "1"}
    proc = subprocess.Popen([sys.executable, "-I", "-B", "-m", "agentprov_backend.worker"], stdin=subprocess.PIPE,
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, cwd=session_dir, env=env)
    log = session_dir / f"raw/capture/{session}.capture.jsonl"
    try:
        assert proc.stdin is not None
        proc.stdin.write("".join(json.dumps(m) + "\n" for m in msgs).encode())
        proc.stdin.flush()
        deadline = time.monotonic() + 300
        # the request event and its header note are written before the inner transport stalls
        while not (log.is_file() and b'"kind":"wire_headers"' in log.read_bytes()):
            if time.monotonic() > deadline or proc.poll() is not None:
                raise SystemExit(f"{KILL}: the worker did not reach the stalled request")
            threading.Event().wait(0.05)
    finally:
        proc.send_signal(signal.SIGKILL)
        proc.wait(timeout=60)
    (session_dir / "script.json").unlink()      # written by the parent; kept beside the session, not in it
    shutil.rmtree(home)
    if append_terminal(log, "aborted") is None:
        raise SystemExit(f"{KILL}: the parent could not append the terminal event")


def _files(root: Path) -> list[Path]:
    return sorted(p for p in root.rglob("*") if p.is_file() and p.name != "SOURCE.json")


def write_fixture(name: str, description: str, session_dir: Path, steps: Any, run_cell: dict[str, Any],
                  dest_root: Path) -> None:
    dest = dest_root / name
    if dest.exists():
        shutil.rmtree(dest)
    (dest / "session").mkdir(parents=True)
    shutil.copytree(session_dir / "raw", dest / "session" / "raw")
    (dest / "script.json").write_text(json.dumps(list(steps), indent=2) + "\n", encoding="utf-8")
    (dest / "run_cell.json").write_text(json.dumps(run_cell, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    entries = []
    for p in _files(dest):
        data = p.read_bytes()
        entries.append({
            "sample_file": p.relative_to(dest).as_posix(),
            "url": None,
            "repository": "https://github.com/nickjones39/AgentPROV",
            "commit_or_revision": None,
            "original_path": "backends/autodojo/tools/make_capture_fixtures.py",
            "sha256": hashlib.sha256(data).hexdigest(),
            "size_bytes": len(data),
            "licence": LICENCE,
            "licence_class": "permissive",
            "synthetic": True,
            "retrieved_at": None,
            "note": f"scenario {name}: {description}. Synthetic scripted-transport capture (test_only) of the AutoDojo "
                    "fork aa458794; UUIDv7, times, chain hashes and digests change on regeneration.",
        })
    (dest / "SOURCE.json").write_text(json.dumps(entries, indent=2) + "\n", encoding="utf-8")


def projection(scenario_dir: Path) -> Any:
    (log,) = sorted((scenario_dir / "session" / "raw" / "capture").glob("*.capture.jsonl"))
    events = []
    for line in log.read_bytes().splitlines():
        e = json.loads(line)
        data = dict(e["data"])
        if e["type"] == "session.start":
            data.pop("session"), data.pop("ex"), data.pop("runtime")
        if e["type"] == "note" and data.get("kind") == "identity_digests":
            data = {**data, "payload": {k: v for k, v in data["payload"].items()
                                        if k not in ("python", "platform", "lock_sha256", "lock_source")}}
        if e["type"] == "native.log":
            data = {}
        if e["type"] == "error":
            data.pop("traceback", None)
            # the traceback blob holds interpreter paths, so its digest depends on where the environment lives
            data["redactions"] = [{k: v for k, v in r.items() if k != "blob"} for r in data.get("redactions", [])]
        events.append((e["seq"], e["type"], e["pass"], e["actor"], data))
    natives = sorted((scenario_dir / "session" / "raw" / "capture").glob("*.native.json"))
    nat = [{k: v for k, v in json.loads(n.read_bytes()).items() if k not in ("evaluation_timestamp", "duration")}
           for n in natives]
    return [events, nat]


def _tree_digest(root: Path) -> str:
    """sha256 over the relative paths and bytes of a package's ``.py`` and ``.toml`` files (no caches)."""
    h = hashlib.sha256()
    for path in sorted(p for p in root.rglob("*") if p.is_file() and p.suffix in (".py", ".toml")
                       and "__pycache__" not in p.parts):
        h.update(path.relative_to(root).as_posix().encode() + b"\0" + path.read_bytes() + b"\0")
    return h.hexdigest()


def check_installed_harness(project: str) -> None:
    """Refuse to generate fixtures with a harness other than this checkout's (review R3-3): an isolated (``-I``)
    interpreter of this environment imports the installed, non-editable ``agentprov_backend`` and
    ``agentprov_capture``, which must equal ``backends/shared/src`` and ``capture/src``."""
    probe = ("import os, agentprov_backend, agentprov_capture; "
             "print(os.path.dirname(agentprov_backend.__file__)); print(os.path.dirname(agentprov_capture.__file__))")
    out = subprocess.run([sys.executable, "-I", "-c", probe], capture_output=True, text=True, check=True).stdout.split()
    pairs = ((Path(out[0]), REPO / "backends" / "shared" / "src" / "agentprov_backend"),
             (Path(out[1]), REPO / "capture" / "src" / "agentprov_capture"))
    stale = [src.name for installed, src in pairs if _tree_digest(installed) != _tree_digest(src)]
    if stale:
        raise SystemExit(f"the installed {', '.join(stale)} differ from this checkout's source; run: uv sync --offline "
                         f"--project {project} --reinstall-package agentprov-backend --reinstall-package agentprov-capture")


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--check", action="store_true", help="regenerate into a temporary directory and compare projections")
    ap.add_argument("--only", nargs="*", default=None)
    args = ap.parse_args(argv)
    check_installed_harness("backends/autodojo")
    netguard.install()
    time.sleep = lambda s: None  # retry back-off of the SDK / the fork never changes what is sent
    backend = AutoDojoBackend()
    names = args.only or [*AUTODOJO_SCENARIOS, KILL]
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / "work"
        target = Path(tmp) / "out" if args.check else args.out
        for name in names:
            if name == KILL:
                sdir = work / name / "session"
                _kill(sdir)
                sc = AUTODOJO_SCENARIOS["autodojo_banking_important_instructions"]
                run_cell = {"cell": dict(sc.cell), "agent": dict(sc.agent), "attack_env": {}}
                write_fixture(name, KILL_DESCRIPTION, sdir, AUTODOJO_KILL_SCRIPT, run_cell, target)
            else:
                sc = AUTODOJO_SCENARIOS[name]
                session = _execute(sc, work / name / "session", backend)
                run_cell = {"cell": dict(sc.cell), "agent": dict(sc.agent), "attack_env": dict(sc.attack_env)}
                write_fixture(name, sc.description, session.dir, sc.steps, run_cell, target)
            print(f"{name}: {sum(p.stat().st_size for p in _files(target / name))} bytes")  # noqa: T201
        if args.check:
            stale = [n for n in names
                     if json.dumps(projection(target / n), sort_keys=True)
                     != json.dumps(projection(args.out / n), sort_keys=True)]
            for n in stale:
                print(f"stale: {n}")  # noqa: T201
            return 1 if stale else 0
    (args.out / "README.md").write_text(README, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
