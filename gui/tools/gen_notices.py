"""Generate ``gui/THIRD_PARTY_NOTICES.md``: the licences of everything a GUI bundle ships (G5; design §13).

    uv run --project gui python gui/tools/gen_notices.py [--check]

The packages are the runtime closure of ``agentprov-gui`` in ``gui/uv.lock`` (dev tools such as PyInstaller, pytest,
ruff and mypy are not shipped). Each licence comes from the installed distribution's own metadata
(``License-Expression``, else ``License``, else the ``License ::`` classifiers), never from memory. Qt and PySide6 get
the LGPLv3 statement of design §13 (dynamic linking, the licence texts in ``packaging/licenses/``, how to replace the
libraries, where the corresponding source is). ``--check`` fails when the file is out of date (a test runs it).
"""

from __future__ import annotations

import argparse
import importlib.metadata as md
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / "THIRD_PARTY_NOTICES.md"
FIRST_PARTY = {"agentprov", "agentprov-capture", "agentprov-gui"}
LGPL_QT = """\
## Qt and PySide6 (LGPLv3)

The bundle contains Qt {qt} and PySide6 / Shiboken6 {pyside} from The Qt Company, used under the **GNU Lesser General
Public License v3** (`LGPL-3.0-only`). The full texts are in `licenses/LGPL-3.0.txt` and `licenses/GPL-3.0.txt`
(LGPLv3 incorporates GPLv3).

- Qt is **linked dynamically**: its libraries are separate files in the bundle (`Contents/Frameworks/` on macOS, the
  `_internal` folder elsewhere), never linked statically, and they are not modified.
- **You may replace them** with your own build of the same Qt and PySide6 versions, or a compatible later version, by
  replacing those files. The one-folder layout makes this possible. On macOS, re-sign the bundle afterwards (an ad-hoc
  signature, `codesign --force --deep -s -`, is enough for your own Mac).
- **Corresponding source:** Qt {qt} at https://download.qt.io/official_releases/qt/ and https://code.qt.io/, and
  PySide6/Shiboken6 {pyside} at https://download.qt.io/official_releases/QtForPython/ and https://code.qt.io/pyside/pyside-setup.
  On request, the project maintainers provide the exact sources used for a given bundle.
"""


def runtime_closure(lock: dict, root: str = "agentprov-gui") -> list[str]:
    """Package names reachable from ``root`` through ``dependencies`` (not ``dev-dependencies``)."""
    packages = {p["name"]: p for p in lock["package"]}
    seen: set[str] = set()
    stack = [root]
    while stack:
        name = stack.pop()
        if name in seen or name not in packages:
            continue
        seen.add(name)
        stack += [d["name"] for d in packages[name].get("dependencies", [])]
    return sorted(seen - FIRST_PARTY)


def licence_of(name: str) -> str:
    try:
        meta = md.metadata(name)
    except md.PackageNotFoundError:
        return "not installed on this platform (see its project page)"
    expr = meta.get("License-Expression")
    if expr:
        return expr.strip()
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    lic = (meta.get("License") or "").strip()
    if lic and len(lic) <= 80 and "\n" not in lic:
        return lic + (f" ({'; '.join(classifiers)})" if classifiers else "")
    return "; ".join(classifiers) or (lic.splitlines()[0][:80] if lic else "see the package")


def render(lock: dict) -> str:
    names = runtime_closure(lock)
    versions = {p["name"]: p["version"] for p in lock["package"]}
    rows = [f"| {n} | {versions.get(n, '')} | {licence_of(n)} |" for n in names]
    qt = versions.get("pyside6-essentials", "?")
    return "\n".join([
        "# Third-party notices: AgentPROV desktop GUI bundles",
        "",
        "Generated by `gui/tools/gen_notices.py` from `gui/uv.lock` and the packages' own metadata. The AgentPROV core",
        "(MIT) and its notices are in the repository's `THIRD_PARTY_NOTICES.md`. Graphviz is not bundled.",
        "",
        LGPL_QT.format(qt=qt, pyside=qt),
        "## Python packages in the bundle",
        "",
        "Some packages are platform-specific (for example SecretStorage on Linux, pywin32-ctypes on Windows, PyObjC on",
        "macOS); a bundle contains only those of its platform. The Python runtime itself is PSF-2.0.",
        "",
        "| package | version | licence (from its metadata) |",
        "|---|---|---|",
        *rows,
        "",
    ])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when the notices file is out of date")
    args = ap.parse_args(argv)
    text = render(tomllib.loads((HERE / "uv.lock").read_text(encoding="utf-8")))
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("gen_notices: gui/THIRD_PARTY_NOTICES.md is out of date; run gui/tools/gen_notices.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"gen_notices: wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
