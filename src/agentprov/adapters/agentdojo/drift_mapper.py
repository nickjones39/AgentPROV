"""The DRIFT build of the ``agentdojo.tracelogger`` mapper: ``drift.k18.*`` run logs -> AER ``aer/0.1`` (docs/architecture
D.6.19; D-270..D-279; ``docs/reports/phase10l/``).

DRIFT's ``pipeline_main.py`` (SaFo-Lab/DRIFT) writes one JSON object per run with the DRIFT key set ``KD18_BASE`` and the
message list under ``conversations`` (DRIFT itself, AgentDyn's vendored copy, Figshare 32657856, drift-1) or ``messages``
(AgentDyn variant C, re-keyed). :class:`DriftBuild` maps both variants, in the D.6.5 record order of the generic mapper:
the ``execution`` header, the actors, the ``run`` and ``att0`` scopes, no fixtures (DRIFT writes no ``injections``), the
messages with the activities that generate them, and the two judgements. What differs from the generic AgentDojo build:

- **Defence-authored structures** (D-273, D-274). A ``user`` message in the ``</function_error>`` wrapper holding
  ``[CALL ERROR]`` is the validator's refusal of the preceding assistant turn (whose ``tool_calls`` DRIFT emptied): a
  ``decision`` (verdict ``deny``, subject that message) and the message ``generated_by`` it. The last tool message of each
  call batch passed DRIFT's isolation step (``DRIFTLLM.injection_isolate`` reads and edits ``messages[-1]`` only), so it
  gets an execution, then a ``decision`` (verdict ``other``, subtype ``drift.isolation_pass``, the original
  ``ambiguous``) that generates it; the earlier results of a batch were never inspected and stay generated by their
  executions.
- **What DRIFT does not log stays unknown** (D-275): the agent's prompt (``unk /input not_recorded``), DRIFT's own LLM
  calls (no records), times. The assistant text form (``reserialised`` or ``raw``), DRIFT's configuration, privilege map,
  plan and token total are kept under ``ext.drift`` (D-276 for the plan's semantics).
- **Single pass** (``drift.single_pass@1``): ``att0`` has ``index: 0`` and no earlier-attempt issue.
- **No quirk hook points.** The generic build's hook points do not run here. A declared quirk whose hook implements any
  of them and whose selector matches the file raises ``drift.quirk_hook_not_applied`` (detail: the quirk id); census-only
  hooks (``hooks/drift.py``) are inert and raise nothing.

No DRIFT log names the code that wrote it (D-272): every profile of these logs has ``verified_code = []``, so each D rule
is cited through its ``_unverified`` twin and every harness reading is class I; the logged values stay O. A DRIFT quirk the
profile does not declare is reported (``agentdojo.undeclared_quirk``) and its row is not applied (D.6.4).

Pure (A-2), like the generic mapper; the helpers ``_Rec``, ``_loc``, ``_lexical`` and ``_artefact_json`` are the family's.
"""

