    # ---------------------------------------------------------------------------------------------- messages
    def _shape(self, message: object) -> str | None:
        if not isinstance(message, dict):
            return None
        role = message.get("role")
        keys = _SHAPES.get(role) if isinstance(role, str) else None
        if keys is None or set(message) != keys or not isinstance(message.get("content"), str):
            return None
        if role == "assistant":
            calls = message.get("tool_calls")
            if not (isinstance(calls, list) and all(self._call_ok(c) for c in calls)):
                return None
        if role == "tool":
            if not self._call_ok(message.get("tool_call")) or not (message.get("error") is None or isinstance(message.get("error"), str)):
                return None
        return str(role)

    @staticmethod
    def _call_ok(call: object) -> bool:
        return (isinstance(call, dict) and set(call) <= _CALL_KEYS and {"function", "args"} <= set(call)
                and isinstance(call["function"], str) and isinstance(call["args"], dict))

    def _messages(self, body: list[Any]) -> None:
        msgs = self.messages
        self.prev: str | None = None
        self.first_user: str | None = None
        self.last_assistant: tuple[str, int, bool] | None = None  # (id, index, made calls)
        self.batches: list[dict[str, Any]] = []
        self.prompt_issue = False
        i = 0
        while i < len(msgs):
            message = msgs[i]
            role = self._shape(message)
            if role == "assistant":
                j = i + 1
                tools: list[int] = []
                while j < len(msgs) and self._shape(msgs[j]) == "tool":
                    tools.append(j)
                    j += 1
                self._assistant(body, i, message, tools)
                i = j
                continue
            if role == "tool":
                self._tool(body, i, message, None, None, 0, last_of_batch=True)
            elif role == "user":
                self._user(body, i, message)
            else:
                self._unknown(body, i, message)
            i += 1
        self._trailing_calls()

