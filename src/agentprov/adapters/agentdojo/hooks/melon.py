"""Quirk hook ``agentdojo.melon_defence_messages`` (pre-check PC-melon-agentdojo-03/04; D-586).

The MELON defences of xwsdid/MELON write messages of their own into the conversation:

* base MELON (``melon``, ``melon_at``, ``melon_sm``) replaces the model's reply after a detection with a fixed English stop
  message (``updated_messages[-1] = llm_message``, ``pi_detector.py`` l. 643-656 at ``71d99dff``);
* MELON-R (``melon_r``, ``melon_rp``) replaces it with a fixed block message (l. 1510-1530), or inserts a security
  warning as a system message at index 0 before querying the model again (l. 1551-1569). The logs hold three warning
  texts, none byte-identical to the pinned one.

Without this hook the stop and block messages are agent output generated by the model call, and an insert at index 0 is
the benchmark's system prompt (the positional rule), while the real harness prompt after it has no author. With it, every
text whose digest ``params`` lists for the file's defence is that defence's (``agentdojo.defence_authored_message@1``,
class I). A reply becomes a ``terminate`` decision by the defence that generates the message (the model call stays and
generates nothing). An insert has the defence as its author. A later system message with a pinned harness-prompt
digest is the harness prompt, moved by the insert (``agentdojo.system_prompt_by_digest@1``, class I).

``params``: ``replies`` and ``inserts`` are lists of ``{sha256, defences, note?}`` (the digest of the logged text and the
defence actor names that write it); ``moves_prompt`` lists the defences whose inserts move the harness prompt. Census:
``replies`` (terminate decisions citing the rule), ``inserts`` (system messages it authors) and ``moved_prompts``.
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from typing import Any, Final

from agentprov.adapters.agentdojo.quirks import CensusFile, HookView, MessageAuthor, QuirkHook, TextMessage
from agentprov.adapters.code_verification import reading_of
from agentprov.errors import ProfileError

QUIRK_ID: Final = "agentdojo.melon_defence_messages"
AUTHORED: Final = "agentdojo.defence_authored_message@1"
BY_DIGEST: Final = "agentdojo.system_prompt_by_digest@1"
_HEX64: Final = re.compile(r"[0-9a-f]{64}")


def _texts(params: Mapping[str, Any], key: str) -> dict[str, tuple[str, ...]]:
    """``params[key]`` as digest -> defence names (``ProfileError`` for malformed params: a packaging defect)."""
    rows = params.get(key, ())
    out: dict[str, tuple[str, ...]] = {}
    if not isinstance(rows, list | tuple):
        raise ProfileError(f"{QUIRK_ID}: params.{key} must be a list")
    for row in rows:
        digest = row.get("sha256") if isinstance(row, Mapping) else None
        names = row.get("defences") if isinstance(row, Mapping) else None
        if not isinstance(digest, str) or not _HEX64.fullmatch(digest) or digest in out or not isinstance(names, list | tuple) \
                or not names or not all(isinstance(n, str) and n for n in names):
            raise ProfileError(f"{QUIRK_ID}: params.{key} rows need a unique sha256 and a non-empty defences list")
        out[digest] = tuple(names)
    return out


def _defence(view: HookView, names: Sequence[str]) -> str | None:
    """The one defence of the file among ``names`` (none or several: nothing is attributed)."""
    found = [name for name in sorted(view.defence_ids) if name in names]
    return found[0] if len(found) == 1 else None


def _author(view: HookView, message: TextMessage) -> MessageAuthor | None:
    if message.sha256 is None:
        return None
    if message.role == "assistant":
        names = _texts(view.params, "replies").get(message.sha256)
        defence = _defence(view, names) if names else None
        return MessageAuthor(defence, (AUTHORED,), "terminate") if defence is not None else None
    names = _texts(view.params, "inserts").get(message.sha256)
    if names:
        defence = _defence(view, names)
        return MessageAuthor(defence, (AUTHORED,)) if defence is not None else None
    movers = view.params.get("moves_prompt", ())
    if message.index > 0 and isinstance(movers, list | tuple) and _defence(view, [str(m) for m in movers]) is not None:
        pinned = {v.sha256 for v in view.family.prompt_variants if v.sha256 is not None and v.matches(view.facets)}
        if message.sha256 in pinned:
            return MessageAuthor("bench", (BY_DIGEST,))
    return None


def _cites(record: Mapping[str, Any], rule: str, pointer: str | None) -> bool:
    return any(reading_of(str(ref)) == rule and (pointer is None or str(ref).endswith("#" + pointer))
               for ref in record.get("rule", ()))


def _replies(cf: CensusFile) -> int:
    return sum(1 for r in cf.of_kind("decision") if r.get("verdict") == "terminate" and _cites(r, AUTHORED, None))


def _inserts(cf: CensusFile) -> int:
    return sum(1 for r in cf.of_kind("message") if r.get("role") == "system" and _cites(r, AUTHORED, "/actor"))


def _moved(cf: CensusFile) -> int:
    return sum(1 for r in cf.of_kind("message") if r.get("role") == "system" and _cites(r, BY_DIGEST, "/actor"))


HOOKS: Final = (
    QuirkHook(
        quirk_id=QUIRK_ID,
        rules=(AUTHORED, BY_DIGEST),
        message_author=_author,
        census={"replies": _replies, "inserts": _inserts, "moved_prompts": _moved},
    ),
)
