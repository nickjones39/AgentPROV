"""The AgentDojo history table: introducing-commit dates and benchmark versions in force (docs/architecture D.6.16).

Package data (``tables/agentdojo-history.table.toml``), generated by ``tools/agentdojo/history_table.py`` from the
blobless full history of the pinned commits, pinned by its sha256 in the profile (so the profile digest covers it) and
parsed here with a closed schema, like the identity tables of D.4.5. It serves two rules and nothing else:

* ``agentdojo.committed_no_later_than@1`` (D): the committer date of the commit that introduced a log's blob, found by the
  commit id the git origin carries (``introduced_in_commit``, C.3.12). The mapper reads no git store and no cache, so a
  mapping is a pure function of the AER inputs and the profile (invariant 4).
* ``agentdojo.benchmark_era_from_commit@1`` (I): the benchmark version in force in that commit's tree, and the version
  registered next;
* the facet ``introduced_under`` of D.5.4 (format 2, D-84): the oldest pin whose history contains the commit, which
  ``verified_code`` selectors read (a log introduced under the 2024-06 pin is June-2024 code; one introduced later is not).

A commit that is not in the table is not guessed at: the mapper writes neither field and says so with an issue.
"""

from __future__ import annotations

import re
import tomllib
from collections.abc import Mapping
from dataclasses import dataclass
from importlib import resources
from typing import Any, Final

from agentprov.errors import ProfileError
from agentprov.io.canonical import sha256_hex

__all__ = ["Era", "HistoryTable", "VersionRow", "load_history_table", "origin_introduced_under", "parse_history_table"]

FORMAT: Final = "agentprov-agentdojo-history-table/2"
_HEX40: Final = re.compile(r"[0-9a-f]{40}")
_DATE: Final = re.compile(r"[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z")
_LABEL: Final = re.compile(r"v[0-9]+(?:\.[0-9]+){0,2}")
_VERSION_KEYS: Final = frozenset({"label", "dir", "cut", "cut_date", "cut_subject"})
_COMMIT_KEYS: Final = frozenset({"id", "date", "version", "registered", "under"})


@dataclass(frozen=True, slots=True)
class VersionRow:
    """A benchmark version: its label, the directory that registers it and the commit that introduced the directory."""

    label: str
    dir: str
    cut: str
    cut_date: str
    cut_subject: str


@dataclass(frozen=True, slots=True)
class CommitRow:
    id: str
    date: str
    version: str
    registered: bool  # false: the commit's tree has no version directory (it predates the label)
    under: str  # the oldest pin whose history contains the commit (D-84)


@dataclass(frozen=True, slots=True)
class Era:
    """The era of one introducing commit: the version in force, whether it was registered yet, and the version after it."""

    candidate: str
    registered: bool
    next_version: str | None
    next_cut_date: str | None


@dataclass(frozen=True, slots=True)
class HistoryTable:
    repo: str
    pins: tuple[str, ...]
    versions: tuple[VersionRow, ...]
    commits: Mapping[str, CommitRow]

    def date(self, commit: str) -> str | None:
        row = self.commits.get(commit)
        return row.date if row is not None else None

    def introduced_under(self, origin_commit: Any, introduced: Any) -> str | None:
        """D-84: the oldest pin whose history contains the commit that introduced a log's blob. That commit when the
        origin carries it and the table lists it; else, for an origin at the oldest pin, that pin (its blob is in that
        pin's tree, so the introducing commit is in its history); else ``None`` (not known: fail closed)."""
        if isinstance(introduced, str):
            row = self.commits.get(introduced)
            return row.under if row is not None else None
        return self.pins[0] if self.pins and origin_commit == self.pins[0] else None

    def era(self, commit: str) -> Era | None:
        row = self.commits.get(commit)
        if row is None:
            return None
        labels = [v.label for v in self.versions]
        following = self.versions[labels.index(row.version) + 1] if labels.index(row.version) + 1 < len(labels) else None
        return Era(row.version, row.registered, following.label if following else None, following.cut_date if following else None)


def _fail(path: str, why: str) -> ProfileError:
    return ProfileError(f"history table {path!r}: {why}")


def _closed(row: Any, keys: frozenset[str], path: str, what: str) -> dict[str, Any]:
    if not isinstance(row, dict) or set(row) != keys:
        raise _fail(path, f"a {what} row has exactly the keys {sorted(keys)}")
    return row


def parse_history_table(data: bytes, path: str = "<bytes>") -> HistoryTable:
    """The checked table of its bytes. :class:`~agentprov.errors.ProfileError` on any defect (it is trusted package data)."""
    try:
        doc = tomllib.loads(data.decode("utf-8"))
    except (tomllib.TOMLDecodeError, UnicodeDecodeError) as exc:
        raise _fail(path, "not valid TOML/UTF-8") from exc
    if set(doc) != {"format", "repo", "pins", "version", "commit"} or doc["format"] != FORMAT:
        raise _fail(path, f"top-level keys are format ({FORMAT}), repo, pins, version and commit")
    pins = doc["pins"]
    if not isinstance(doc["repo"], str) or not isinstance(pins, list) or not all(isinstance(p, str) and _HEX40.fullmatch(p) for p in pins):
        raise _fail(path, "repo is a string and pins are 40-hex commits")
    versions: list[VersionRow] = []
    for raw in doc["version"]:
        row = _closed(raw, _VERSION_KEYS, path, "version")
        if not (all(isinstance(v, str) for v in row.values()) and _LABEL.fullmatch(row["label"]) and _HEX40.fullmatch(row["cut"])
                and _DATE.fullmatch(row["cut_date"])):
            raise _fail(path, f"version row {row.get('label')!r} is malformed")
        versions.append(VersionRow(row["label"], row["dir"], row["cut"], row["cut_date"], row["cut_subject"]))
    if not versions or len({v.label for v in versions}) != len(versions):
        raise _fail(path, "versions are non-empty with unique labels")
    labels = {v.label for v in versions}
    commits: dict[str, CommitRow] = {}
    for raw in doc["commit"]:
        row = _closed(raw, _COMMIT_KEYS, path, "commit")
        if not (isinstance(row["id"], str) and _HEX40.fullmatch(row["id"]) and isinstance(row["date"], str) and _DATE.fullmatch(row["date"])
                and row["version"] in labels and isinstance(row["registered"], bool) and row["under"] in pins):
            raise _fail(path, f"commit row {str(row.get('id'))[:12]!r} is malformed")
        if row["id"] in commits:
            raise _fail(path, f"commit {row['id'][:12]} is listed twice")
        commits[row["id"]] = CommitRow(row["id"], row["date"], row["version"], row["registered"], row["under"])
    return HistoryTable(doc["repo"], tuple(pins), tuple(versions), commits)


def origin_introduced_under(table: HistoryTable | None, origin: Mapping[str, Any]) -> str | None:
    """The facet ``introduced_under`` (D-84) of a log from its origin as JSON (``kind``, ``repo``, ``commit``,
    ``introduced_in_commit``): :meth:`HistoryTable.introduced_under` for a git origin in the table's repository, else
    ``None``. The mapper, its degenerate header and the SEM citation policy read it the same way."""
    if table is None or origin.get("kind") != "git" or origin.get("repo") != table.repo:
        return None
    return table.introduced_under(origin.get("commit"), origin.get("introduced_in_commit"))


def load_history_table(path: str, sha256: str) -> HistoryTable:
    """The table from package data: digest-checked against the profile's pin, then parsed."""
    node = resources.files("agentprov.adapters.agentdojo").joinpath(*path.split("/"))
    if not node.is_file():
        raise _fail(path, "is not shipped in the package")
    data = node.read_bytes()
    if sha256_hex(data) != sha256:
        raise _fail(path, "its sha256 differs from the one the profile pins")
    return parse_history_table(data, path)
