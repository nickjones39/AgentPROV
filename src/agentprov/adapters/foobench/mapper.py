class FooMapper:
    """``Mapper`` for ``foobench.jsonl`` (D.2.4)."""

    mapper_id: Final = ADAPTER_ID
    version: Final = ADAPTER_VERSION
    accepts: Final = frozenset({(DIALECT_ID, VARIANT)})
    namespaces: Final = NAMESPACES
    catalogues: Final = CATALOGUES

    def map(self, unit: ExecutionUnit, ctx: MappingContext) -> Iterator[AerRecord]:
        yield from _Build(unit, ctx).run()

    @staticmethod
    def prov_primary(flags: frozenset[str]) -> str:
        """``native``: the trace file is what the (hypothetical) framework itself wrote (R-22)."""
        return "native"

    def degenerate_header(self, unit: ExecutionUnit, ctx: MappingContext, *, issue_code: str, detail: str) -> dict[str, Any]:
        """The header of a degenerate AER (D.2.8 case 3), with its error issue reported through ``ctx``.

        The task id is the header line's ``task``, which the reader requires of every parseable file; a unit built
        without the reader has none, and no valid header exists then (the task id is required and a sentinel is banned).
        """
        head = _dict(_dict(unit.primary.value).get("header"))
        task: dict[str, Any] = {"benchmark": "foobench"}
        if isinstance(head.get("task"), str):
            task["task_id"] = head["task"]
        header: dict[str, Any] = {
            "k": "execution",
            "id": "exec",
            "aer": "0.1",
            "ex": ctx.ex,
            "mode": unit.mode,
            "unit": "agent_execution",
            "source_key": {"sha256": unit.primary.artefact.sha256, "loc": unit.primary.locator.key()},
            "artifacts": [unit.primary.artefact.to_json()],
            "adapter": {"id": ADAPTER_ID, "version": ADAPTER_VERSION},
            "dialect": {"id": DIALECT_ID, "variant": VARIANT},
            "profile": ctx.profile.header(),
            "rules": ctx.catalogue_versions(CATALOGUES),
            "ns": dict(NAMESPACES),
            "canon": "jcs-rfc8785",
            "hash": "sha256",
            "task": task,
            "ev": "O",
            "by": "source",
            "evf": {"/task/benchmark": "D"},
            "rule": [ctx.rule(R_SCHEMA, "/task/benchmark")],
            "src": [{"a": unit.primary.artefact.id, "line": 0, "p": "/task"}],
            "unk": {"/instrumentation": "not_recorded"},
        }
        if "task_id" not in task:  # D-219: no header line was read (a failed map job), so no task was captured
            for key in ("by", "evf", "src"):
                header.pop(key)
            header.update(ev="D", rule=[ctx.rule(R_SCHEMA)])
            header["unk"]["/task/task_id"] = "not_captured" if unit.primary.value is None else "not_recorded"
        ctx.issue(issue_code, ids=["exec"], rule=ctx.rule(R_SCHEMA), severity="error", detail=detail)
        return header


class _Build:
    """One mapping run. Records are built in full first: actors are emitted before the records that name them, and
    ``ext`` entries attach to records that already exist."""

    def __init__(self, unit: ExecutionUnit, ctx: MappingContext) -> None:
        value = unit.primary.value
        if not isinstance(value, Mapping) or not isinstance(value.get("header"), Mapping) or not isinstance(value.get("events"), list):
            raise MalformedArtefact("the located item is not a FooBench file")
        self.unit = unit
        self.ctx = ctx
        self.art = unit.primary.artefact
        self.header: Mapping[str, Any] = value["header"]
        self.primary = _File(
            art=self.art.id,
            parsed=ParsedFile(self.header, tuple((int(e["line"]), e["event"]) for e in value["events"])),
            scope=None,
            prefix="m",
        )
        family = ctx.profile.family_table()
        self.actor_table: Mapping[str, Any] = _dict(family.get("actors"))
        self.guard_verdicts: Mapping[str, Any] = _dict(family.get("guard_verdicts"))
        self.approval_decisions: Mapping[str, Any] = _dict(family.get("approval_decisions"))
        self.approvers: Mapping[str, Any] = _dict(family.get("approvers"))
        self.main_thread = str(family.get("main_thread", "main"))
        self.exec_rec = _Rec(ctx, "execution", "exec", ev="O", by="source")
        self.body: list[_Rec] = []
        self.by_id: dict[str, _Rec] = {}
        self.counters: dict[str, int] = {}
        self.actors: dict[str, _Rec] = {}
        self.guards: dict[str, str] = {}  # guard label -> actor id
        self.artifacts: list[ArtefactRef] = [self.art]
        self.msg_scope: dict[str, str] = {}
        self.msg_actor: dict[str, str | None] = {}
        self.open_execs: list[str] = []  # tool_execution ids with a tool_start and no tool_end
        self.host: _Rec | None = None  # the nearest preceding host record (None: the header)
        self.aux: dict[str, tuple[ArtefactRef, ParsedFile] | None] = {}
        self.requests: list[tuple[_File, str, _Request]] = []

    # ---------------------------------------------------------------------------------------------- ids and records
    def new_id(self, prefix: str) -> str:
        n = self.counters.get(prefix, 0)
        self.counters[prefix] = n + 1
        return f"{prefix}{n}"

    def emit(self, rec: _Rec, *, host: bool = True) -> _Rec:
        self.body.append(rec)
        self.by_id[rec.id] = rec
        if host:
            self.host = rec
        return rec

    def issue(self, code: str, ids: Sequence[str], rule_id: str, *, severity: str = "warning", detail: str | None = None) -> None:
        self.ctx.issue(code, ids=ids, rule=self.ctx.rule(rule_id), severity=severity, detail=detail)  # type: ignore[arg-type]

    # ---------------------------------------------------------------------------------------------- actors
    def actor(self, label: str, line: int, *, sub: tuple[str, Mapping[str, Any]] | None = None) -> str:
        """The actor id of a source actor label (the profile's actor table, class D); the record is created on first use."""
        entry = self.actor_table.get(label)
        if not isinstance(entry, Mapping):
            raise _bad(line, "unknown actor label")
        if label not in self.actors:
            self.actors[label] = self._actor_record(label, entry, sub)
        return label

    def _actor_record(self, label: str, entry: Mapping[str, Any], sub: tuple[str, Mapping[str, Any]] | None) -> _Rec:
        model_from = entry.get("model_from")
        art, header = (self.art.id, self.header) if entry.get("model_file", "primary") == "primary" else (sub or ("", {}))
        has_model = isinstance(model_from, str) and isinstance(header.get(model_from), str)
        if has_model:
            assert isinstance(model_from, str)
            rec = _Rec(self.ctx, "actor", label, ev="O", by="config")
            rec.put("model", {"requested": header[model_from]})
            rec.at(art, 0, "/" + model_from)
            rec.unknown("/model/served", "not_recorded")
            rec.tag("/kind", "D", R_ACTORS)
            rec.put("kind", str(entry["kind"]))
            if isinstance(entry.get("role"), str):
                rec.put("role", entry["role"])
                rec.tag("/role", "D", R_ACTORS)
            if isinstance(entry.get("on_behalf_of"), str):
                rec.put("on_behalf_of", entry["on_behalf_of"])
                rec.tag("/on_behalf_of", "D", R_ACTORS)
        else:
            rec = _Rec(self.ctx, "actor", label, ev="D", by=None)
            rec.rule(R_ACTORS)
            rec.put("kind", str(entry["kind"]))
            if isinstance(entry.get("role"), str):
                rec.put("role", entry["role"])
            if isinstance(entry.get("on_behalf_of"), str):
                rec.put("on_behalf_of", entry["on_behalf_of"])
            if isinstance(model_from, str):
                rec.unknown("/model", "not_recorded")
        if isinstance(entry.get("on_behalf_of"), str):
            self.actor(str(entry["on_behalf_of"]), 0)
        return rec

    def guard_actor(self, label: str, line: int) -> str:
        if label not in self.guards:
            rid = self.new_id("def")
            rec = _Rec(self.ctx, "actor", rid, ev="O", by="source")
            rec.put("kind", "defense")
            rec.tag("/kind", "D", R_ACTORS)
            rec.put("name", label)
            rec.at(self.art.id, line, "/guard")
            self.guards[label] = rid
            self.actors[rid] = rec
        return self.guards[label]

    def call_role(self, label: str) -> str:
        role = _dict(self.actor_table.get(label)).get("call_role", "agent")
        return role if role in ("agent", "auxiliary") else "agent"

    # ---------------------------------------------------------------------------------------------- scopes
    def _scope(self, kind: str, prefix: str, actor: str, parent: str, rule_id: str, **extra: Any) -> str:
        rid = self.new_id(prefix)
        rec = _Rec(self.ctx, "scope", rid, ev="D", by=None)
        rec.put("kind", kind)
        rec.put("parent", parent)
        rec.put("actor", actor)
        for key, value in extra.items():
            rec.put(key, value)
        rec.rule(rule_id)
        self.emit(rec, host=False)
        return rid

    def main_scope(self, fc: _File) -> str:
        if fc.scope is None:  # the primary file's attempt, created on first use
            fc.scope = self._scope("attempt", "att", self.actor("agent", 0), "run", R_SCOPES)
        return fc.scope

    def thread_scope(self, fc: _File, label: str, actor: str) -> str:
        if fc.depth > 0 or label == self.main_thread:
            return self.main_scope(fc)
        if label not in fc.threads:
            fc.threads[label] = self._scope("thread", "thr", actor, "run", R_SCOPES)
        return fc.threads[label]

    def _run_scope(self) -> None:
        rec = _Rec(self.ctx, "scope", "run", ev="O", by="source")
        rec.put("kind", "run")
        rec.put("actor", self.actor("agent", 0))
        start = _instant(self.header.get("t"), 0, "t")
        if start is not None:
            rec.put("t", {"start": start})
            rec.at(self.art.id, 0, "/t")
        else:
            rec.at(self.art.id, 0)
            rec.unknown("/t", "not_recorded")
        rec.unknown("/status", "not_recorded")
        self.emit(rec, host=False)

    # ---------------------------------------------------------------------------------------------- run
    def run(self) -> Iterator[AerRecord]:
        self._open_aux()
        self._run_scope()
        self.process(self.primary)
        self._finish()
        yield self._header()
        names = [a for a in _ACTOR_ORDER if a in self.actors] + [a for a in self.actors if a not in _ACTOR_ORDER]
        for name in names:
            yield self.actors[name].done()
        for rec in self.body:
            yield rec.done()

    def _open_aux(self) -> None:
        """Parse the unit's auxiliary files once. A defect is declared where the file is used, never fatal."""
        limits = IngestLimits()
        for label in sorted(self.unit.auxiliary):
            ref = self.unit.auxiliary[label]
            try:
                self.aux[label] = (ref, parse_events(self.ctx.open_auxiliary(label), limits))
            except (AgentProvError, IngestError):
                self.aux[label] = None

    def process(self, fc: _File) -> None:
        for line, ev in fc.parsed.events:
            handler = _HANDLERS.get(str(ev["type"]))
            if handler is None:
                self.keep(fc, line, ev, issue="unmapped_event_type", rule_id=R_UNKNOWN, severity="info")
            else:
                handler(self, fc, line, ev)

    def keep(self, fc: _File, line: int, ev: Mapping[str, Any], *, issue: str, rule_id: str, severity: str) -> None:
        """Keep an event verbatim in ``ext.foobench.events[]`` of the nearest preceding host record (never dropped)."""
        host = self.host if self.host is not None else self.exec_rec
        host_pointer = json_pointer("ext", "foobench", "events", len(host.events), "value")
        rest = {k: v for k, v in ev.items() if k != "type"}
        value = encode_value(rest, at=host_pointer, lex=host.lex)
        src: dict[str, Any] = {"line": line} if fc.art == self.art.id else {"a": fc.art, "line": line}
        host.events.append({"type": str(ev["type"]), "value": value, "src": src, "after": [{"id": host.id, "b": "pos"}]})
        self.issue(f"foobench.{issue}", [host.id], rule_id, severity=severity)

    # ---------------------------------------------------------------------------------------------- messages
    def msg_prefix(self, fc: _File, scope: str) -> str:
        return fc.prefix if scope == fc.scope or fc.depth > 0 else "p"

    def add_message(self, fc: _File, line: int, scope: str, index: int, msg: object) -> None:
        if not isinstance(msg, dict):
            raise _bad(line, "add entries must be objects")
        sid, role = _req(msg, "id", line), _req(msg, "role", line)
        if sid in fc.msgs:
            raise _bad(line, "duplicate message id")
        rid = self.new_id(self.msg_prefix(fc, scope))
        fc.msgs[sid] = rid
        rec = _Rec(self.ctx, "message", rid)
        rec.put("scope", scope)
        rec.put("role", role)
        origin, author = _str(msg, "origin", line, required=False), _str(msg, "author", line, required=False)
        label = origin or author
        if label is not None:
            actor = self.actor(label, line)
            rec.put("actor", actor)
            rec.tag("/actor", "D", R_ACTORS)
            self.msg_actor[rid] = actor
        else:
            rec.unknown("/actor", "not_recorded")
            self.msg_actor[rid] = None
        rec.put("parts", [self._content_part(msg, line)])
        rec.at(fc.art, line, f"/add/{index}")
        if origin is not None:  # inserted by the harness or the environment: no generator in aer/0.1 (C.3.15)
            rec.unknown("/generated_by", "not_recorded")
        self.msg_scope[rid] = scope
        self.emit(rec)
        if origin is not None:
            self.issue("foobench.observation_unlinked", [rid], R_OBSERVATION, severity="info")

    def _content_part(self, msg: Mapping[str, Any], line: int) -> dict[str, Any]:
        text, blob = msg.get("text"), msg.get("blob")
        if isinstance(text, str) and blob is None:
            return {"t": "text", "text": text}
        if isinstance(blob, dict) and text is None:
            ref = self.blob_ref(blob, line)
            return {"t": "blob", "data": ref, "media": ref["media"]}
        raise _bad(line, "a message holds exactly one of text and blob")

    def blob_ref(self, blob: Mapping[str, Any], line: int) -> dict[str, Any]:
        """A BlobRef (C.11.5) from a source's ``{sha256, bytes, media}``. The declared size is the source's claim: one a
        BlobRef cannot carry (beyond I-JSON) is malformed, and so is one that contradicts the blob's bytes when the
        caller supplies them (auxiliary ``blob:<hex>``, digest-verified). Unsupplied, it stands for AER-V21 to check."""
        digest, size, media = blob.get("sha256"), blob.get("bytes"), blob.get("media")
        if not isinstance(digest, str) or _SHA256_HEX.fullmatch(digest) is None:
            raise _bad(line, "sha256 must be 64 lower-case hex digits")
        if not isinstance(size, int) or isinstance(size, bool) or not 0 <= size <= I_JSON_MAX:
            raise _bad(line, "bytes must be a non-negative I-JSON integer")
        if not isinstance(media, str) or not media:
            raise _bad(line, "media must be a non-empty string")
        try:
            data: bytes | None = self.ctx.open_auxiliary(f"blob:{digest}")
        except AgentProvError:
            data = None
        if data is not None and hashlib.sha256(data).hexdigest() == digest and len(data) != size:
            raise _bad(line, "bytes differs from the size of the referenced blob")
        return {"$blob": f"sha256:{digest}", "bytes": size, "media": media}

    def result_message(
        self, fc: _File, line: int, scope: str, generator: str, actor: str, part: str | None, text: str, pointer: str
    ) -> _Rec:
        """A ``tool_result`` message generated by an execution or a decision (C.5.2, C.5.5)."""
        rid = self.new_id(self.msg_prefix(fc, scope))
        rec = _Rec(self.ctx, "message", rid)
        rec.put("scope", scope)
        rec.put("role", "tool")
        rec.put("actor", actor)
        rec.tag("/actor", "D", R_ACTORS)
        rec.put("generated_by", generator)
        part_body: dict[str, Any] = {"t": "tool_result", "text": text}
        if part is not None:
            part_body["responds_to"] = part
            rec.tag("/parts/0/responds_to", "D", R_CALL)
        else:  # a text-parsed action has no request part
            rec.unknown("/parts/0/responds_to", "not_applicable")
        rec.put("parts", [part_body])
        rec.at(fc.art, line, pointer)
        self.msg_scope[rid] = scope
        self.msg_actor[rid] = actor
        return self.emit(rec)

    def call_part(self, fc: _File, call: str, line: int) -> str:
        part = fc.calls.get(call)
        if part is None:
            raise _bad(line, "call id does not name an earlier tool_call")
        return part

    def part_scope(self, part: str) -> str:
        return self.msg_scope[part.split("#", 1)[0]]

    # ---------------------------------------------------------------------------------------------- model calls
    def on_llm_request(self, fc: _File, line: int, ev: Mapping[str, Any]) -> None:
        rq = _req(ev, "id", line)
        if rq in fc.requests:
            raise _bad(line, "duplicate request id")
        actor = self.actor(_req(ev, "actor", line), line)
        scope = self.thread_scope(fc, _str(ev, "thread", line, required=False) or self.main_thread, actor)
        add = ev.get("add", [])
        if not isinstance(add, list):
            raise _bad(line, "add must be an array")
        prefix = self.msg_prefix(fc, scope)
        for i, msg in enumerate(add):
            self.add_message(fc, line, scope, i, msg)
        context: list[str] | None = None
        if "context" in ev:
            raw = ev["context"]
            if not isinstance(raw, list) or not all(isinstance(c, str) for c in raw):
                raise _bad(line, "context must be an array of message ids")
            if any(c not in fc.msgs for c in raw):
                raise _bad(line, "context names an unknown message")
            context = [fc.msgs[c] for c in raw]
        req = _Request(line, _instant(ev.get("ts"), line), actor, scope, context, prefix)
        fc.requests[rq] = req
        self.requests.append((fc, rq, req))

    def on_llm_response(self, fc: _File, line: int, ev: Mapping[str, Any]) -> None:
        rq = _req(ev, "request", line)
        req = fc.requests.get(rq)
        if req is None or rq in fc.answered:
            raise _bad(line, "response does not answer an open request")
        reply = ev.get("reply")
        if not isinstance(reply, dict):
            raise _bad(line, "reply must be an object")
        fc.answered.add(rq)
        finish = _str(ev, "finish", line, required=False)
        mc = self.model_call(fc, req, line, _instant(ev.get("ts"), line), finish)
        self.reply_message(fc, line, req, mc, reply)

    def model_call(self, fc: _File, req: _Request, line: int | None, ts: str | None, finish: str | None) -> _Rec:
        rid = self.new_id("mc")
        rec = _Rec(self.ctx, "model_call", rid)
        rec.put("actor", req.actor)
        rec.put("role", self.call_role(req.actor))
        rec.tag("/role", "D", R_ACTORS)
        rec.put("scope", req.scope)
        if req.context is not None:
            rec.put("input", list(req.context))
        else:
            rec.unknown("/input", "not_recorded")
        rec.at(fc.art, req.line)
        if line is not None:
            rec.put("status", "kept")
            rec.tag("/status", "D", R_SUCCESS)
            rec.at(fc.art, line)
            if finish is not None:
                rec.put("finish_reason", finish)
                rec.evf["/finish_reason"] = "O:provider"
        else:
            rec.unknown("/status", "not_recorded")
        times = {k: v for k, v in (("start", req.ts), ("end", ts)) if v is not None}
        if times:
            rec.put("t", times)
        else:
            rec.unknown("/t", "not_recorded")
        return self.emit(rec)

    def reply_message(self, fc: _File, line: int, req: _Request, mc: _Rec, reply: Mapping[str, Any]) -> None:
        sid = _req(reply, "id", line)
        if sid in fc.msgs:
            raise _bad(line, "duplicate message id")
        rid = self.new_id(req.prefix)
        fc.msgs[sid] = rid
        rec = _Rec(self.ctx, "message", rid)
        rec.put("scope", req.scope)
        rec.put("role", _str(reply, "role", line, required=False) or "assistant")
        rec.put("actor", req.actor)
        rec.tag("/actor", "D", R_ACTORS)
        rec.put("generated_by", mc.id)
        parts: list[dict[str, Any]] = []
        text = reply.get("text")
        if text is not None:
            if not isinstance(text, str):
                raise _bad(line, "text must be a string")
            parts.append({"t": "text", "text": text})
        calls = reply.get("calls", [])
        if not isinstance(calls, list):
            raise _bad(line, "calls must be an array")
        for call in calls:
            if not isinstance(call, dict) or "args" not in call:
                raise _bad(line, "a call needs an id, a name and args")
            cid, name = _req(call, "id", line), _req(call, "name", line)
            if cid in fc.calls:
                raise _bad(line, "duplicate call id")
            fc.calls[cid] = f"{rid}#{len(parts)}"
            parts.append(
                {
                    "t": "tool_call",
                    "name": name,
                    "args": encode_value(call["args"], at=f"/parts/{len(parts)}/args", lex=rec.lex),
                    "provider_call_id": cid,
                }
            )
        rec.put("parts", parts)
        rec.at(fc.art, line, "/reply")
        self.msg_scope[rid] = req.scope
        self.msg_actor[rid] = req.actor
        self.emit(rec)

    # ---------------------------------------------------------------------------------------------- tools
    def new_execution(
        self, fc: _File, line: int, call: str, name: str, ts: str | None, *, args: object = None, has_args: bool = False
    ) -> _Rec:
        part = self.call_part(fc, call, line)
        if call in fc.runs:
            raise _bad(line, "call id is executed twice")
        rid = self.new_id("te")
        rec = _Rec(self.ctx, "tool_execution", rid)
        rec.put("actor", self.actor("env", line))
        rec.tag("/actor", "D", R_ACTORS)
        rec.put("scope", self.part_scope(part))
        rec.put("call", part)
        rec.tag("/call", "D", R_CALL)
        rec.put("name", name)
        if has_args:
            rec.put_json("args", args)
        if ts is not None:
            rec.put("t", {"start": ts})
        else:
            rec.unknown("/t", "not_recorded")
        if call in fc.approvals:
            rec.put("authorised_by", fc.approvals[call])
            rec.tag("/authorised_by", "D", R_CALL)
        rec.at(fc.art, line)
        fc.runs[call] = rid
        return self.emit(rec)

    def on_tool_start(self, fc: _File, line: int, ev: Mapping[str, Any]) -> None:
        rec = self.new_execution(
            fc, line, _req(ev, "call", line), _req(ev, "name", line), _instant(ev.get("ts"), line),
            args=ev.get("args"), has_args="args" in ev,
        )  # fmt: skip
        rec.unknown("/status", "not_recorded")
        self.open_execs.append(rec.id)

    def on_tool_end(self, fc: _File, line: int, ev: Mapping[str, Any]) -> None:
        call = _req(ev, "call", line)
        te_id = fc.runs.get(call)
        if te_id is None or te_id not in self.open_execs:
            raise _bad(line, "tool_end does not close an open tool_start")
        self.open_execs.remove(te_id)
        te = self.by_id[te_id]
        status = ev.get("status")
        te.unk.pop("/status", None)
        if isinstance(status, str) and status in _TOOL_STATUS:
            te.put("status", status)
        else:
            te.unknown("/status", "ambiguous")
        end = _instant(ev.get("ts"), line)
        if end is not None:
            t = dict(te.data.get("t", {}))
            t["end"] = end
            te.put("t", t)
            te.unk.pop("/t", None)
        te.at(fc.art, line)
        output = ev.get("output")
        if output is None:
            self.issue("missing_tool_result", [te_id], R_CALL)
            return
        if not isinstance(output, str):
            raise _bad(line, "output must be a string")
        res = self.result_message(fc, line, str(te.data["scope"]), te_id, str(te.data["actor"]), str(te.data["call"]), output, "/output")
        res.tag("/generated_by", "D", R_CALL)
        source_id = _str(ev, "message", line, required=False)
        if source_id is not None:
            if source_id in fc.msgs:
                raise _bad(line, "duplicate message id")
            fc.msgs[source_id] = res.id

    def on_guard_verdict(self, fc: _File, line: int, ev: Mapping[str, Any]) -> None:
        part = self.call_part(fc, _req(ev, "call", line), line)
        actor = self.guard_actor(_req(ev, "guard", line), line)
        scope = self.part_scope(part)
        dc = self.decision(fc, line, ev, actor, scope, part, str(ev.get("verdict")), self.guard_verdicts)
        reason = _str(ev, "reason", line, required=False)
        if reason is not None:
            dc.put("reason", reason)
        replacement = ev.get("replacement")
        if replacement is not None:
            if not isinstance(replacement, str):
                raise _bad(line, "replacement must be a string")
            res = self.result_message(fc, line, scope, dc.id, actor, part, replacement, "/replacement")
            source_id = _str(ev, "message", line, required=False)
            if source_id is not None:
                if source_id in fc.msgs:
                    raise _bad(line, "duplicate message id")
                fc.msgs[source_id] = res.id

    def decision(
        self, fc: _File, line: int, ev: Mapping[str, Any], actor: str, scope: str, part: str, label: str, table: Mapping[str, Any]
    ) -> _Rec:
        rid = self.new_id("dc")
        rec = _Rec(self.ctx, "decision", rid)
        rec.put("actor", actor)
        if actor in self.actors and self.actors[actor].data["ev"] == "D":
            rec.tag("/actor", "D", R_ACTORS)
        rec.put("scope", scope)
        rec.put("subject", part)
        rec.tag("/subject", "D", R_CALL)
        verdict = table.get(label)
        if isinstance(verdict, str):
            rec.put("verdict", verdict)
            rec.tag("/verdict", "D", R_VERDICT)
        else:  # outside the closed table: the verdict is kept verbatim in ext and declared unknown
            rec.unknown("/verdict", "ambiguous")
            rec.ext["foobench"] = {"verdict_raw": label}
        ts = _instant(ev.get("ts"), line)
        if ts is not None:
            rec.put("t", {"start": ts})
        rec.at(fc.art, line)
        return self.emit(rec)

    def on_approval(self, fc: _File, line: int, ev: Mapping[str, Any]) -> None:
        call = _req(ev, "call", line)
        part = self.call_part(fc, call, line)
        approver = self.approvers.get(_req(ev, "approver", line))
        if not isinstance(approver, str):
            raise _bad(line, "unknown approver")
        actor = self.actor(approver, line)
        decision = _req(ev, "decision", line)
        dc = self.decision(fc, line, ev, actor, self.part_scope(part), part, decision, self.approval_decisions)
        if dc.data.get("verdict") in ("allow", "modify"):
            fc.approvals[call] = dc.id
        if dc.data.get("verdict") == "modify":  # the request as the approver saw it, before the edit
            dc.put("original", part)
            dc.tag("/original", "D", R_CALL)

    def on_handoff(self, fc: _File, line: int, ev: Mapping[str, Any]) -> None:
        call = _req(ev, "call", line)
        ts = _instant(ev.get("ts"), line)
        te = self.new_execution(fc, line, call, _req(ev, "name", line), ts)
        te.put("status", "ok")
        te.tag("/status", "D", R_SUCCESS)
        label, sub_file = _req(ev, "to", line), _str(ev, "sub_file", line, required=False)
        sub: tuple[ArtefactRef, ParsedFile] | None = None
        if sub_file is not None:
            if sub_file in self.aux and self.aux[sub_file] is not None:
                sub = self.aux[sub_file]
            else:
                code = "unparseable_artefact" if sub_file in self.aux else "dangling_source_ref"
                self.issue(code, [te.id], R_HANDOFF, severity="error")
        sub_header = (sub[0].id, sub[1].header) if sub is not None else None
        actor = self.actor(label, line, sub=sub_header)
        scope = self._scope("subagent", "sc", actor, "run", R_HANDOFF, spawned_by=te.id)
        if sub is not None and sub_file is not None:
            ref, parsed = sub
            if ref.id not in {a.id for a in self.artifacts}:
                self.artifacts.append(ref)
            if sub_file in fc.chain or fc.depth + 1 > _MAX_NESTING:  # never a silent truncation (regen item 55)
                reason = "hand-off cycle" if sub_file in fc.chain else f"nesting limit {_MAX_NESTING}"
                self.issue("foobench.handoff_not_expanded", [te.id], R_HANDOFF, detail=f"{reason}: {sub_file} not expanded")
            else:
                self.process(_File(art=ref.id, parsed=parsed, scope=scope, prefix="sm", depth=fc.depth + 1,
                                   chain=(*fc.chain, sub_file)))
        result = ev.get("result")
        if result is not None:
            if not isinstance(result, str):
                raise _bad(line, "result must be a string")
            res = self.result_message(fc, line, str(te.data["scope"]), te.id, str(te.data["actor"]), str(te.data["call"]), result, "/result")
            source_id = _str(ev, "message", line, required=False)
            if source_id is not None:
                if source_id in fc.msgs:
                    raise _bad(line, "duplicate message id")
                fc.msgs[source_id] = res.id
        else:
            self.issue("missing_tool_result", [te.id], R_HANDOFF)

