# ------------------------------------------------------------------------------------------------ small helpers
def _bad(line: int, what: str) -> MalformedArtefact:
    """A malformed-event error naming only the line and a constant label (never source text, D.2.7)."""
    return MalformedArtefact(f"line {line}: {what}")


def _str(ev: Mapping[str, Any], key: str, line: int, *, required: bool = True) -> str | None:
    value = ev.get(key)
    if value is None and not required:
        return None
    if not isinstance(value, str) or not value:
        raise _bad(line, f"{key} must be a non-empty string")
    return value


def _pointer(value: object) -> bool:
    """An RFC 6901 pointer that stays a plain string in AER (a lone surrogate would be ``$utf16``-wrapped, C.11.3)."""
    if not isinstance(value, str) or _POINTER.fullmatch(value) is None:
        return False
    try:
        value.encode("utf-8")
    except UnicodeEncodeError:
        return False
    return True


def _patch(value: object, line: int) -> list[Any]:
    """A source ``store_patch``: RFC 6902 operations, as the AER ``state_change.patch`` holds them (C.3). A member name
    beginning with ``$`` would ``$lit``-wrap the operation (C.11.3), hiding its ``op`` and ``path``: malformed too."""
    if not isinstance(value, list):
        raise _bad(line, "store_patch must be an array")
    for op in value:
        if not isinstance(op, dict) or any(str(k).startswith("$") for k in op):
            raise _bad(line, "a store_patch operation must be an object without $-members")
        kind = op.get("op")
        if not isinstance(kind, str) or kind not in _PATCH_OPS or not _pointer(op.get("path")):
            raise _bad(line, "a store_patch operation needs an RFC 6902 op and a JSON Pointer path")
        need = _PATCH_OPS[kind]
        if need is not None and (need not in op or (need == "from" and not _pointer(op["from"]))):
            raise _bad(line, f"a store_patch {kind} operation needs {need}")
    return value


def _req(ev: Mapping[str, Any], key: str, line: int) -> str:
    value = _str(ev, key, line)
    assert value is not None
    return value


def _instant(value: object, line: int, what: str = "ts") -> str | None:
    """An RFC 3339 UTC instant with a ``Z`` suffix, or ``None`` when absent."""
    if value is None:
        return None
    if not isinstance(value, str) or _RFC3339_Z.fullmatch(value) is None:
        raise _bad(line, f"{what} must be an RFC 3339 UTC instant")
    try:
        datetime.datetime.fromisoformat(value)
    except ValueError:
        raise _bad(line, f"{what} must be an RFC 3339 UTC instant") from None
    return value


def _dict(value: object) -> Mapping[str, Any]:
    return value if isinstance(value, Mapping) else {}


class _Rec:
    """One AER record under construction: fields, evidence plumbing and lexical hints (C.6, C.11.4)."""

    def __init__(self, ctx: MappingContext, kind: str, rid: str, *, ev: str = "O", by: str | None = "source") -> None:
        self.ctx = ctx
        self.data: dict[str, Any] = {"k": kind, "id": rid, "ev": ev}
        if by is not None:
            self.data["by"] = by
        self.evf: dict[str, str] = {}
        self.rules: list[str] = []
        self.src: list[dict[str, Any]] = []
        self.unk: dict[str, str] = {}
        self.ext: dict[str, Any] = {}
        self.events: list[dict[str, Any]] = []  # ext.foobench.events[]
        self.lex = LexHints()

    @property
    def id(self) -> str:
        return str(self.data["id"])

    def put(self, name: str, value: Any) -> None:
        self.data[name] = value

    def put_json(self, name: str, value: object) -> None:
        """A source ``Json`` value, encoded with its lexical hints (C.11.3-4)."""
        self.data[name] = encode_value(value, at="/" + name, lex=self.lex)

    def tag(self, pointer: str, cls: str, rule_id: str) -> None:
        """Mark ``pointer`` as class ``D`` or ``I`` under ``rule_id`` (a pointer-scoped reference, C.6.4)."""
        self.evf[pointer] = cls
        self.rules.append(self.ctx.rule(rule_id, pointer))

    def rule(self, rule_id: str) -> None:
        """An unscoped rule reference (it justifies a record whose existence is class D)."""
        self.rules.append(self.ctx.rule(rule_id))

    def at(self, art: str, line: int, pointer: str | None = None) -> None:
        loc: dict[str, Any] = {"a": art, "line": line}
        if pointer is not None:
            loc["p"] = pointer
        self.src.append(loc)

    def unknown(self, pointer: str, reason: str) -> None:
        self.unk[pointer] = reason

    def done(self) -> dict[str, Any]:
        out = dict(self.data)
        if self.evf:
            out["evf"] = dict(self.evf)
        if self.rules:
            out["rule"] = list(dict.fromkeys(self.rules))
        if self.src:
            out["src"] = list(self.src)
        if self.unk:
            out["unk"] = dict(self.unk)
        ext: dict[str, Any] = {k: dict(v) if isinstance(v, dict) else v for k, v in self.ext.items()}
        if self.events:
            ext.setdefault("foobench", {})["events"] = list(self.events)
        if self.lex:
            ext["lex"] = self.lex.as_dict()
        if ext:
            out["ext"] = ext
        return out


