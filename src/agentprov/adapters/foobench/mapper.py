"""Mapper ``foobench.jsonl``: FooBench JSONL traces -> AER ``aer/0.1`` (docs/architecture D.12.2; C.3.13-C.3.15).

FooBench is a self-authored toy format with event types the core has never seen. This mapper is the evidence for
"new event types without core change" (DoD Q.3): it maps onto the **existing** record kinds only, and uses the generic
``activity`` and ``artefact`` kinds exactly where no specialised kind fits (A-9):

===========================  ====================================================================================
FooBench event               AER
===========================  ====================================================================================
llm_request + llm_response   ``model_call`` + output ``message`` (``generated_by``); the planner call is ``auxiliary``
tool_start + tool_end        ``tool_execution`` + ``tool_result`` message
guard_verdict                ``decision`` (verdict from the profile's closed table); a ``deny`` has no execution
plan_update                  ``activity`` ``foobench:plan_step`` + ``artefact`` ``foobench:plan``
memory_write                 ``artefact`` ``foobench:memory_item`` generated by the tool execution (+ ``state_change``)
memory_read                  ``activity`` ``foobench:memory_read`` + ``artefact`` ``foobench:memory_snippet``
screenshot                   ``activity`` ``foobench:observe`` + ``artefact`` ``foobench:screenshot`` (a blob)
handoff                      ``tool_execution`` + ``scope`` ``subagent`` (``spawned_by``) holding the second file
approval (approve / edit)    ``decision`` (``allow`` / ``modify``) and ``tool_execution.authorised_by``
text_action                  ``tool_execution`` with ``requested_by`` and no ``call`` (name and args are class I)
checkpoint_restore           kept verbatim in ``ext.foobench.events[]`` of the nearest preceding host + an issue
any other type               kept verbatim in ``ext.foobench.events[]`` of the nearest preceding host + an issue
===========================  ====================================================================================

Nothing is dropped and nothing is invented: what aer/0.1 cannot express (an activity generating a message, a restore,
an unknown event) is kept in ``ext`` or left unlinked, and declared with a seal issue. Every D and I claim cites a rule
of the ``foobench`` catalogue; every reference the format joins by call id is class D.

A malformed event (wrong types, a dangling reference, a blob size that contradicts the supplied blob, D.12.2) raises
``MalformedArtefact``: the runner seals a degenerate AER (D.2.8 case 3), so the file is still recorded. Pure (A-2): the
output is a function of the unit's bytes and the blobs supplied with it, this code, the profile and the catalogues.
Standard library and ``agentprov.{ingest,aer,adapters,errors}`` only.
"""

