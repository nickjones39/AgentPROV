"""The FooBench semantics profile ``foobench.toy@1`` (docs/architecture D.12.1 row 7; C.14; EF E.7).

A semantics profile reads one AER and yields standoff annotations (integrity, channel, role) from the tables in
``foobench.toy-1/tables.toml``; the SEM engine numbers and seals them. Every annotation is class ``I``: the tables are
the profile author's declared reading of the toy tools, not a verified property of a framework (rules
``foobench.tool_role_table@1``, ``foobench.tool_output_label_table@1``, ``foobench.artefact_label_table@1`` and
``foobench.observation_label_table@1``).

* a ``tool_call`` part and a ``tool_execution`` get ``role`` from the tool table (``["unknown"]`` for a name that is not
  listed, so the text-parsed action ``te5`` is labelled like any execution); the engine emits no exposure for a
  request-less execution (DECISIONS D-16), the labels are still produced;
* a ``tool_result`` part gets ``integrity`` (and ``channel`` where the table has one) from the tool that generated it
  (``unknown`` when the tool is not listed); a result generated by a guard decision is not tool output and gets none;
* an ``artefact`` gets ``integrity`` (and ``channel``) from its type, ``unknown`` for an undeclared type;
* the user-role messages the harness or the environment insert into the context get an ``integrity`` from their own
  actor (no ``channel``: C.14.3 allows it on ``tool_result`` parts and artefacts only); no link to an artefact is
  asserted (the AER declares none, ``foobench.observation_injected@1``).

FooBench records no judgement, so the profile emits no ``outcome``. Its taint policy is sink roles plus ``unknown``
over ``untrusted`` and ``unknown`` integrity (``foobench.taint_sink_untrusted@1``).

This package imports only the standard library and ``agentprov.{aer,sem}`` (D.2.1 boundary test).
"""

from __future__ import annotations

import tomllib
from collections.abc import Iterator, Mapping
from typing import TYPE_CHECKING, Any, Final

from agentprov.aer.types import Json
from agentprov.sem.profiles import SemanticsProfileError
from agentprov.sem.types import INTEGRITY_VALUES, ROLE_VALUES, Annotation, Premise, TaintPolicy

if TYPE_CHECKING:
    from agentprov.aer.reader import AerDocument

__all__ = ["PROFILE_ID", "FooBenchToyProfile", "build_profile"]

PROFILE_ID: Final = "foobench.toy"
_TABLES: Final = "tables.toml"
_RULE_ROLE: Final = "foobench.tool_role_table@1"
_RULE_OUTPUT: Final = "foobench.tool_output_label_table@1"
_RULE_ARTEFACT: Final = "foobench.artefact_label_table@1"
_RULE_OBSERVATION: Final = "foobench.observation_label_table@1"
_RULE_TAINT: Final = "foobench.taint_sink_untrusted@1"
_UNKNOWN_ROLES: Final = ("unknown",)


def _label(entry: Mapping[str, Any], where: str) -> tuple[str, str | None]:
    integrity, channel = entry.get("integrity"), entry.get("channel")
    if integrity not in INTEGRITY_VALUES:
        raise SemanticsProfileError(f"{where}: integrity {integrity!r} is not in the closed vocabulary")
    if channel is not None and (not isinstance(channel, str) or not channel):
        raise SemanticsProfileError(f"{where}: channel must be a non-empty string")
    return str(integrity), channel


class FooBenchToyProfile:
    """``foobench.toy@1``: the tool, artefact and observation tables of the FooBench toy format."""

    ns: Mapping[str, Json] = {}

    def __init__(self, profile_id: str, version: int, files: Mapping[str, bytes], sha256: str) -> None:
        if profile_id != PROFILE_ID or version != 1 or _TABLES not in files:
            raise SemanticsProfileError(f"not a FooBench semantics profile: {profile_id}@{version}")
        self._id, self._version, self._sha256 = profile_id, version, sha256
        doc = tomllib.loads(files[_TABLES].decode("utf-8"))
        # name -> (roles, integrity, channel)
        self._tools: dict[str, tuple[tuple[str, ...], str, str | None]] = {}
        for entry in doc.get("tool", []):
            roles = tuple(entry.get("roles", ()))
            if not roles or any(r not in ROLE_VALUES for r in roles):
                raise SemanticsProfileError(f"tool {entry.get('name')!r}: roles must be a non-empty subset of the vocabulary")
            integrity, channel = _label(entry, f"tool {entry.get('name')!r}")
            if entry["name"] in self._tools:
                raise SemanticsProfileError(f"tool {entry['name']!r} is listed twice")
            self._tools[str(entry["name"])] = (roles, integrity, channel)
        self._artefacts: dict[str, tuple[str, str | None]] = {}
        for entry in doc.get("artefact", []):
            self._artefacts[str(entry["type"])] = _label(entry, f"artefact {entry.get('type')!r}")
        self._observations: dict[str, str] = {}  # actor -> integrity (no channel on text and blob parts, C.14.3)
        for entry in doc.get("observation", []):
            integrity, channel = _label(entry, f"observation {entry.get('actor')!r}")
            if channel is not None:
                raise SemanticsProfileError(f"observation {entry.get('actor')!r}: C.14.3 allows no channel on this part kind")
            self._observations[str(entry["actor"])] = integrity
        taint = doc["taint"]
        subjects, objects = frozenset(taint["subject_roles"]), frozenset(taint["object_integrity"])
        if not subjects <= frozenset(ROLE_VALUES) or not objects <= frozenset(INTEGRITY_VALUES):
            raise SemanticsProfileError("the taint policy names values outside the closed vocabularies")
        self._taint = TaintPolicy(rule=_RULE_TAINT, subject_roles=subjects, object_integrity=objects)

    @property
    def id(self) -> str:
        return self._id

    @property
    def version(self) -> int:
        return self._version

    @property
    def sha256(self) -> str:
        return self._sha256

    @property
    def rules(self) -> Mapping[str, int]:
        return {"foobench": 1}

    @property
    def taint_policy(self) -> TaintPolicy | None:
        return self._taint

    # ---------------------------------------------------------------------------------------------- annotate
    def annotate(self, aer: AerDocument) -> Iterator[Annotation]:
        """Yield the annotations in AER file order (deterministic; reads only the AER)."""
        for rec in aer.records:
            kind = rec.get("k")
            if kind == "message":
                yield from self._message(aer, rec)
            elif kind == "tool_execution":
                name = rec.get("name")
                roles = self._roles(name)
                yield Annotation(str(rec["id"]), "role", list(roles), "I", (_RULE_ROLE,), (Premise(str(rec["id"]), "/name"),))
            elif kind == "artefact":
                yield from self._artefact(rec)

    def _roles(self, name: object) -> tuple[str, ...]:
        entry = self._tools.get(name) if isinstance(name, str) else None
        return entry[0] if entry is not None else _UNKNOWN_ROLES

    def _message(self, aer: AerDocument, msg: Mapping[str, Any]) -> Iterator[Annotation]:
        mid = str(msg["id"])
        parts = msg.get("parts")
        if not isinstance(parts, list):
            return
        generator = aer.get(str(msg["generated_by"])) if isinstance(msg.get("generated_by"), str) else None
        execution = generator if generator is not None and generator.get("k") == "tool_execution" else None
        observation = self._observations.get(str(msg.get("actor"))) if msg.get("role") == "user" else None
        for index, part in enumerate(parts):
            if not isinstance(part, dict):
                continue
            target, t = f"{mid}#{index}", part.get("t")
            if t == "tool_call":
                yield Annotation(target, "role", list(self._roles(part.get("name"))), "I", (_RULE_ROLE,),
                                 (Premise(mid, f"/parts/{index}/name"),))
            elif t == "tool_result" and execution is not None:
                name = execution.get("name")
                entry = self._tools.get(name) if isinstance(name, str) else None
                integrity, channel = ("unknown", None) if entry is None else entry[1:]
                premises = (Premise(str(execution["id"]), "/name"),)
                yield Annotation(target, "integrity", integrity, "I", (_RULE_OUTPUT,), premises)
                if channel is not None:
                    yield Annotation(target, "channel", channel, "I", (_RULE_OUTPUT,), premises)
            if observation is not None:
                yield Annotation(target, "integrity", observation, "I", (_RULE_OBSERVATION,),
                                 (Premise(mid, "/actor"), Premise(mid, "/role")))

    def _artefact(self, rec: Mapping[str, Any]) -> Iterator[Annotation]:
        entry = self._artefacts.get(str(rec.get("type")))
        integrity, channel = ("unknown", None) if entry is None else entry
        target, premises = str(rec["id"]), (Premise(str(rec["id"]), "/type"),)
        yield Annotation(target, "integrity", integrity, "I", (_RULE_ARTEFACT,), premises)
        if channel is not None:
            yield Annotation(target, "channel", channel, "I", (_RULE_ARTEFACT,), premises)


def build_profile(profile_id: str, version: int, files: Mapping[str, bytes], sha256: str) -> FooBenchToyProfile:
    """The entry point of :func:`agentprov.adapters.semantics_profiles.load_semantics_profile` (C.14.1)."""
    return FooBenchToyProfile(profile_id, version, files, sha256)
