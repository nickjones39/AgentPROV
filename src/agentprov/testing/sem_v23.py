"""SEM ↔ AgentDojo-PROV v2.3 label equivalence (docs/architecture C.14; EF E.7.3 item 2, E.8.4; J.3.5 gate D).

The comparator lines up an AER with its frozen v2.3 compat graph (the ``<stem>.json`` beside each transcript) and
compares, per element, what v2.3 stated as node attributes (``adprov:integrity``, ``adprov:role``,
``adprov:source_channel``, ``adprov:contains_injection_marker``) with what a semantics profile states as SEM annotations.
Used by ``tests/adapters/agentdojo/test_semantics.py`` (golden pairs) and ``tools/agentdojo/sem_equivalence_scan.py``
(the full baseline trees, local only). Nothing here prints fixture text: differences are ids, attribute names, labels.
"""

from __future__ import annotations

import json
from collections import defaultdict
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from agentprov.aer.reader import AerDocument
from agentprov.sem.types import SINK_ROLES, Annotation

#: C.14.3: the record or part kinds each core annotation type may target ("part:<t>" for message parts).
ALLOWED_TARGETS: dict[str, frozenset[str]] = {
    "integrity": frozenset({"part:text", "part:reasoning", "part:tool_call", "part:tool_result", "part:blob",
                            "part:file", "part:uri", "part:refusal", "part:other", "fixture", "artefact"}),
    "channel": frozenset({"part:tool_result", "artefact"}),
    "role": frozenset({"tool_execution", "part:tool_call", "activity"}),
    "injection_marker": frozenset({"part:tool_result"}),
    "outcome": frozenset({"judgement"}),
    "author": frozenset({"message", "part:text", "part:reasoning", "part:tool_call", "part:tool_result", "part:blob",
                         "part:file", "part:uri", "part:refusal", "part:other", "artefact"}),
}


def target_kind(doc: AerDocument, target: str) -> str | None:
    if "#" in target:
        part = doc.part(target)
        return f"part:{part.get('t')}" if part is not None else None
    record = doc.get(target)
    return str(record.get("k")) if record is not None else None


def pointer_resolves(record: Mapping[str, Any], pointer: str) -> bool:
    node: Any = record
    for token in pointer.split("/")[1:]:
        token = token.replace("~1", "/").replace("~0", "~")
        if isinstance(node, dict) and token in node:
            node = node[token]
        elif isinstance(node, list) and token.isascii() and token.isdigit() and int(token) < len(node):
            node = node[int(token)]
        else:
            return False
    return True


def annotation_records(anns: Iterable[Annotation]) -> list[dict[str, Any]]:
    return [a.to_record(f"a{i}") for i, a in enumerate(anns)]


@dataclass(frozen=True)
class Difference:
    """One element where v2.3 and the profile disagree (no fixture text)."""

    element: str  # AER id or part id
    attribute: str  # adprov:integrity | adprov:role | adprov:source_channel | adprov:contains_injection_marker
    v23: Any
    sem: Any
    category: str | None  # a registered category, or None when unexplained


def result_part(doc: AerDocument, te_id: str) -> str | None:
    """The part id of the tool_result generated by ``te_id`` (directly, or by a decision about it)."""
    generators = {te_id} | {r["id"] for r in doc.of_kind("decision") if r.get("subject") == te_id}
    for message in doc.of_kind("message"):
        if message.get("generated_by") in generators:
            for k, part in enumerate(message.get("parts", [])):
                if part.get("t") == "tool_result":
                    return f"{message['id']}#{k}"
    return None


def load_graph(path: Path) -> dict[str, Any]:
    return json.loads(path.read_bytes())


def compare_with_v23(doc: AerDocument, anns: list[Annotation], graph: Mapping[str, Any],
                     known: frozenset[str]) -> list[Difference]:
    """Per-element comparison of the profile's annotations with the v2.3 compat graph (EF E.8.4 attribute rows).

    Tool activities are aligned with the AER's tool executions by ``adprov:step`` (the v2.3 tool-turn counter, which
    runs over every pass in order) and checked by tool name. Categories registered here: ``unknown_tool_fail_closed``
    (the tool is not in the applicable suite table: v2.3 said trusted / neutral / a channel, the profile says unknown
    and gives no channel) and ``yaml_rejection_fallback`` (the YAML normaliser rejected the output and a fallback
    reading found a payload that v2.3 called absent).
    """
    on: dict[tuple[str, str], list[Annotation]] = defaultdict(list)
    for a in anns:
        on[(a.target, a.type)].append(a)
    out: list[Difference] = []

    def one(target: str, type_: str) -> Any:
        found = on.get((target, type_), [])
        assert len(found) <= 1, f"{target}: {len(found)} {type_} annotations"
        return found[0].value if found else None

    entities, activities = graph.get("entity", {}), graph.get("activity", {})
    generated = {g["prov:activity"]: g["prov:entity"] for g in graph.get("wasGeneratedBy", {}).values()}
    acts = sorted(activities.items(), key=lambda kv: kv[1]["adprov:step"])
    tes = doc.of_kind("tool_execution")
    assert len(acts) == len(tes), f"{len(acts)} v2.3 tool activities vs {len(tes)} tool executions"
    for (aid, act), te in zip(acts, tes, strict=True):
        assert act["prov:label"] == te["name"], f"{te['id']}: v2.3 activity {aid} is another tool"
        unknown = te["name"] not in known
        # role: v2.3 sink <=> any sink role
        sem_roles = one(te["id"], "role")
        v23_sink = act["adprov:role"] == "sink"
        sem_sink = bool(set(sem_roles or []) & SINK_ROLES)
        if v23_sink != sem_sink or (act["adprov:role"] == "neutral" and sem_roles == ["unknown"]):
            cat = "unknown_tool_fail_closed" if unknown and sem_roles == ["unknown"] else None
            out.append(Difference(te["id"], "adprov:role", act["adprov:role"], sem_roles, cat))
        part = result_part(doc, te["id"])
        assert part is not None, f"{te['id']}: no tool_result part"
        entity = entities[generated[aid]]
        integrity = one(part, "integrity")
        if integrity != entity["adprov:integrity"]:
            cat = "unknown_tool_fail_closed" if unknown and integrity == "unknown" else None
            out.append(Difference(part, "adprov:integrity", entity["adprov:integrity"], integrity, cat))
        channel = one(part, "channel")
        if channel != entity.get("adprov:source_channel"):
            cat = "unknown_tool_fail_closed" if unknown and channel is None else None
            out.append(Difference(part, "adprov:source_channel", entity.get("adprov:source_channel"), channel, cat))
        marks = on.get((part, "injection_marker"), [])
        v23_marker = entity.get("adprov:contains_injection_marker")
        values = [m.value for m in marks if isinstance(m.value, dict)]
        sem_marker: bool | None = None if not marks else any(v.get("status") == "present" for v in values)
        if v23_marker != sem_marker:
            fallback = any(v.get("status") == "present" and v.get("normaliser") != "agentdojo.yaml_norm@1"
                           for v in values)
            cat = "yaml_rejection_fallback" if fallback and v23_marker is False else None
            out.append(Difference(part, "adprov:contains_injection_marker", v23_marker, sem_marker, cat))
    # the user query and the agent (v2.3 labels both trusted; every user and assistant part here)
    user = entities.get("adprov:e_user_query", {}).get("adprov:integrity")
    agent = graph.get("agent", {}).get("adprov:ag_llm", {}).get("adprov:integrity")
    for message in doc.of_kind("message"):
        expected = {"user": user, "assistant": agent}.get(str(message.get("role")))
        if expected is None:
            continue
        for k, _part in enumerate(message.get("parts", [])):
            pid = f"{message['id']}#{k}"
            got = one(pid, "integrity")
            if got != expected:
                out.append(Difference(pid, "adprov:integrity", expected, got, None))
    return out
