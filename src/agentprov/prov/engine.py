"""The ``agentprov-prov/0.1`` engine: rule driver, classification, bundle routing and the Inference-6 closure
(EF E.0-E.3, E.5.3, E.9; F.1).

``derive(aer)`` is a pure function of the AER, the spec (its ``aprov`` catalogue), the adapter catalogues the AER header
names (package resources) and :class:`ProvOptions`. It reads no raw artefact, clock, environment, randomness or
network (E.0.1 item 2; E.9 item 3), and its output bytes are canonical JCS (E.5.3).

Pipeline: node rules -> edge rules -> order and status attributes -> classes (E.1.5 item 2) -> routing and the
attribute evidence rule (items 4-5) -> communication closure (E.1.6) -> derivation keys and names (E.3.4, E.4.2) ->
top-level conversion provenance (E.3.3) -> canonical PROV-JSON.
"""

