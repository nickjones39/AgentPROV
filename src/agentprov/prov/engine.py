class Citation(NamedTuple):
    """An AER rule that declares an assumption, with the field that cites it (the premise the statement rests on)."""

    rule: str
    field: Field


class ProvDerivationError(AgentProvError):
    """A typed failure of ``derive`` (E.0.1 item 5): the engine is total, never an uncaught exception."""

    code = "prov.derive"
    exit_code = 1


@dataclass(frozen=True, slots=True)
class ProvOptions:
    """The option set of the profile (E.0.3); recorded as ``apv:profileOptions`` and in every ``dk``."""

    context_encoding: Literal["members"] = "members"
    emit_content: bool = False

    def as_json(self) -> dict[str, Any]:
        return {"context_encoding": self.context_encoding, "emit_content": self.emit_content}


@dataclass(frozen=True, slots=True)
class BundleInfo:
    iri: str  # prefixed name, e.g. ``xd:bundle.core.<dk>``
    kind: str  # ``core`` | ``inference`` | ``assessment``
    methods: tuple[str, ...]
    derivation_key: str
    digest: str  # ``sha256:<hex>`` of the JCS bytes of the bundle's content
    statements: Mapping[str, int]  # by evidence-class letter
    profile: str = ""  # assessment bundles: the semantics profile ``<id>@<version>`` (E.3.1)


@dataclass(slots=True)
class DerivationReport:
    """What ``agentprov stats`` reads (AD-10 as ruled): rules fired, statements per (bundle, class, rule), skipped
    references and disclosed gaps.

    ``assessment`` maps each assessment bundle IRI to its counters (E.7.3): what was materialised (``labels``,
    ``payload_present``, ``payload_ambiguous``, ``authorship``, ``exposures``, ``taints``) and what was not, by cause:
    ``payload_absent`` and ``payload_gap`` (no statement, E.7.3; the census is the SEM validator's, item 3),
    ``payload_fixture_unresolved``, ``outcome_harness_default`` (C.14.3), ``label_target_without_node``,
    ``exposure_no_request`` (a tool execution without a request part has no generating invocation),
    ``exposure_no_invocation`` (a request not generated by a model call), ``exposure_context_unknown`` (the
    invocation's input is unknown), ``exposure_neutral_request`` and ``exposure_trusted_object`` (pairs not selected,
    item 1), ``premise_annotation_without_statement`` and ``premise_field_unknown`` (a premise field declared unknown,
    not cited; D-930)."""

    rules_fired: dict[str, int] = field(default_factory=dict)
    statements: list[dict[str, Any]] = field(default_factory=list)
    skipped: list[dict[str, str]] = field(default_factory=list)
    disclosed: list[dict[str, str]] = field(default_factory=list)
    communications: dict[str, int] = field(default_factory=dict)
    assessment: dict[str, dict[str, int]] = field(default_factory=dict)

    def as_json(self) -> dict[str, Any]:
        out = {
            "communications": dict(sorted(self.communications.items())),
            "disclosed": self.disclosed,
            "rules_fired": dict(sorted(self.rules_fired.items())),
            "skipped": self.skipped,
            "statements": self.statements,
        }
        if self.assessment:
            out["assessment"] = {k: dict(sorted(v.items())) for k, v in sorted(self.assessment.items())}
        return out


@dataclass(frozen=True, slots=True)
class ProvDerivation:
    prov_json: bytes
    bundles: tuple[BundleInfo, ...]
    digests: Mapping[str, str]
    report: DerivationReport
    document: Mapping[str, Any] = field(repr=False, default_factory=dict)


# ===================================================================================================== context
class Ctx:
    """Everything a rule may ask about the AER, plus the statement store. Rules never classify or name."""

    def __init__(self, doc: AerDocument, spec: ProvSpec, options: ProvOptions, registry: RuleRegistry) -> None:
        self.doc = doc
        self.spec = spec
        self.options = options
        self.registry = registry
        self.header: dict[str, Any] = doc.header
        self.seal: dict[str, Any] = doc.seal
        self.records: list[dict[str, Any]] = doc.records
        self.declared: dict[str, int] = dict(self.header.get("rules", {}))
        self._pos = {str(r.get("id")): i for i, r in enumerate(self.records)}
        self._nodes: dict[str, Stmt] = {}
        self.stmts: list[Stmt] = []
        self._once: set[tuple[Any, ...]] = set()
        self._merged: dict[tuple[Any, ...], Stmt] = {}
        self.report = DerivationReport()
        self._carry: dict[str, tuple[str, tuple[Citation, ...]]] = {}
        self._patch: dict[str, str] = {}
        self._subject_nodes: dict[str, list[str]] = {}
        self._dispatch: dict[str, Attr] = {}
        self._seal_premises: dict[Field, tuple[EvidenceClass, str | None]] = {}
        self.modified_requests: set[str] = set()
        self.scope_actors: set[str] = set()
        self._generated: dict[str, list[str]] = {}
        self._rule_cache: dict[str, Any] = {}
        self._gaps: dict[str, int] = {}

    # ---------------------------------------------------------------------------------- AER queries
    def rec(self, rid: str) -> dict[str, Any] | None:
        return self.doc.get(rid)

    def part(self, pid: str) -> dict[str, Any] | None:
        return self.doc.part(pid)

    def kind(self, rid: str) -> str | None:
        if is_part_id(rid):
            return "part" if self.part(rid) is not None else None
        rec = self.rec(rid)
        return str(rec.get("k")) if rec is not None else None

    def pos(self, rid: str) -> int:
        return self._pos.get(rid.split("#", 1)[0], len(self.records))

    @staticmethod
    def _resolve(value: Any, ptr: str) -> Any:
        if ptr == "":
            return value
        for token in ptr.split("/")[1:]:
            token = token.replace("~1", "/").replace("~0", "~")
            if isinstance(value, dict):
                if token not in value:
                    return _MISSING
                value = value[token]
            elif isinstance(value, list):
                if not (token.isascii() and token.isdigit()) or int(token) >= len(value):
                    return _MISSING
                value = value[int(token)]
            else:
                return _MISSING
        return value

    def unk_reason(self, rid: str, ptr: str) -> str | None:
        """The ``unk`` reason covering ``ptr`` (the pointer itself or an enclosing one), else ``None``."""
        rec = self.rec(rid)
        unk = (rec or {}).get("unk")
        if not isinstance(unk, dict):
            return None
        best: tuple[int, str] | None = None
        for key, reason in unk.items():
            if isinstance(key, str) and is_prefix(key, ptr) and (best is None or len(key) > best[0]):
                best = (len(key), str(reason))
        return best[1] if best else None

    def present(self, rid: str | None, ptr: str) -> bool:
        """The value at ``ptr`` exists and is not declared unknown (E.1.5 item 1)."""
        if rid is None:
            return False
        rec = self.rec(rid)
        if rec is None:
            return False
        if self._resolve(rec, ptr) is _MISSING:
            return False
        return self.unk_reason(rid, ptr) is None

    def val(self, rid: str, ptr: str) -> Any:
        rec = self.rec(rid)
        value = self._resolve(rec, ptr) if rec is not None else _MISSING
        if value is _MISSING:
            raise ProvDerivationError(f"{rid}{ptr} does not resolve", code="prov.unresolved_pointer")
        return value

    def seal_premise(self, f: Field) -> tuple[EvidenceClass, str | None] | None:
        """A seal issue premise's class (its rule's) and rule id; ``None`` for a record field."""
        return self._seal_premises.get(f)

    def field_class(self, f: Field) -> EvidenceClass:
        seal = self.seal_premise(f)
        if seal is not None:
            return seal[0]
        rec = self.rec(f.rid)
        if rec is None:
            raise ProvDerivationError(f"premise {f.rid} is not a record", code="prov.unresolved_reference")
        return cls(rec, f.ptr)

    def rule_entry(self, rule_id: str) -> Any:
        if rule_id not in self._rule_cache:
            self._rule_cache[rule_id] = self.registry.lookup(rule_id, self.declared)
        return self._rule_cache[rule_id]

    def rule_class(self, rule_id: str) -> EvidenceClass:
        entry = self.rule_entry(rule_id)
        if entry is None:
            raise ProvDerivationError(f"rule {rule_id} is not in a declared catalogue", code="prov.rule_unknown")
        return LETTER[entry.cls]

    def citing_assumption(self, rid: str, assumption: str) -> tuple[Citation, ...]:
        """The rules cited by record ``rid`` whose catalogue entry declares ``assumption`` (F.1.5), each with the field
        that cites it: the scoped pointer, or the record itself for an unscoped citation or one scoped to an unknown
        (whose pointer does not resolve). A statement that rests on the
        assumption takes that field as a premise, so it is named in ``apv:sourcePointer`` and ``apv:basisRule``."""
        rec = self.rec(rid)
        found: dict[tuple[str, str], Citation] = {}
        for ref in (rec or {}).get("rule", ()):
            entry = self.rule_entry(rule_id_of(str(ref)))
            if entry is not None and assumption in entry.assumptions:
                pointer = str(ref).partition("#")[2]
                if pointer and not self.present(rid, pointer):  # a citation justifying an unknown: cite the record
                    pointer = ""
                found[(entry.rule_id, pointer)] = Citation(entry.rule_id, Field(rid, pointer))
        return tuple(found[k] for k in sorted(found))

    # ---------------------------------------------------------------------------------- prepass data
    def prepass(self) -> None:
        for record in self.records:
            rid, kind = str(record.get("id")), record.get("k")
            if kind == "scope" and self.present(rid, "/actor"):
                self.scope_actors.add(str(record["actor"]))
            elif kind == "message" and self.present(rid, "/generated_by"):
                self._generated.setdefault(str(record["generated_by"]), []).append(rid)
            elif kind == "decision" and self.present(rid, "/subject") and self.present(rid, "/verdict"):
                subject, verdict = str(record["subject"]), record["verdict"]
                if verdict == "modify" and is_part_id(subject):
                    self.modified_requests.add(subject)
                if verdict == "deny" and (self.part(subject) or {}).get("t") == "tool_call":
                    fields = (Field(rid, "/subject"), Field(rid, "/verdict"))
                    self._dispatch[subject] = Attr("apv:dispatchStatus", q("apv:Denied"), fields, rule="aprov.n_part@1")
        for i, issue in enumerate(self.seal.get("issues", [])):
            if not isinstance(issue, dict) or issue.get("code") != "unexecuted_tool_call":
                continue
            rule = rule_id_of(str(issue.get("rule", "")))
            known = self.rule_entry(rule) is not None
            ceiling = self.rule_class(rule) if known else D
            premise = Field(SEAL, f"/issues/{i}")  # the declaration is the premise: an I one is pointed at (E.1.5 item 6)
            self._seal_premises[premise] = (ceiling, rule if known else None)
            for pid in issue.get("ids", []):
                if isinstance(pid, str) and pid not in self._dispatch:
                    self._dispatch[pid] = Attr("apv:dispatchStatus", q("apv:NotDispatched"), (premise,),
                                               rule="aprov.n_part@1", ceiling=ceiling, cited=(rule,) if known else ())

    def dispatch_status(self, pid: str) -> Attr | None:
        return self._dispatch.get(pid)

    def generated_messages(self, activity: str) -> list[str]:
        return list(self._generated.get(activity, ()))

    def call_args(self, te: str) -> Any:
        if not self.present(te, "/call"):
            return None
        call = str(self.val(te, "/call"))
        mid, _, k = call.partition("#")
        return self.val(mid, f"/parts/{k}/args") if self.present(mid, f"/parts/{k}/args") else None

    def set_carry(self, sc: str, pred: str, refs: tuple[Citation, ...]) -> None:
        self._carry[sc] = (pred, refs)

    def carry(self, sc: str) -> tuple[str, tuple[Citation, ...]] | None:
        return self._carry.get(sc)

    def carried_over(self, sc: str) -> bool:
        return sc in self._carry

    def set_patch_pred(self, sc: str, pred: str) -> None:
        self._patch[sc] = pred

    def patch_pred(self, sc: str) -> str | None:
        return self._patch.get(sc)

    def current_state(self, sc: str) -> str | None:
        """The state entity a state change denotes: its ``.after``, else its ``.before``, else its carried-over
        predecessor's (AD-SW5)."""
        base = iri.local(sc)
        for name in (f"{base}.after", f"{base}.before"):
            if name in self._nodes:
                return name
        carry = self._carry.get(sc)
        return self.current_state(carry[0]) if carry else None

    def first_state(self) -> tuple[str, str] | None:
        for record in self.records:
            if record.get("k") == "state_change":
                sc = str(record["id"])
                name = f"{iri.local(sc)}.before"
                if self.present(sc, "/before_sha256") and name in self._nodes:
                    return sc, name
        return None

    def register_subject_node(self, dc: str, name: str) -> None:
        self._subject_nodes.setdefault(dc, []).append(name)

    def subject_node(self, dc: str) -> str | None:
        names = self._subject_nodes.get(dc)
        return names[0] if names else None

    def decision_subject_nodes(self, dc: str) -> list[Stmt]:
        return [self._nodes[n] for n in self._subject_nodes.get(dc, ()) if n in self._nodes]

    def last_message(self, scope: str) -> str | None:
        """The message of ``scope`` with the largest ordinal (message ids follow source position, C.4.2)."""
        best: tuple[int, int, str] | None = None
        for record in self.records:
            if record.get("k") == "message" and record.get("scope") == scope:
                rid = str(record["id"])
                digits = rid[1:] if rid.startswith("m") and rid[1:].isascii() and rid[1:].isdigit() else ""
                key = (int(digits) if digits else -1, self.pos(rid), rid)
                if best is None or key > best:
                    best = key
        return best[2] if best else None

    def checker_targets(self, assumption: str) -> list[tuple[str, list[Field], str]]:
        scored = [str(r["id"]) for r in self.records
                  if r.get("k") == "scope" and r.get("scored") is True and self.present(str(r["id"]), "/scored")]
        out: list[tuple[str, list[Field], str]] = []
        if assumption == "apv:CheckerUsesOutput":
            for att in scored:
                msgs = [str(r["id"]) for r in self.records if r.get("k") == "message" and r.get("scope") == att
                        and r.get("role") == "assistant"]
                if msgs:
                    last = max(msgs, key=lambda m: (int(m[1:]) if m[1:].isascii() and m[1:].isdigit() else -1, self.pos(m)))
                    out.append((iri.local(last), [Field(att, "/scored")], "apv:CheckedOutput"))
        elif assumption == "apv:CheckerUsesPreState":
            first = self.first_state()
            if first:
                out.append((first[1], [Field(first[0], "/before_sha256")], "apv:CheckedPreState"))
        elif assumption == "apv:CheckerUsesPostState":
            changes = [str(r["id"]) for r in self.records if r.get("k") == "state_change"]
            for sc in reversed(changes):
                state = self.current_state(sc)
                if state:
                    out.append((state, [Field(sc, "")], "apv:CheckedState"))
                    break
        elif assumption == "apv:CheckerUsesCallTrace":
            for att in scored:
                for r in self.records:
                    if r.get("k") == "message" and r.get("scope") == att:
                        for k, part in enumerate(r.get("parts", [])):
                            if isinstance(part, dict) and part.get("t") == "tool_call":
                                out.append((f"{iri.local(str(r['id']))}-{k}",
                                            [Field(att, "/scored"), Field(str(r["id"]), f"/parts/{k}")],
                                            "apv:CheckedCallTrace"))
        return out

    def refuse_generic_misuse(self, rid: str, record: Mapping[str, Any]) -> None:
        """NE-21: a generic ``activity`` (``artefact``) whose type names an occurrence (content) that a specialised
        kind represents is refused with a typed failure."""
        kind_type = record.get("type")
        name = kind_type.split(":", 1)[1] if isinstance(kind_type, str) and ":" in kind_type else ""
        names = SPECIALISED_KIND_NAMES if record.get("k") == "activity" else SPECIALISED_CONTENT_NAMES
        if name in names:
            raise ProvDerivationError(
                f"activity {rid} has type {kind_type!r}, which a specialised kind represents (NE-21)",
                code="prov.generic_kind_misuse",
            )

    # ---------------------------------------------------------------------------------- reporting
    def skipped(self, rid: str, ptr: str, why: str) -> None:
        self.report.skipped.append({"pointer": f"{rid}{ptr}", "reason": why})

    def disclose(self, code: str, rid: str, detail: str) -> None:
        self.report.disclosed.append({"code": code, "id": rid, "detail": detail})

    # ---------------------------------------------------------------------------------- statement store
    def node(self, name: str) -> Stmt | None:
        return self._nodes.get(name)

    def add_node(
        self,
        name: str,
        section: str,
        rule: str,
        types: Sequence[str],
        rid: str | None,
        attrs: Sequence[Attr] = (),
        *,
        fields: Sequence[Field] | None = None,
        nodes: Sequence[str] = (),
        path: str | None = None,
    ) -> Stmt:
        if name in self._nodes:
            raise ProvDerivationError(f"node {name} declared twice", code="prov.statement_collision")
        prule = self.spec.rule(rule)
        stmt = Stmt(
            rule=rule,
            section=section,
            args={},
            attrs=[*(Attr("prov:type", q(t)) for t in types), *attrs],
            fields=list(fields) if fields is not None else ([Field(rid, "")] if rid is not None else []),
            nodes=list(nodes),
            ceiling=prule.cap(path),
            assumptions=prule.assumptions_by_path.get(path or "", ()),
            name=name,
        )
        self._nodes[name] = stmt
        self.stmts.append(stmt)
        return stmt

    def add_gap(self, about: str, rid: str, ptr: str, status: str, *, rule: str = "aprov.n_gap@1") -> None:
        """An ``apv:Gap`` entity ``x:<about>.gap-<n>`` (``n`` counts the gaps of that node, E.1.2)."""
        self._gaps[about] = self._gaps.get(about, -1) + 1
        name = f"{about}.gap-{self._gaps[about]}"
        attrs = [
            Attr("apv:about", q("x:" + about)),
            Attr("apv:property", ptr),
            Attr("apv:status", q(status)),
        ]
        prule = self.spec.rule("aprov.n_gap@1")
        gap = self.add_node(name, "entity", "aprov.n_gap@1", ["apv:Gap"], rid, attrs)
        gap.ceiling = prule.ceiling
        if rule != "aprov.n_gap@1":
            gap.attrs.append(Attr("apv:reason", rule))
        self.report.disclosed.append({"code": "gap", "id": f"{rid}{ptr}", "detail": status})

    def rel(
        self,
        section: str,
        rule: str,
        args: Mapping[str, str],
        attrs: Sequence[Attr] = (),
        *,
        fields: Sequence[Field] = (),
        path: str | None = None,
        disc: str = "",
        cited: Sequence[str | Citation] = (),
        once: bool = False,
        merge: bool = False,
    ) -> Stmt | None:
        """Add a relation. ``once`` keeps only the first statement per (rule, section, arguments). ``merge`` states a
        fact that several records support once: a repeat on the same path, with the same attributes and discriminator,
        adds its fields and citations to the first statement (regen item 165) instead of colliding with it
        (``prov.statement_collision``)."""
        missing = [v for v in args.values() if v not in self._nodes]
        if missing:
            self.skipped(fields[0].rid if fields else "-", fields[0].ptr if fields else "", f"{rule}: endpoint without a node")
            return None
        key = (rule, section, tuple(sorted(args.items())))
        if once:
            if key in self._once:
                return None
            self._once.add(key)
        mkey = (*key, path, disc)
        first = self._merged.get(mkey) if merge else None
        if first is not None and first.attrs == list(attrs):
            first.fields = list(dict.fromkeys([*first.fields, *fields, *(c.field for c in cited if isinstance(c, Citation))]))
            first.cited = tuple(sorted({*first.cited, *(c.rule if isinstance(c, Citation) else c for c in cited)}))
            return first
        prule = self.spec.rule(rule)
        stmt = Stmt(
            rule=rule,
            section=section,
            args={k: "x:" + v for k, v in args.items()},
            attrs=list(attrs),
            fields=list(dict.fromkeys([*fields, *(c.field for c in cited if isinstance(c, Citation))])),
            nodes=list(args.values()),
            ceiling=prule.cap(path),
            assumptions=prule.assumptions_by_path.get(path or "", ()),
            cited=tuple(sorted({c.rule if isinstance(c, Citation) else c for c in cited})),
            disc=disc,
        )
        self.stmts.append(stmt)
        if merge:
            self._merged.setdefault(mkey, stmt)
        return stmt


# ===================================================================================================== classification
def _node_refs(value: Any) -> list[str]:
    """The node local names an attribute value names: ``x:<local>`` QNames, alone or in a list."""
    items = value if isinstance(value, list) else [value]
    return [str(v["$"])[2:] for v in items
            if isinstance(v, dict) and v.get("type") == "prov:QUALIFIED_NAME" and str(v.get("$", "")).startswith("x:")]


class _Classifier:
    def __init__(self, ctx: Ctx) -> None:
        self.ctx = ctx
        self._field_methods: dict[Field, frozenset[str]] = {}

    def methods_of_field(self, f: Field) -> frozenset[str]:
        if f in self._field_methods:
            return self._field_methods[f]
        seal = self.ctx.seal_premise(f)
        if seal is not None:
            if seal[1] is None:
                raise ProvDerivationError(f"INFERRED premise {f.rid}{f.ptr} cites no I-class rule", code="prov.method_set_empty")
            self._field_methods[f] = frozenset({seal[1]})
            return self._field_methods[f]
        rec = self.ctx.rec(f.rid) or {}
        found = {rule_id_of(r) for r in applicable_refs(rec, f.ptr) if self._is_inferred_rule(rule_id_of(r))}
        if not found:  # an I tag that arises by propagation: the record cites the assumption elsewhere (C.6.4)
            found = {rule_id_of(str(r)) for r in rec.get("rule", ()) if self._is_inferred_rule(rule_id_of(str(r)))}
        if not found:
            raise ProvDerivationError(f"INFERRED field {f.rid}{f.ptr} cites no I-class rule", code="prov.method_set_empty")
        self._field_methods[f] = frozenset(found)
        return self._field_methods[f]

    def _is_inferred_rule(self, rule_id: str) -> bool:
        entry = self.ctx.rule_entry(rule_id)
        return entry is not None and entry.cls == "I"

    def _combine(self, parts: list[tuple[EvidenceClass, frozenset[str]]]) -> tuple[EvidenceClass, frozenset[str]]:
        c = min(p[0] for p in parts)
        methods: set[str] = set()
        if c == I:
            for pc, pm in parts:
                if pc == I:
                    methods |= pm
            if not methods:
                raise ProvDerivationError("an INFERRED statement with an empty method set", code="prov.method_set_empty")
        return c, frozenset(methods)

    def _premises(self, fields: Sequence[Field], cited: Sequence[str]) -> list[tuple[EvidenceClass, frozenset[str]]]:
        parts: list[tuple[EvidenceClass, frozenset[str]]] = []
        for f in fields:
            c = self.ctx.field_class(f)
            parts.append((c, self.methods_of_field(f) if c == I else frozenset()))
        for rule in cited:
            c = self.ctx.rule_class(rule)
            parts.append((c, frozenset({rule}) if c == I else frozenset()))
        return parts

    def stmt(self, s: Stmt) -> None:
        if s.cls is not None:
            return
        parts = [(s.ceiling, frozenset({s.rule}) if s.ceiling == I else frozenset())]
        parts += self._premises(s.fields, s.cited)
        parts += s.sem
        for name in s.nodes:
            node = self.ctx.node(name)
            if node is None:
                raise ProvDerivationError(f"{s.rule}: node {name} is not declared", code="prov.unresolved_reference")
            self.stmt(node)
            assert node.cls is not None
            parts.append((node.cls, node.methods))
        for p in s.prem:
            self.stmt(p)
            assert p.cls is not None
            parts.append((p.cls, p.methods))
        s.cls, s.methods = self._combine(parts)
        for a in s.attrs:
            if a.fields or a.cited:
                a.cls, a.methods = self._combine([(a.ceiling, frozenset()), *self._premises(a.fields, a.cited)])
            else:
                a.cls = min(a.ceiling, s.cls)
                a.methods = s.methods if a.cls == I and s.cls == I else frozenset()
                if a.cls == I and not a.methods:
                    a.methods = frozenset({a.rule or s.rule})

    def cap_references(self, s: Stmt) -> None:
        """C.6.5 rule 4 for attributes, as routing needs it: an attribute naming an INFERRED node (an ``x:`` QName such as
        ``apv:partOf`` or ``apv:afterCausal``) is INFERRED, so a reference into an inference bundle is routed out of a
        stronger element (E.1.5 item 5) instead of naming, from the core, a node the core does not hold. Runs after every
        statement is classified (node classes are final; no recursion). An attribute naming an O or D node is left as it
        is (the D cap would only change the ``apv:derivedAttribute`` list, never the routing)."""
        for a in s.attrs:
            assert a.cls is not None
            for name in _node_refs(a.value):
                node = self.ctx.node(name)
                if a.cls > I and node is not None and node.cls == I:
                    a.cls, a.methods = self._combine([(a.cls, a.methods), (node.cls, node.methods)])


# ===================================================================================================== derive
def derive(
    aer: AerDocument,
    sems: Sequence[Any] = (),
    *,
    spec: ProvSpec | None = None,
    options: ProvOptions | None = None,
    registry: RuleRegistry | None = None,
    check_aer: bool = True,
    sem_profiles: Mapping[tuple[str, int], SemanticsProfile] | None = None,
) -> ProvDerivation:
    """Derive the canonical bundled PROV-JSON of one sealed AER execution (E.0.1).

    ``check_aer`` runs the AER validator (tier 2, without raw-store checks) and refuses an invalid AER (E.0.1 item 4);
    callers that have just validated the file with the store may pass ``False``.

    ``sems`` are sealed SEM documents of this AER (C.14), validated by the caller (tier 3); each gives one assessment
    bundle (E.7). ``sem_profiles`` maps ``(profile id, version)`` to the semantics profile of each document; the engine
    reads only its identity, ``sha256`` and ``taint_policy``. The engine never discovers profiles itself (adapter
    families are a higher layer, MN M.5.1). Refusals: ``prov.sem_stale`` (another AER or digest),
    ``prov.sem_profile_missing``, ``prov.sem_profile_mismatch``, ``prov.sem_duplicate_profile`` (two documents of one
    profile) and ``prov.sem_invalid`` (a malformed document). The SEM rule catalogues named by a document's header are
    looked up in ``registry`` too.
    """
    from agentprov.prov.rules import edges, nodes, top

    spec = spec or load_spec()
    options = options or ProvOptions()
    registry = registry or RuleRegistry.default()
    if options.context_encoding != "members":
        raise ProvDerivationError("only the members context encoding exists in v0.1", code="prov.unsupported_option")
    sem_inputs = _sem_inputs(aer, sems, sem_profiles or {})
    if check_aer:
        result = validate_records([*aer.records, aer.seal], store=None, catalogues=registry, mode="dev")
        if not result.ok:
            codes = ", ".join(sorted({f.code for f in result.errors}))
            raise ProvDerivationError(f"the AER does not pass the validator ({codes})", code="prov.aer_invalid")
    try:
        ctx = Ctx(aer, spec, options, registry)
        ctx.prepass()
        edges.state_predecessors(ctx)
        nodes.apply(ctx)
        nodes.model_services(ctx)
        nodes.scope_parents(ctx)
        nodes.message_scopes(ctx)
        nodes.capture_profile(ctx)
        edges.decision_nodes(ctx)
        edges.apply(ctx)
        edges.after_attributes(ctx)
        nodes.statuses(ctx)
        return _assemble(ctx, top, sem_inputs)
    except ProvDerivationError:
        raise
    except (KeyError, TypeError, ValueError, AttributeError, IndexError) as exc:  # totality (E.0.1 item 5)
        raise ProvDerivationError(f"unexpected AER shape: {type(exc).__name__}", code="prov.unexpected_input") from exc


def _sem_inputs(aer: AerDocument, sems: Sequence[SemDocument],
                profiles: Mapping[tuple[str, int], SemanticsProfile]) -> list[tuple[SemDocument, SemanticsProfile]]:
    """Check each SEM document against the AER and pair it with its profile, in (profile id, version) order."""
    out: dict[tuple[str, int], tuple[SemDocument, SemanticsProfile]] = {}
    for sem in sems:
        try:
            ex, digest, key = sem.ex, sem.aer_digest, (sem.profile_id, sem.profile_version)
            version = sem.header.get("sem")
            str(sem.digest)
        except (AttributeError, KeyError, TypeError, ValueError) as exc:
            raise ProvDerivationError("a SEM document without a readable header", code="prov.sem_invalid") from exc
        if version != "0.1" or not isinstance(sem.records, list) or not sem.records:
            raise ProvDerivationError("not a sem/0.1 document", code="prov.sem_invalid")
        if ex != aer.ex or digest != str(aer.seal.get("records_sha256")):
            raise ProvDerivationError(f"a SEM document of {key[0]}@{key[1]} was computed from another AER",
                                      code="prov.sem_stale")
        if key in out:
            raise ProvDerivationError(f"two SEM documents of {key[0]}@{key[1]}", code="prov.sem_duplicate_profile")
        profile = profiles.get(key)
        if profile is None:
            raise ProvDerivationError(f"no semantics profile {key[0]}@{key[1]} was supplied",
                                      code="prov.sem_profile_missing")
        if (profile.id, profile.version) != key:
            raise ProvDerivationError(f"the profile supplied for {key[0]}@{key[1]} is {profile.id}@{profile.version}",
                                      code="prov.sem_profile_mismatch")
        out[key] = (sem, profile)
    return [out[k] for k in sorted(out)]


@dataclass(slots=True)
class _Split:
    """INFERRED attributes routed out of a stronger element (E.1.5 item 5)."""

    target: Stmt
    rule: str
    methods: frozenset[str]
    attrs: list[Attr]


def _assemble(ctx: Ctx, top: Any, sem_inputs: Sequence[tuple[SemDocument, SemanticsProfile]] = ()) -> ProvDerivation:
    classifier = _Classifier(ctx)
    for s in ctx.stmts:
        classifier.stmt(s)
    for s in ctx.stmts:
        classifier.cap_references(s)
    # routing (E.1.5 item 4) and the attribute evidence rule (item 5)
    splits: dict[tuple[int, str, frozenset[str]], _Split] = {}
    kept: dict[int, list[Attr]] = {}
    derived_attrs: dict[int, set[str]] = {}
    for s in ctx.stmts:
        assert s.cls is not None
        s.bundle = CORE if s.cls >= D else ("inf", s.methods)
        keep: list[Attr] = []
        after_classes: list[EvidenceClass] = []
        for a in s.attrs:
            assert a.cls is not None
            if a.cls == I and s.cls > I:
                key = (id(s), a.rule or s.rule, a.methods)
                splits.setdefault(key, _Split(s, a.rule or s.rule, a.methods, [])).attrs.append(a)
                continue
            keep.append(a)
            if a.rule == "aprov.after@1":
                after_classes.append(a.cls)
            if a.cls == D and s.cls == O:
                derived_attrs.setdefault(id(s), set()).add(a.prop)
        if after_classes:
            weakest_after = min(after_classes)
            keep.append(Attr("apv:afterEvidenceClass", q(weakest_after.qname), rule="aprov.after@1", cls=weakest_after))
            if weakest_after == D and s.cls == O:
                derived_attrs.setdefault(id(s), set()).add("apv:afterEvidenceClass")
        kept[id(s)] = keep
    comms = _closure(ctx)
    # bundles and derivation keys (E.3.4)
    keys: set[tuple[str, frozenset[str]]] = {CORE}
    keys |= {s.bundle for s in [*ctx.stmts, *comms] if s.bundle is not None}
    keys |= {("inf", sp.methods) for sp in splits.values()}
    aer_digest = str(ctx.seal.get("records_sha256", ""))
    options = ctx.options.as_json()
    dks: dict[tuple[str, frozenset[str]], str] = {}
    for bkey in sorted(keys, key=lambda k: (k[0] != "core", sorted(k[1]))):
        kind = "core" if bkey[0] == "core" else "inference"
        dks[bkey] = iri.derivation_key(
            spec_id=ctx.spec.id,
            catalogue_sha256=ctx.spec.catalogue_sha256,
            aer_digest=aer_digest,
            sem_digest=None,
            kind=kind,
            key=iri.method_slug(bkey[1]) if bkey[1] else None,
            options=options,
        )
    bundle_iri = {k: (f"xd:bundle.core.{dks[k]}" if k[0] == "core" else f"xd:bundle.inf.{iri.method_slug(k[1])}.{dks[k]}")
                  for k in dks}
    # statement names (E.4.2), with discriminators only where (rule, arguments) repeat within a bundle
    relations = [s for s in [*ctx.stmts, *comms] if not s.is_node]
    groups: dict[tuple[Any, ...], list[Stmt]] = {}
    for s in relations:
        argv = tuple(s.args.get(k, "-") for k in ARG_ORDER[s.section])
        groups.setdefault((s.bundle, s.rule, s.section, argv), []).append(s)
    for (bkey, rule, _section, argv), members in groups.items():
        discs = [m.disc if len(members) > 1 else "" for m in members]
        if len(set(discs)) != len(discs):
            raise ProvDerivationError(f"statement collision under {rule}", code="prov.statement_collision")
        for m, disc in zip(members, discs, strict=True):
            m.name = iri.statement_name(dks[bkey], rule, argv, disc)
    # split-out mentions and assessments (named with their inference bundle's dk)
    extra: list[tuple[tuple[str, frozenset[str]], str, dict[str, Any], str]] = []
    core_iri = bundle_iri[CORE]
    for (_, rule, methods), sp in sorted(splits.items(), key=lambda kv: (kv[1].target.name or "", kv[0][1], sorted(kv[0][2]))):
        bkey = ("inf", methods)
        dk = dks[bkey]
        target = sp.target
        body = _attr_block(sp.attrs)
        evidence = _evidence(ctx, Stmt(rule=rule, section="entity", args={}, fields=[f for a in sp.attrs for f in a.fields],
                                       cited=tuple(c for a in sp.attrs for c in a.cited), cls=I, methods=methods))
        if target.is_node and target.section == "entity":
            name = f"{target.name}.mn-{iri.h(dk + chr(10) + rule, 12)}"
            body.update(evidence)
            extra.append((bkey, "entity", body, name))
            mention = {"prov:specificEntity": "x:" + name, "prov:generalEntity": "x:" + str(target.name), "prov:bundle": core_iri}
            mname = "_:" + iri.statement_name(dk, rule, [mention[k] for k in ARG_ORDER["mentionOf"]])
            extra.append((bkey, "mentionOf", mention, mname))
        else:
            subject = "x:" + str(target.name)
            claim = ("apv:OrderedAfter" if rule == "aprov.after@1" else
                     "apv:SentTransformed" if rule == "aprov.a_sent_transform@1" else "apv:Labelled")
            name = "as-" + iri.h("\n".join([dk, rule, subject, "-", claim]), 16)
            body.update(evidence)
            body["prov:type"] = q("apv:Assessment")
            body["apv:claim"] = q(claim)
            body["apv:subject"] = q(subject)
            body["apv:premise"] = q(subject)  # the element whose attribute the assessment carries (E.1.5 item 6)
            extra.append((bkey, "entity", body, name))
    # the bundles
    content: dict[tuple[str, frozenset[str]], dict[str, dict[str, Any]]] = {k: {} for k in dks}
    for s in [*ctx.stmts, *comms]:
        assert s.bundle is not None
        section = content[s.bundle].setdefault(s.section, {})
        body = _attr_block(kept.get(id(s), s.attrs))
        if not s.is_node:
            body.update(s.args)
        body.update(_evidence(ctx, s))
        if derived_attrs.get(id(s)):
            body["apv:derivedAttribute"] = _multi([q(p) for p in derived_attrs[id(s)]])
        if s.prem:
            body["apv:premise"] = _multi([q("x:" + str(p.name)) for p in s.prem])
        if s.section in UNIDENTIFIED:
            body = {k: v for k, v in body.items() if k.startswith("prov:") and k in ARG_ORDER[s.section]}
            name = "_:" + str(s.name)
        else:
            name = "x:" + str(s.name)
        if name in section:
            raise ProvDerivationError(f"duplicate identifier {name}", code="prov.statement_collision")
        section[name] = body
    for ekey, section_name, ebody, name in extra:
        ident = name if name.startswith("_:") else "x:" + name
        content[ekey].setdefault(section_name, {})[ident] = ebody
    # assessment bundles (E.7), one per SEM document, after the statements they cite are classified and named
    assessed = _assessments(ctx, classifier, sem_inputs, bundle_iri, aer_digest, options)
    # report
    report = ctx.report
    counts: Counter[tuple[str, str, str, str]] = Counter()
    for s in [*ctx.stmts, *comms]:
        assert s.bundle is not None and s.cls is not None
        counts[(s.bundle[0], iri.method_slug(s.bundle[1]), s.cls.letter, s.rule)] += 1
        report.rules_fired[s.rule] = report.rules_fired.get(s.rule, 0) + 1
    report.statements = [{"bundle": b, "methods": m, "class": c, "rule": r, "count": n}
                         for (b, m, c, r), n in sorted(counts.items())]
    report.communications = {"core": sum(1 for c in comms if c.bundle == CORE),
                             "inference": sum(1 for c in comms if c.bundle != CORE)}
    for info, result, _ in assessed:
        for (rule, letter), n in sorted(result.rules.items()):
            report.rules_fired[rule] = report.rules_fired.get(rule, 0) + n
            report.statements.append({"bundle": "assessment", "methods": info.profile, "class": letter, "rule": rule,
                                      "count": n})
        report.assessment[info.iri] = result.counts
    bundles = []
    bundle_docs: dict[str, dict[str, Any]] = {}
    for bkey in sorted(dks, key=lambda k: (k[0] != "core", sorted(k[1]))):
        doc = content[bkey]
        bundle_docs[bundle_iri[bkey]] = doc
        letters: Counter[str] = Counter()
        for s in [*ctx.stmts, *comms]:
            if s.bundle == bkey and s.cls is not None:
                letters[s.cls.letter] += 1
        letters["I"] += sum(1 for k, section, _, _ in extra if k == bkey and section == "entity")
        letters = Counter({k: v for k, v in letters.items() if v})
        bundles.append(BundleInfo(
            iri=bundle_iri[bkey],
            kind="core" if bkey[0] == "core" else "inference",
            methods=tuple(sorted(bkey[1])),
            derivation_key=dks[bkey],
            digest="sha256:" + sha256_hex(jcs_bytes(doc)),
            statements=dict(sorted(letters.items())),
        ))
    for info, result, _ in assessed:
        bundle_docs[info.iri] = result.content
        bundles.append(info)
    document: dict[str, Any] = {"prefix": iri.prefixes_for(ctx.doc.ex)}
    document.update(top.build(ctx, bundles, dks[CORE], [(sem, profile, info) for info, _, (sem, profile) in assessed]))
    document["bundle"] = bundle_docs
    data = jcs_bytes(document)
    return ProvDerivation(
        prov_json=data,
        bundles=tuple(bundles),
        digests={"prov_json": "sha256:" + sha256_hex(data)},
        report=report,
        document=document,
    )


def _assessments(
    ctx: Ctx,
    classifier: _Classifier,
    sem_inputs: Sequence[tuple[SemDocument, SemanticsProfile]],
    bundle_iri: Mapping[tuple[str, frozenset[str]], str],
    aer_digest: str,
    options: Mapping[str, Any],
) -> list[tuple[BundleInfo, Any, tuple[SemDocument, SemanticsProfile]]]:
    """One assessment bundle per SEM document: ``xd:bundle.assess.<profile-slug>.<dk>`` with ``dk`` over the SEM digest
    and the profile (E.3.4, E.7.2)."""
    if not sem_inputs:
        return []
    from agentprov.prov.rules import assess

    node_bundles = {str(s.name): bundle_iri[s.bundle] for s in ctx.stmts if s.is_node and s.bundle is not None}
    out = []
    for sem, profile in sem_inputs:
        slug = iri.profile_slug(profile.id, profile.version)
        dk = iri.derivation_key(spec_id=ctx.spec.id, catalogue_sha256=ctx.spec.catalogue_sha256, aer_digest=aer_digest,
                                sem_digest=str(sem.digest), kind="assessment", key=slug, options=options)
        biri = f"xd:bundle.assess.{slug}.{dk}"
        result = assess.build(ctx, classifier, sem, profile, dk=dk, bundle_iri=biri, node_bundles=node_bundles,
                              registry=ctx.registry)
        info = BundleInfo(iri=biri, kind="assessment", methods=(), derivation_key=dk,
                          digest="sha256:" + sha256_hex(jcs_bytes(result.content)),
                          statements=dict(sorted(result.classes.items())), profile=f"{profile.id}@{profile.version}")
        out.append((info, result, (sem, profile)))
    return out


def _multi(values: list[Any]) -> Any:
    """A multi-valued attribute: unique values sorted by their JCS bytes; one value is a scalar (E.5.3 item 4)."""
    unique = {jcs_bytes(v): v for v in values}
    ordered = [unique[k] for k in sorted(unique)]
    return ordered[0] if len(ordered) == 1 else ordered


def _attr_block(attrs: Sequence[Attr]) -> dict[str, Any]:
    grouped: dict[str, list[Any]] = {}
    for a in attrs:
        grouped.setdefault(a.prop, []).append(a.value)
    return {prop: _multi(values) for prop, values in grouped.items()}


def assumption_attrs(names: Iterable[str]) -> dict[str, Any]:
    """``apv:assumption`` (core ``apv:`` individuals, QNames) and ``apv:adapterAssumption`` (adapter-declared
    ``<ns>:<Name>`` terms, strings: documents declare no adapter prefixes) for a set of assumption names (E.1.5 item 6,
    E.10 item 11; apv 0.2.0, D-501). Empty when there are none."""
    core = sorted({n for n in names if n.startswith("apv:")})
    adapter = sorted({n for n in names if not n.startswith("apv:")})
    out: dict[str, Any] = {}
    if core:
        out["apv:assumption"] = _multi([q(n) for n in core])
    if adapter:
        out["apv:adapterAssumption"] = _multi(adapter)
    return out


def _evidence(ctx: Ctx, s: Stmt) -> dict[str, Any]:
    """The evidence attributes of E.1.5 item 6."""
    assert s.cls is not None
    out: dict[str, Any] = {"apv:evidenceClass": q(s.cls.qname), "apv:rule": s.rule}
    pointers: list[tuple[int, str, str]] = []
    basis: set[str] = set(s.cited)
    scoped: set[str] = set()
    parties: set[str] = set()
    for f in s.fields:
        rec = ctx.rec(f.rid) or {}
        pointers.append((ctx.pos(f.rid), f.ptr, f"{f.rid}{f.ptr}"))
        if ctx.seal_premise(f) is not None:
            continue  # a seal issue: its rule is the attribute's citation (``cited``), already in the basis
        c = cls(rec, f.ptr)
        if c == O:
            who = party(rec, f.ptr)
            if who is not None and who in PARTY_QNAME:
                parties.add(PARTY_QNAME[who])
        else:
            for ref in applicable_refs(rec, f.ptr):
                basis.add(rule_id_of(ref))
                if "#" in ref:
                    scoped.add(ref)
    if pointers:
        seen: dict[str, None] = {}
        for _, _, text in sorted(pointers):
            seen.setdefault(text, None)
        out["apv:sourcePointer"] = list(seen) if len(seen) > 1 else next(iter(seen))
    if basis:
        out["apv:basisRule"] = _multi(sorted(basis))
    if scoped:
        out["apv:rulePointer"] = _multi(sorted(scoped))
    if parties:
        out["apv:attestedBy"] = _multi([q(p) for p in parties])
    assumptions: set[str] = set(s.assumptions)
    for rule in basis:
        entry = ctx.rule_entry(rule)
        if entry is not None:
            assumptions.update(entry.assumptions)
    out.update(assumption_attrs(assumptions))
    if s.cls == I:
        out["apv:method"] = _multi(sorted(s.methods))
    return out


# ===================================================================================================== Inference 6
def _closure(ctx: Ctx) -> list[Stmt]:
    """``aprov.comm@1``: exactly the Inference-6 closure over named activities, per routing scope (E.1.6)."""
    gens: dict[str, list[Stmt]] = {}
    for s in ctx.stmts:
        if s.section == "wasGeneratedBy":
            gens.setdefault(s.args["prov:entity"], []).append(s)
    witnesses: dict[tuple[str, str], list[tuple[Stmt, Stmt, frozenset[str], EvidenceClass]]] = {}
    for u in ctx.stmts:
        if u.section != "used":
            continue
        a2 = u.args["prov:activity"]
        for g in gens.get(u.args["prov:entity"], ()):
            a1 = g.args["prov:activity"]
            if a1 == a2:
                continue
            assert u.cls is not None and g.cls is not None
            witnesses.setdefault((a2, a1), []).append((u, g, u.methods | g.methods, min(u.cls, g.cls)))
    rule = ctx.spec.rule("aprov.comm@1")
    out: list[Stmt] = []
    core_pairs: set[tuple[str, str]] = set()
    for pair in sorted(witnesses):
        core = [w for w in witnesses[pair] if not w[2]]
        if not core:
            continue
        c = min(max(w[3] for w in core), rule.ceiling)
        chosen = [w for w in core if w[3] >= c]
        out.append(_comm(pair, chosen, c, CORE))
        core_pairs.add(pair)
    occurring = {s.bundle[1] for s in ctx.stmts if s.bundle is not None and s.bundle[0] == "inf"}
    for pair, ws in witnesses.items():
        if pair in core_pairs:
            continue
        sets = {w[2] for w in ws}
        occurring |= {m for m in sets if not any(o < m for o in sets)}
    for methods in sorted(occurring, key=sorted):
        smaller = [o for o in occurring if o < methods]
        for pair in sorted(witnesses):
            if pair in core_pairs:
                continue
            inside = [w for w in witnesses[pair] if w[2] <= methods]
            if not inside or any(any(w[2] <= o for w in witnesses[pair]) for o in smaller):
                continue
            out.append(_comm(pair, inside, I, ("inf", methods)))
    return out


def _comm(pair: tuple[str, str], chosen: list[tuple[Stmt, Stmt, frozenset[str], EvidenceClass]], c: EvidenceClass,
          bundle: tuple[str, frozenset[str]]) -> Stmt:
    a2, a1 = pair
    premises: list[Stmt] = []
    for u, g, _, _ in chosen:
        premises += [u, g]
    entities = sorted({u.args["prov:entity"] for u, _, _, _ in chosen})
    return Stmt(
        rule="aprov.comm@1",
        section="wasInformedBy",
        args={"prov:informed": a2, "prov:informant": a1},
        attrs=[Attr("apv:viaEntity", q(e), cls=c) for e in entities],
        prem=list(dict.fromkeys(premises)),
        ceiling=D,
        cls=c,
        methods=bundle[1],
        bundle=bundle,
    )
